/** Finance-only read models. Decimal values cross the action boundary as strings. */
export interface ReconciliationCatalog {
    items: Array<{
        id: string;
        skuCode: string;
        name: string;
        unit: string;
        archived: boolean;
    }>;
    page: number;
    hasMore: boolean;
}

export interface ReconciliationFinding {
    code: string;
    title: string;
    nextStep: string;
}

export interface InventoryReconciliationDiagnosis {
    variant: ReconciliationCatalog['items'][number];
    checkedAt: string;
    stockValue: string;
    basisTotal: string;
    difference: string;
    healthFlagged: boolean;
    locations: Array<{
        id: string;
        name: string;
        quantity: string;
        averageCost: string | null;
        value: string;
        companyInternal: boolean;
    }>;
    basis: Array<{
        accountId: string;
        code: string;
        name: string;
        value: string;
    }>;
    findings: ReconciliationFinding[];
    movements: Array<{
        id: string;
        type: string;
        quantity: string;
        cost: string | null;
        createdAt: string;
        from: string | null;
        to: string | null;
        receiptNumber: string | null;
    }>;
    journals: Array<{
        id: string;
        number: string;
        movementId: string;
        date: string;
        status: string;
        referenceType: string | null;
        autoGenerated: boolean;
        linesTruncated: boolean;
        lines: Array<{
            accountCode: string;
            accountName: string;
            debit: string;
            credit: string;
            currency: string;
        }>;
    }>;
    coverage: {
        movementCount: number;
        movementsTruncated: boolean;
        journalsTruncated: boolean;
    };
}
