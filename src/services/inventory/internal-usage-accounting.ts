import { Prisma } from '@prisma/client';
import { getMainPrisma, getTenantIdFromContext } from '@/lib/core/prisma';
import { BusinessRuleError } from '@/lib/errors/errors';
import { resolveAccountCode } from '@/services/accounting/account-mapping-policy';

/** Explicit Finance choice only: do not turn a missing mapping into an inferred expense. */
export async function resolveInternalUsageAccounts(
    inventoryOverride: string | null,
) {
    const tenantId = getTenantIdFromContext();
    if (!tenantId)
        throw new BusinessRuleError(
            'Tenant pemakaian internal tidak dapat diverifikasi.',
        );
    const mapping = await getMainPrisma().tenantAccountRole.findUnique({
        where: { tenantId_role: { tenantId, role: 'internal-usage-expense' } },
    });
    if (!mapping) {
        throw new BusinessRuleError(
            'Minta Finance mengatur Beban Pemakaian Internal (ATK) di COA → Pemetaan Peran sebelum mencatat pemakaian.',
        );
    }
    const inventory =
        inventoryOverride ||
        (await resolveAccountCode('OPERATIONAL', 'inventory')).id;
    return { inventory, expense: mapping.accountId };
}

/** Validate accounting readiness under the same tenant transaction as stock posting. */
export async function assertInternalUsageAccounting(
    tx: Prisma.TransactionClient,
    productVariantId: string,
    accountIds: { inventory: string; expense: string },
    amount: Prisma.Decimal,
) {
    // Row locks serialize this feature's debits against one inventory control account.
    await tx.$queryRaw`SELECT id FROM "Account" WHERE id IN (${accountIds.inventory}, ${accountIds.expense}) ORDER BY id FOR UPDATE`;
    const accounts = await tx.account.findMany({
        where: { id: { in: [accountIds.inventory, accountIds.expense] } },
    });
    const inventory = accounts.find(
        (account) => account.id === accountIds.inventory,
    );
    const expense = accounts.find(
        (account) => account.id === accountIds.expense,
    );
    if (
        !inventory?.isActive ||
        inventory.type !== 'ASSET' ||
        inventory.category !== 'CURRENT_ASSET' ||
        inventory.currency !== 'IDR' ||
        inventory.isCashAccount
    ) {
        throw new BusinessRuleError(
            'Akun persediaan ATK belum valid. Minta Finance memeriksa dasar persediaan; ATK yang sudah dibebankan saat pembelian tidak boleh dibebankan lagi.',
        );
    }
    if (
        !expense?.isActive ||
        expense.type !== 'EXPENSE' ||
        expense.category !== 'OPERATING_EXPENSE' ||
        expense.currency !== 'IDR'
    ) {
        throw new BusinessRuleError(
            'Mapping Beban Pemakaian Internal harus akun beban operasional aktif dalam IDR, bukan HPP/WIP. Minta Finance memperbaikinya.',
        );
    }
    // Require attributable *posted* inventory value for this SKU. A GL balance from
    // unrelated SKUs is not proof that this item's purchase was capitalized.
    const basis = await tx.$queryRaw<Array<{ value: Prisma.Decimal }>>`
        SELECT COALESCE(SUM(l.debit - l.credit), 0) AS value
        FROM "JournalLine" l JOIN "JournalEntry" j ON j.id = l."journalEntryId"
        JOIN "StockMovement" m ON m.id = j."referenceId"
        WHERE m."productVariantId" = ${productVariantId}
          AND l."accountId" = ${inventory.id} AND j.status = 'POSTED' AND j."isAutoGenerated"
          AND j."referenceType"::text = CASE WHEN m.type = 'PURCHASE' THEN 'GOODS_RECEIPT'
            WHEN m.type = 'ADJUSTMENT' THEN 'STOCK_ADJUSTMENT' ELSE 'MANUAL_ENTRY' END
    `;
    const totals = await tx.journalLine.aggregate({
        where: { accountId: inventory.id, journalEntry: { status: 'POSTED' } },
        _sum: { debit: true, credit: true },
    });
    const balance = new Prisma.Decimal(totals._sum.debit ?? 0).minus(
        totals._sum.credit ?? 0,
    );
    if (
        new Prisma.Decimal(basis[0]?.value ?? 0).lt(amount) ||
        balance.lt(amount)
    ) {
        throw new BusinessRuleError(
            'Nilai persediaan ATK yang tertaut ke jurnal belum mencukupi. Minta Finance mencocokkan penerimaan dan saldo awal. Jangan gunakan penyesuaian hanya untuk melewati pemeriksaan ini.',
        );
    }
}
