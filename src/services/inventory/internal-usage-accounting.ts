import { Prisma, type Account } from '@prisma/client';
import { getMainPrisma, getTenantIdFromContext } from '@/lib/core/prisma';
import { BusinessRuleError } from '@/lib/errors/errors';
import { resolveAccountCode } from '@/services/accounting/account-mapping-policy';

/** Distinct readiness causes; never collapse them into a generic "saldo kurang". */
export const INTERNAL_USAGE_READINESS = {
    MISSING_MAPPING: 'INTERNAL_USAGE_MISSING_MAPPING',
    MISSING_COST: 'INTERNAL_USAGE_MISSING_COST',
    MISSING_SOURCE_BASIS: 'INTERNAL_USAGE_MISSING_SOURCE_BASIS',
    SOURCE_ACCOUNT_MISMATCH: 'INTERNAL_USAGE_SOURCE_ACCOUNT_MISMATCH',
    INSUFFICIENT_GL: 'INTERNAL_USAGE_INSUFFICIENT_GL',
} as const;
type ReadinessCode =
    (typeof INTERNAL_USAGE_READINESS)[keyof typeof INTERNAL_USAGE_READINESS];
const MAX_JOURNAL_AMOUNT = '9999999999999.99';

// Messages are safe for warehouse staff: cause + next step, no account values.
function notReady(code: ReadinessCode, message: string): never {
    throw new BusinessRuleError(message, undefined, code);
}

/** Explicit Finance choice only: do not turn a missing mapping into an inferred expense. */
export async function resolveInternalUsageAccounts(
    inventoryOverride: string | null,
) {
    const tenantId = getTenantIdFromContext();
    if (!tenantId)
        throw new BusinessRuleError(
            'Tenant pemakaian internal tidak dapat diverifikasi.',
        );
    const mapping = await getMainPrisma().tenantAccountRole.findUnique({
        where: { tenantId_role: { tenantId, role: 'internal-usage-expense' } },
    });
    if (!mapping) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_MAPPING,
            'Minta Finance mengatur Beban Pemakaian Internal (ATK) di COA → Pemetaan Peran sebelum mencatat pemakaian.',
        );
    }
    const inventory =
        inventoryOverride ||
        (await resolveAccountCode('OPERATIONAL', 'inventory')).id;
    return { inventory, expense: mapping.accountId };
}

/** Usage is valued at the location WAC only; a sale price is never a cost. */
export function internalUsageAmount(
    cost: Prisma.Decimal | null | undefined,
    quantity: number,
) {
    if (!cost || cost.lte(0))
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_COST,
            'Biaya persediaan di gudang ini belum tersedia. Minta Finance mencocokkan penerimaan ATK; harga jual tidak dapat dipakai sebagai biaya.',
        );
    const amount = cost.mul(quantity).toDecimalPlaces(2);
    if (amount.lte(0) || amount.gt(MAX_JOURNAL_AMOUNT))
        throw new BusinessRuleError(
            'Nilai pemakaian di luar batas pencatatan jurnal.',
        );
    return amount;
}

/**
 * Posted inventory value attributable to this SKU, per eligible inventory account.
 * Only auto journals sourced from this SKU's own movements count: a GL balance from
 * unrelated SKUs is not proof that this item's purchase was capitalized.
 */
export async function skuInventoryBasis(
    tx: Prisma.TransactionClient,
    productVariantId: string,
) {
    const rows = await tx.$queryRaw<
        Array<{ accountId: string; value: Prisma.Decimal }>
    >`
        SELECT l."accountId" AS "accountId", COALESCE(SUM(l.debit - l.credit), 0) AS value
        FROM "JournalLine" l JOIN "JournalEntry" j ON j.id = l."journalEntryId"
        LEFT JOIN "StockMovement" m ON m.id = j."referenceId"
        LEFT JOIN "AtkCostCorrection" c ON c."journalId" = j.id AND c.id = j."referenceId"
        LEFT JOIN "StockMovement" source ON source.id = c."sourceMovementId"
        JOIN "Account" a ON a.id = l."accountId"
        WHERE j.status = 'POSTED' AND j."isAutoGenerated"
          AND ((m."productVariantId" = ${productVariantId}
            AND j."referenceType"::text = CASE WHEN m.type = 'PURCHASE' THEN 'GOODS_RECEIPT'
                WHEN m.type = 'ADJUSTMENT' THEN 'STOCK_ADJUSTMENT' ELSE 'MANUAL_ENTRY' END)
            OR (source."productVariantId" = ${productVariantId} AND j."referenceType" = 'STOCK_ADJUSTMENT'))
          AND a.type = 'ASSET' AND a.category = 'CURRENT_ASSET' AND a."isActive"
          AND a.currency = 'IDR' AND NOT a."isCashAccount"
        GROUP BY l."accountId"
    `;
    return new Map(
        rows.map((row) => [row.accountId, new Prisma.Decimal(row.value)]),
    );
}

/**
 * Credit the account that actually capitalized this SKU. The resolved account wins
 * whenever it holds enough SKU basis (unchanged behaviour); otherwise exactly one
 * other account must hold it. Never choose by balance size or split a usage.
 */
export async function selectInternalUsageInventory(
    tx: Prisma.TransactionClient,
    productVariantId: string,
    resolvedInventoryId: string,
    amount: Prisma.Decimal,
    isOverride: boolean,
) {
    // A product-level override is an explicit Finance choice: keep it strict.
    if (isOverride) return resolvedInventoryId;
    const basis = await skuInventoryBasis(tx, productVariantId);
    if (basis.get(resolvedInventoryId)?.gte(amount)) return resolvedInventoryId;
    const sources = [...basis].filter(
        ([id, value]) => id !== resolvedInventoryId && value.gte(amount),
    );
    if (sources.length === 1) return sources[0][0];
    const funded = [...basis.values()].filter((value) => value.gt(0)).length;
    if (funded === 0) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_SOURCE_BASIS,
            'Penerimaan barang ini belum tertaut ke jurnal persediaan, jadi nilainya belum bisa dibebankan. Minta Finance memeriksa penerimaan atau saldo awal barang ini.',
        );
    }
    // One funded account that is simply short is a basis gap, not a split.
    if (funded === 1) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_SOURCE_BASIS,
            'Nilai barang ini yang tertaut ke jurnal penerimaan belum mencukupi untuk jumlah ini. Minta Finance mencocokkan penerimaan dan saldo awal; jangan gunakan penyesuaian hanya untuk melewati pemeriksaan ini.',
        );
    }
    notReady(
        INTERNAL_USAGE_READINESS.SOURCE_ACCOUNT_MISMATCH,
        'Nilai barang ini tercatat terpecah di beberapa akun persediaan, sehingga sistem tidak dapat memilih akun dengan pasti. Minta Finance memeriksa akun persediaan barang ini sebelum barang diserahkan.',
    );
}

function isInventoryAccount(account: Account | undefined) {
    return (
        account?.isActive &&
        account.type === 'ASSET' &&
        account.category === 'CURRENT_ASSET' &&
        account.currency === 'IDR' &&
        !account.isCashAccount
    );
}

function isExpenseAccount(account: Account | undefined) {
    return (
        account?.isActive &&
        account.type === 'EXPENSE' &&
        account.category === 'OPERATING_EXPENSE' &&
        account.currency === 'IDR'
    );
}

/**
 * Validate accounting readiness. Posting calls this under the stock transaction
 * with row locks; the read-only preflight calls it without locks.
 */
export async function assertInternalUsageAccounting(
    tx: Prisma.TransactionClient,
    productVariantId: string,
    accountIds: { inventory: string; expense: string },
    amount: Prisma.Decimal,
    { lock }: { lock: boolean } = { lock: true },
) {
    // Row locks serialize this feature's debits against one inventory control account.
    if (lock)
        await tx.$queryRaw`SELECT id FROM "Account" WHERE id IN (${accountIds.inventory}, ${accountIds.expense}) ORDER BY id FOR UPDATE`;
    const accounts = await tx.account.findMany({
        where: { id: { in: [accountIds.inventory, accountIds.expense] } },
    });
    const inventory = accounts.find(
        (account) => account.id === accountIds.inventory,
    );
    const expense = accounts.find(
        (account) => account.id === accountIds.expense,
    );
    if (!inventory || !isInventoryAccount(inventory)) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_MAPPING,
            'Akun persediaan ATK belum valid. Minta Finance memeriksa dasar persediaan; ATK yang sudah dibebankan saat pembelian tidak boleh dibebankan lagi.',
        );
    }
    if (!expense || !isExpenseAccount(expense)) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_MAPPING,
            'Mapping Beban Pemakaian Internal harus akun beban operasional aktif dalam IDR, bukan HPP/WIP. Minta Finance memperbaikinya.',
        );
    }
    const basis =
        (await skuInventoryBasis(tx, productVariantId)).get(inventory.id) ??
        new Prisma.Decimal(0);
    if (basis.lt(amount)) {
        notReady(
            INTERNAL_USAGE_READINESS.MISSING_SOURCE_BASIS,
            'Nilai persediaan ATK yang tertaut ke jurnal belum mencukupi. Minta Finance mencocokkan penerimaan dan saldo awal. Jangan gunakan penyesuaian hanya untuk melewati pemeriksaan ini.',
        );
    }
    const totals = await tx.journalLine.aggregate({
        where: { accountId: inventory.id, journalEntry: { status: 'POSTED' } },
        _sum: { debit: true, credit: true },
    });
    const balance = new Prisma.Decimal(totals._sum.debit ?? 0).minus(
        totals._sum.credit ?? 0,
    );
    if (balance.lt(amount)) {
        notReady(
            INTERNAL_USAGE_READINESS.INSUFFICIENT_GL,
            'Saldo akun persediaan ATK belum mencukupi untuk pemakaian ini. Minta Finance memeriksa saldo akun; jangan gunakan penyesuaian stok untuk melewati pemeriksaan ini.',
        );
    }
    return { inventory, expense, basis, balance };
}
