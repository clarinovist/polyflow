const url = process.env.RETURN_CREDIT_TEST_DATABASE_URL;
const db = url ? returnTestClient(url) : null;
const peer = url ? returnTestClient(url) : null;
const secondUrl = url ? new URL(url) : null;
if (secondUrl) secondUrl.pathname = '/polyflow_return_credit_tenant_test';
const other = secondUrl ? returnTestClient(secondUrl.toString()) : null;
const actor = 'atk-test-actor';
const backup = { ready: () => true, save: async () => 'synthetic-verified-backup#sha256=fixture' };
const run = <T>(fn: () => Promise<T>) => tenantContext.run(db!, () => runWithActor(actor, fn));
async function seed(client: PrismaClient) {
    await verifyReturnTestDatabase(client);
    await client.$executeRaw`TRUNCATE "Product", "Location", "Account", "FiscalPeriod", "User", "SystemSequence", "AuditLog" CASCADE`;
    await client.user.create({ data: { id: actor, email: 'atk@example.invalid', password: 'synthetic', role: 'FINANCE' } });
    await client.location.create({ data: { id: 'office', name: 'Synthetic office', slug: 'atk-office' } });
    await client.product.create({ data: { id: 'product', name: 'Synthetic supplies', productType: 'OPERATIONAL', inventoryAccountId: 'inventory' } });
    await client.productVariant.create({ data: { id: 'sku', productId: 'product', skuCode: 'ATK-RECOVERY-TEST', name: 'Synthetic pen', primaryUnit: 'PCS' } });
    await client.account.createMany({ data: [
        { id: 'inventory', code: '11300', name: 'Inventory', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: 'loss', code: '91100', name: 'Inventory loss', type: 'EXPENSE', category: 'OPERATING_EXPENSE' },
        { id: 'payable', code: '21100', name: 'Payable', type: 'LIABILITY', category: 'CURRENT_LIABILITY' },
        { id: 'earnings', code: '33000', name: 'Current Year Earnings', type: 'EQUITY', category: 'RETAINED_EARNINGS' },
    ] });
    const date = new Date(); const received = new Date(date.getTime() - 1000);
    const [year, month] = toBusinessDateString(date).split('-').map(Number);
    const bounds = getWibMonthBounds(year, month);
    await client.fiscalPeriod.create({ data: { id: 'period', name: 'Synthetic period', year, month, startDate: bounds.start, endDate: bounds.end, status: 'OPEN' } });
    await client.systemSequence.create({ data: { key: `JOURNAL_ENTRY_${year}`, value: 1 } });
    await client.inventory.create({ data: { locationId: 'office', productVariantId: 'sku', quantity: 10, averageCost: 100 } });
    await client.stockMovement.createMany({ data: [
        { id: 'receipt', productVariantId: 'sku', type: 'PURCHASE', toLocationId: 'office', quantity: 20, cost: 100, createdAt: received, companyOwned: true },
        { id: 'loss', productVariantId: 'sku', type: 'ADJUSTMENT', fromLocationId: 'office', quantity: 10, cost: null, createdAt: date, companyOwned: true },
    ] });
    await client.journalEntry.create({ data: { id: 'receipt-j', entryNumber: 'ATK-RECEIPT', entryDate: received, description: 'Synthetic receipt', referenceId: 'receipt', referenceType: 'GOODS_RECEIPT', status: 'POSTED', isAutoGenerated: true,
        lines: { create: [{ accountId: 'inventory', debit: 2000 }, { accountId: 'payable', credit: 2000 }] } } });
    await client.journalEntry.create({ data: { id: 'loss-j', entryNumber: 'ATK-LOSS', entryDate: date, description: 'Synthetic overcharged loss', referenceId: 'loss', referenceType: 'STOCK_ADJUSTMENT', status: 'POSTED', isAutoGenerated: true,
        lines: { create: [{ accountId: 'loss', debit: 1020 }, { accountId: 'inventory', credit: 1020 }] } } });
}
async function input(kind: 'REFUND' | 'COMPENSATION' = 'REFUND'): Promise<AtkRecoveryApply> {
    const p = await previewAtkRecovery(db!, { sourceMovementId: 'loss', kind }, backup);
    expect(p.status).toBe('eligible');
    return { sourceMovementId: 'loss', kind, fingerprint: p.proposal!.fingerprint, postingDate: p.proposal!.postingDate, requestId: randomUUID(), reason: 'Synthetic verified evidence', confirmed: true };
}
const basis = () => db!.$transaction(tx => skuInventoryBasis(tx, 'sku'));

describe.skipIf(!db)('ATK recovery real PostgreSQL contract', () => {
    beforeEach(async () => seed(db!));
    afterAll(async () => { await Promise.all([db?.$disconnect(), peer?.$disconnect(), other?.$disconnect()]); });
    it('refunds and compensates exactly once with immutable evidence and unchanged qty/WAC', async () => {
        const stock = await db!.inventory.findMany(); const movements = await db!.stockMovement.findMany({ orderBy: { id: 'asc' } });
        const req = await input(); const result = await run(() => applyAtkRecovery(db!, req, actor, backup));
        expect(result.amount).toBe('20.00'); expect((await basis()).get('inventory')?.toString()).toBe('1000');
        expect(await run(() => applyAtkRecovery(db!, req, actor, backup))).toMatchObject({ id: result.id, alreadyApplied: true });
        expect(await getAtkRecoveryReceipt(db!, req.requestId)).toMatchObject({ id: result.id });
        expect(await db!.atkCostEvidence.count()).toBe(2);
        const journalId = 'invalid-compensation-journal';
        await db!.journalEntry.create({ data: { id: journalId, entryNumber: 'INVALID-COMP', entryDate: new Date(), description: 'Synthetic invalid inverse', referenceId: 'invalid-compensation', referenceType: 'STOCK_ADJUSTMENT', status: 'POSTED', isAutoGenerated: true } });
        const original = await db!.atkCostCorrection.findUniqueOrThrow({ where: { id: result.id } });
        await expect(db!.atkCostCorrection.create({ data: { ...original, evidenceSnapshot: { synthetic: true }, id: 'invalid-compensation', requestId: randomUUID(), journalId, kind: 'COMPENSATION', reversalOfId: original.id, amount: 21, originalLoss: 1021 } })).rejects.toThrow('Compensation must match');
        await db!.journalEntry.delete({ where: { id: journalId } });
        expect(await db!.auditLog.count({ where: { action: 'ATK_COST_REFUND' } })).toBe(1);
        expect(await db!.inventory.findMany()).toEqual(stock); expect(await db!.stockMovement.findMany({ orderBy: { id: 'asc' } })).toEqual(movements);
        const diagnosis = await inspectInventoryReconciliation(db!, 'sku'); expect(diagnosis.basisTotal).toBe('1000.00');
        await expect(db!.stockMovement.update({ where: { id: 'receipt' }, data: { cost: 200 } })).rejects.toThrow('protected');
        await expect(db!.journalEntry.update({ where: { id: result.journalId }, data: { status: 'VOIDED' } })).rejects.toThrow('protected');
        await expect(db!.journalLine.create({ data: { journalEntryId: result.journalId, accountId: 'inventory', debit: 1 } })).rejects.toThrow('protected');
        await expect(db!.stockMovement.delete({ where: { id: 'receipt' } })).rejects.toThrow('protected');
        const inverse = await input('COMPENSATION'); await run(() => applyAtkRecovery(db!, inverse, actor, backup));
        expect((await basis()).get('inventory')?.toString()).toBe('980');
        expect(await db!.atkCostCorrection.count()).toBe(2);
        expect(await db!.inventory.findMany()).toEqual(stock);
        expect(await previewAtkRecovery(db!, { sourceMovementId: 'loss', kind: 'REFUND' }, backup)).toMatchObject({ status: 'already_applied' });
    });
    it('rejects complete-looking malformed postings, missing evidence and late foreign evidence at the DB boundary', async () => {
        const result = await run(async () => applyAtkRecovery(db!, await input(), actor, backup));
        const original = await db!.atkCostCorrection.findUniqueOrThrow({ where: { id: result.id } });
        const evidence = await db!.atkCostEvidence.findMany({ where: { correctionId: result.id } });
        for (const malformed of ['empty', 'wrong-direction', 'missing-evidence', 'date-mismatch']) {
            await expect(db!.$transaction(async tx => {
                const id = randomUUID(), journalId = randomUUID();
                await tx.journalEntry.create({ data: { id: journalId, entryNumber: id, referenceId: id, referenceType: 'STOCK_ADJUSTMENT', isAutoGenerated: true, status: 'POSTED', description: 'Synthetic malformed correction',
                    entryDate: malformed === 'date-mismatch' ? new Date('2000-01-01') : original.postingDate,
                    lines: { create: malformed === 'empty' ? [] : [
                        { accountId: 'inventory', debit: malformed === 'wrong-direction' ? 20 : 0, credit: malformed === 'wrong-direction' ? 0 : 20 },
                        { accountId: 'loss', debit: malformed === 'wrong-direction' ? 0 : 20, credit: malformed === 'wrong-direction' ? 20 : 0 },
                    ] } } });
                await tx.atkCostCorrection.create({ data: { ...original, evidenceSnapshot: original.evidenceSnapshot as object, id, requestId: randomUUID(), journalId, kind: 'COMPENSATION', reversalOfId: original.id,
                    evidence: { create: malformed === 'missing-evidence' ? [] : evidence.map(e => ({ id: randomUUID(), movementId: e.movementId, journalId: e.journalId })) } } });
                await tx.$executeRaw`SET CONSTRAINTS "atk_document_complete" IMMEDIATE`;
            }), malformed).rejects.toThrow();
        }
        await db!.productVariant.create({ data: { id: 'other-sku', productId: 'product', skuCode: 'OTHER-ATK', name: 'Other synthetic item', primaryUnit: 'PCS' } });
        await db!.stockMovement.create({ data: { id: 'foreign-move', productVariantId: 'other-sku', type: 'PURCHASE', quantity: 1, cost: 100, toLocationId: 'office' } });
        await db!.journalEntry.create({ data: { id: 'foreign-journal', entryNumber: 'FOREIGN', entryDate: new Date(), referenceId: 'foreign-move', description: 'Synthetic unrelated journal' } });
        await expect(db!.atkCostEvidence.create({ data: { id: randomUUID(), correctionId: result.id, movementId: 'foreign-move', journalId: 'foreign-journal' } })).rejects.toThrow('outside');
        expect(await db!.atkCostCorrection.count()).toBe(1); expect(await db!.atkCostEvidence.count()).toBe(2);
    });
    it('rejects malformed documents on native PostgreSQL COMMIT and leaves no persisted correction', async () => {
        const result = await run(async () => applyAtkRecovery(db!, await input(), actor, backup));
        const client = new Client({ connectionString: url! });
        const id = randomUUID(), journalId = randomUUID();
        await client.connect();
        try {
            await client.query('BEGIN');
            await client.query(`INSERT INTO "JournalEntry" (id, "entryNumber", "entryDate", description, "referenceId", "referenceType", status, "isAutoGenerated", "updatedAt")
                SELECT $1, $1, "postingDate", 'Synthetic malformed posting', $2, 'STOCK_ADJUSTMENT', 'POSTED', true, now() FROM "AtkCostCorrection" WHERE id = $3`, [journalId, id, result.id]);
            await client.query(`INSERT INTO "AtkCostCorrection" (id, kind, "requestId", "requestHash", "sourceMovementId", "sourceJournalId", "journalId", "reversalOfId", amount, "historicalUnitCost", "expectedLoss", "originalLoss", fingerprint, "rulesVersion", reason, "actorId", "postingDate", "backupReference", "evidenceSnapshot")
                SELECT $1, 'COMPENSATION', $1, "requestHash", "sourceMovementId", "sourceJournalId", $2, id, amount, "historicalUnitCost", "expectedLoss", "originalLoss", fingerprint, "rulesVersion", reason, "actorId", "postingDate", "backupReference", "evidenceSnapshot" FROM "AtkCostCorrection" WHERE id = $3`, [id, journalId, result.id]);
            await expect(client.query('COMMIT')).rejects.toThrow('exact two-line');
            expect(await db!.atkCostCorrection.findUnique({ where: { id } })).toBeNull();
            expect(await db!.journalEntry.findUnique({ where: { id: journalId } })).toBeNull();
        } finally { await client.query('ROLLBACK'); await client.end(); }
    });
    it('serializes concurrent requests or rejects NOWAIT; never posts a second refund', async () => {
        const req = await input();
        const results = await run(() => Promise.allSettled([applyAtkRecovery(db!, req, actor, backup), applyAtkRecovery(peer!, { ...req, requestId: randomUUID() }, actor, backup)]));
        expect(results.some(r => r.status === 'fulfilled')).toBe(true);
        expect(await db!.atkCostCorrection.count()).toBe(1); expect((await basis()).get('inventory')?.toString()).toBe('1000');
    });
    it('rejects active ledger readers and stale evidence without partial writes', async () => {
        const req = await input();
        await peer!.$transaction(async tx => {
            await tx.$queryRaw`SELECT * FROM "Inventory" WHERE "productVariantId" = 'sku'`;
            await expect(run(() => applyAtkRecovery(db!, req, actor, backup))).rejects.toThrow('Transaksi lain');
        });
        expect(await db!.atkCostCorrection.count()).toBe(0);
        const mutateDuringBackup = { ...backup, save: async () => { await peer!.inventory.updateMany({ data: { quantity: 9 } }); return 'backup'; } };
        await expect(run(() => applyAtkRecovery(db!, req, actor, mutateDuringBackup))).rejects.toThrow();
        expect(await db!.atkCostCorrection.count()).toBe(0);
    });
    it('rejects compensation after downstream use and closed periods', async () => {
        await run(async () => applyAtkRecovery(db!, await input(), actor, backup));
        await db!.stockMovement.create({ data: { id: 'later', type: 'OUT', fromLocationId: 'office', productVariantId: 'sku', quantity: 1, cost: 100 } });
        await db!.inventory.updateMany({ data: { quantity: 9 } });
        expect(await previewAtkRecovery(db!, { sourceMovementId: 'loss', kind: 'COMPENSATION' }, backup)).toMatchObject({ status: 'blocked' });
        await db!.fiscalPeriod.update({ where: { id: 'period' }, data: { status: 'CLOSED' } });
        expect(await previewAtkRecovery(db!, { sourceMovementId: 'loss', kind: 'COMPENSATION' }, backup)).toMatchObject({ status: 'blocked' });
    });
    it('rolls back the correction, evidence and journal if atomic audit fails', async () => {
        const req = await input();
        await db!.$executeRawUnsafe("CREATE FUNCTION atk_test_audit_fail() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action = 'ATK_COST_REFUND' THEN RAISE EXCEPTION 'synthetic audit rejection'; END IF; RETURN NEW; END $$");
        await db!.$executeRawUnsafe('CREATE TRIGGER atk_test_audit BEFORE INSERT ON "AuditLog" FOR EACH ROW EXECUTE FUNCTION atk_test_audit_fail()');
        try {
            await expect(run(() => applyAtkRecovery(db!, req, actor, backup))).rejects.toThrow('synthetic audit rejection');
            expect(await db!.atkCostCorrection.count()).toBe(0); expect(await db!.atkCostEvidence.count()).toBe(0); expect(await db!.journalEntry.count()).toBe(2);
            expect((await basis()).get('inventory')?.toString()).toBe('980');
        } finally {
            await db!.$executeRawUnsafe('DROP TRIGGER atk_test_audit ON "AuditLog"'); await db!.$executeRawUnsafe('DROP FUNCTION atk_test_audit_fail()');
        }
    });
    it('coordinates period close before balance calculation; records corrections on the posting date', async () => {
        const req = await input();
        await peer!.$transaction(async tx => {
            await tx.$queryRaw`SELECT id FROM "FiscalPeriod" WHERE id = 'period' FOR UPDATE`;
            await expect(run(() => applyAtkRecovery(db!, req, actor, backup))).rejects.toThrow('Transaksi lain');
        });
        await run(() => applyAtkRecovery(db!, req, actor, backup));
        const date = toBusinessDateString(new Date());
        const economic = await db!.$transaction(tx => diagnoseInventoryEconomicCompleteness(tx, { startDate: date, endDate: date }));
        expect(economic.findings.some(f => f.code === 'INVENTORY_JOURNAL_WITHOUT_MOVEMENT')).toBe(false);
        await run(() => closeFiscalPeriod('period', actor));
        const closing = await db!.journalEntry.findFirstOrThrow({ where: { reference: 'CLOSING-Synthetic-period' }, include: { lines: true } });
        expect(closing.lines.find(l => l.accountId === 'loss')?.credit.toString()).toBe('1000');
        expect((await db!.fiscalPeriod.findUniqueOrThrow({ where: { id: 'period' } })).status).toBe('CLOSED');
    });
    it('does not resolve another tenants request receipt', async () => {
        await seed(other!);
        const req = await input(); await run(() => applyAtkRecovery(db!, req, actor, backup));
        expect(await getAtkRecoveryReceipt(other!, req.requestId)).toBeNull();
        expect(await other!.atkCostCorrection.count()).toBe(0);
    });
});
