const actor = 'usage-actor';
const run = <T>(client: PrismaClient, callback: () => Promise<T>) => tenantContext.run(client, () => runWithActor(actor, callback));
const payload = () => ({ requestId: randomUUID(), productVariantId: 'usage-pen', locationId: 'usage-office', quantity: 3, unit: 'PCS' as const, date: toBusinessDateString(new Date()), recipient: 'Synthetic recipient', department: 'Administration', purpose: 'Synthetic office use' });
async function seed(client: PrismaClient) {
    await verifyReturnTestDatabase(client);
    await client.$executeRaw`TRUNCATE "Product", "Location", "User", "Account", "FiscalPeriod", "SystemSequence", "AuditLog" CASCADE`;
    await client.user.create({ data: { id: actor, name: 'Synthetic warehouse', email: 'usage@example.invalid', password: 'synthetic-only', role: 'WAREHOUSE' } });
    await client.location.create({ data: { id: 'usage-office', name: 'Synthetic Office', slug: 'usage-office' } });
    await client.account.createMany({ data: [
        { id: 'usage-inventory', code: '11370', name: 'Synthetic supplies', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: 'usage-expense', code: '61970', name: 'Synthetic office expense', type: 'EXPENSE', category: 'OPERATING_EXPENSE' },
        { id: 'usage-clearing', code: '21170', name: 'Synthetic GR clearing', type: 'LIABILITY', category: 'CURRENT_LIABILITY' },
        { id: 'usage-raw', code: '11310', name: 'Synthetic raw material', type: 'ASSET', category: 'CURRENT_ASSET' },
        // Pattern targets for the real resolver used by stock adjustments.
        { id: 'usage-generic', code: '11300', name: 'Synthetic generic stock', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: 'usage-loss', code: '91100', name: 'Synthetic adjustment loss', type: 'EXPENSE', category: 'OPERATING_EXPENSE' },
    ] });
    await client.product.create({ data: { id: 'usage-product', name: 'Synthetic pen', productType: 'OPERATIONAL', inventoryAccountId: 'usage-inventory' } });
    await client.productVariant.create({ data: { id: 'usage-pen', productId: 'usage-product', name: 'Synthetic black pen', skuCode: 'USAGE-PEN', primaryUnit: 'PCS' } });
    await client.inventory.create({ data: { locationId: 'usage-office', productVariantId: 'usage-pen', quantity: 24, averageCost: 2000 } });
    await client.stockMovement.create({ data: { id: 'usage-receipt', type: 'PURCHASE', productVariantId: 'usage-pen', toLocationId: 'usage-office', quantity: 24, cost: 2000, reference: 'Synthetic receipt' } });
    await client.journalEntry.create({ data: { id: 'usage-opening', entryNumber: 'USAGE-RECEIPT', entryDate: new Date(), description: 'Synthetic receipt', referenceType: 'GOODS_RECEIPT', referenceId: 'usage-receipt', status: 'POSTED', isAutoGenerated: true, lines: { create: [
        { accountId: 'usage-inventory', debit: 48000, credit: 0 }, { accountId: 'usage-clearing', debit: 0, credit: 48000 },
    ] } } });
    const [year, month] = toBusinessDateString(new Date()).split('-').map(Number);
    const bounds = getWibMonthBounds(year, month);
    await client.fiscalPeriod.create({ data: { name: 'Synthetic current period', year, month, startDate: bounds.start, endDate: bounds.end, status: 'OPEN' } });
    await client.systemSequence.create({ data: { key: `JOURNAL_ENTRY_${year}`, value: 100 } });
}
async function stock() { return Number((await db!.inventory.findFirstOrThrow()).quantity); }
describe.skipIf(!db)('internal usage real PostgreSQL contract', () => {
    beforeEach(async () => seed(db!));
    afterAll(async () => { await Promise.all([db?.$disconnect(), other?.$disconnect()]); });
    it('posts once under concurrent replay, preserving exact GL/ledger/source/audit', async () => {
        const input = payload();
        const [a, b] = await run(db!, () => Promise.all([createInternalUsage(input, actor), createInternalUsage(input, actor)]));
        expect(a.id).toBe(b.id); expect(await stock()).toBe(21);
        expect(await db!.internalUsage.count()).toBe(1);
        expect(await db!.auditLog.count({ where: { action: 'CREATE_INTERNAL_USAGE' } })).toBe(1);
        const source = await db!.internalUsage.findUniqueOrThrow({ where: { id: a.id }, include: { journal: { include: { lines: true } }, movement: true } });
        expect(source.movement.productionOrderId).toBeNull(); expect(source.movement.cost?.toString()).toBe('2000');
        expect(source.journal.status).toBe('POSTED'); expect(source.journal.lines.map((line) => [line.accountId, Number(line.debit), Number(line.credit)])).toEqual(expect.arrayContaining([['usage-expense', 6000, 0], ['usage-inventory', 0, 6000]]));
        const ledger = await run(db!, () => getStockBalance({ startDate: input.date, endDate: input.date }));
        expect(ledger.rows[0]).toMatchObject({ totalIn: 24, totalOut: 3, closingStock: 21 });
        const diagnosis = await db!.$transaction(async (tx) => {
            await tx.$executeRaw`SET TRANSACTION READ ONLY`;
            return diagnoseInventoryEconomicCompleteness(tx, { startDate: input.date, endDate: input.date });
        });
        expect(diagnosis.flows.productionIssues).toBe(0);
        expect(diagnosis.findings.some((finding) => finding.code === 'INVENTORY_JOURNAL_VECTOR_INVALID')).toBe(false);
        await expect(run(db!, () => createInternalUsage({ ...input, quantity: 4 }, actor))).rejects.toThrow('berbeda');
    });
    it('allows at most one concurrent overdraw and honors reservations', async () => {
        const results = await run(db!, () => Promise.allSettled([createInternalUsage({ ...payload(), quantity: 20 }, actor), createInternalUsage({ ...payload(), quantity: 20 }, actor)]));
        expect(results.filter((result) => result.status === 'fulfilled')).toHaveLength(1); expect(await stock()).toBe(4);
        await db!.stockReservation.create({ data: { productVariantId: 'usage-pen', locationId: 'usage-office', quantity: 3, status: 'ACTIVE', reservedFor: 'SALES_ORDER', referenceId: 'synthetic-reservation' } });
        await expect(run(db!, () => createInternalUsage(payload(), actor))).rejects.toThrow(); expect(await stock()).toBe(4);
    });
    it('rolls back every write when the atomic audit insert fails', async () => {
        await db!.$executeRawUnsafe(`CREATE FUNCTION usage_test_reject_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action = 'CREATE_INTERNAL_USAGE' THEN RAISE EXCEPTION 'synthetic audit failure'; END IF; RETURN NEW; END $$`);
        await db!.$executeRawUnsafe('CREATE TRIGGER usage_test_audit_guard BEFORE INSERT ON "AuditLog" FOR EACH ROW EXECUTE FUNCTION usage_test_reject_audit()');
        try {
            await expect(run(db!, () => createInternalUsage(payload(), actor))).rejects.toThrow('synthetic audit failure');
            expect(await stock()).toBe(24); expect(await db!.internalUsage.count()).toBe(0); expect(await db!.stockMovement.count()).toBe(1); expect(await db!.journalEntry.count()).toBe(1);
        } finally {
            await db!.$executeRawUnsafe('DROP TRIGGER usage_test_audit_guard ON "AuditLog"');
            await db!.$executeRawUnsafe('DROP FUNCTION usage_test_reject_audit()');
        }
    });
    it('rejects missing inventory capitalization and closed fiscal periods without stock change', async () => {
        await db!.journalEntry.update({ where: { id: 'usage-opening' }, data: { status: 'VOIDED' } });
        await expect(run(db!, () => createInternalUsage(payload(), actor))).rejects.toThrow('belum mencukupi');
        await db!.journalEntry.update({ where: { id: 'usage-opening' }, data: { status: 'POSTED' } });
        await db!.fiscalPeriod.updateMany({ data: { status: 'CLOSED' } });
        await expect(run(db!, () => createInternalUsage(payload(), actor))).rejects.toThrow('ditutup');
        expect(await stock()).toBe(24); expect(await db!.internalUsage.count()).toBe(0);
    });
    it('credits the account that capitalized the SKU, never a larger unrelated balance', async () => {
        await db!.product.update({ where: { id: 'usage-product' }, data: { inventoryAccountId: null } });
        await db!.journalEntry.create({ data: { entryNumber: 'USAGE-UNRELATED', entryDate: new Date(), description: 'Unrelated raw stock', referenceType: 'MANUAL_ENTRY', status: 'POSTED', lines: { create: [
            { accountId: 'usage-raw', debit: 900000, credit: 0 }, { accountId: 'usage-clearing', debit: 0, credit: 900000 },
        ] } } });
        const usage = await run(db!, () => createInternalUsage(payload(), actor));
        const source = await db!.internalUsage.findUniqueOrThrow({ where: { id: usage.id }, include: { journal: { include: { lines: true } } } });
        expect(source.inventoryAccountId).toBe('usage-inventory');
        expect(source.journal.lines.map((line) => [line.accountId, Number(line.debit), Number(line.credit)])).toEqual(expect.arrayContaining([['usage-expense', 6000, 0], ['usage-inventory', 0, 6000]]));
        expect(await stock()).toBe(21);
        // The consumed basis stays attributed: the remaining 18 PCS still resolve to the same source.
        await run(db!, () => createInternalUsage({ ...payload(), quantity: 18 }, actor));
        expect(await stock()).toBe(3);
        await expect(run(db!, () => createInternalUsage({ ...payload(), quantity: 3 }, actor))).resolves.toBeTruthy();
        await expect(run(db!, () => createInternalUsage({ ...payload(), quantity: 1 }, actor))).rejects.toThrow();
    });
    it('rejects a basis split across accounts without stock or journal writes', async () => {
        await db!.product.update({ where: { id: 'usage-product' }, data: { inventoryAccountId: null } });
        await db!.stockMovement.create({ data: { id: 'usage-transfer', type: 'TRANSFER', productVariantId: 'usage-pen', fromLocationId: 'usage-office', toLocationId: 'usage-office', quantity: 24, cost: 2000, reference: 'Synthetic reclass' } });
        await db!.journalEntry.create({ data: { entryNumber: 'USAGE-SPLIT', entryDate: new Date(), description: 'Synthetic split', referenceType: 'MANUAL_ENTRY', referenceId: 'usage-transfer', status: 'POSTED', isAutoGenerated: true, lines: { create: [
            { accountId: 'usage-raw', debit: 46000, credit: 0 }, { accountId: 'usage-inventory', debit: 0, credit: 46000 },
        ] } } });
        await expect(run(db!, () => createInternalUsage({ ...payload(), quantity: 24 }, actor))).rejects.toMatchObject({ code: 'INTERNAL_USAGE_SOURCE_ACCOUNT_MISMATCH' });
        expect(await stock()).toBe(24); expect(await db!.internalUsage.count()).toBe(0); expect(await db!.journalEntry.count()).toBe(2);
    });
    it('values operational stock-count losses at WAC and credits the SKU source account', async () => {
        await db!.product.update({ where: { id: 'usage-product' }, data: { inventoryAccountId: null } });
        await db!.productVariant.create({ data: { id: 'usage-note', productId: 'usage-product', name: 'Synthetic note', skuCode: 'USAGE-NOTE', primaryUnit: 'PCS' } });
        await db!.inventory.create({ data: { locationId: 'usage-office', productVariantId: 'usage-note', quantity: 5, averageCost: 7050 } });
        // Same shape as stock-opname finalisation: an uncosted loss posted inside the caller's transaction.
        const loss = (id: string, productVariantId: string, quantity: number) => run(db!, () => db!.$transaction(async (tx) => {
            const movement = await tx.stockMovement.create({ data: { id, type: 'ADJUSTMENT', productVariantId, fromLocationId: 'usage-office', toLocationId: null, quantity, reference: 'OPN-SYNTHETIC' } });
            await recordInventoryMovement(movement, tx);
        }));
        await loss('usage-opname-pen', 'usage-pen', 2);
        expect((await db!.stockMovement.findUniqueOrThrow({ where: { id: 'usage-opname-pen' } })).cost?.toString()).toBe('2000');
        const journal = await db!.journalEntry.findFirstOrThrow({ where: { referenceId: 'usage-opname-pen' }, include: { lines: true } });
        expect(journal.referenceType).toBe('STOCK_ADJUSTMENT');
        expect(journal.lines.map((line) => [line.accountId, Number(line.debit), Number(line.credit)])).toEqual(expect.arrayContaining([['usage-loss', 4000, 0], ['usage-inventory', 0, 4000]]));
        expect(journal.lines.some((line) => line.accountId === 'usage-generic')).toBe(false);
        await expect(loss('usage-opname-note', 'usage-note', 1)).rejects.toMatchObject({ code: 'OPERATIONAL_ADJUSTMENT_MISSING_SOURCE_BASIS' });
        expect(await db!.stockMovement.count({ where: { id: 'usage-opname-note' } })).toBe(0);
        expect(await db!.journalEntry.count({ where: { referenceId: 'usage-opname-note' } })).toBe(0);
    });
    it('isolates identical keys and identifiers across tenant databases', async () => {
        await seed(other!); const input = payload();
        await run(db!, () => createInternalUsage(input, actor));
        expect((await run(other!, () => getInternalUsageHistory())).total).toBe(0);
        await run(other!, () => createInternalUsage(input, actor));
        expect(await other!.internalUsage.count()).toBe(1); expect(await db!.internalUsage.count()).toBe(1);
    });
});
