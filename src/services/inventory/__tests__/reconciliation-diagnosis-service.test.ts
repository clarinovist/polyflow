import { beforeEach, describe, expect, it, vi } from 'vitest';
import { Prisma, type PrismaClient } from '@prisma/client';
import { inspectInventoryReconciliation, listReconciliationCatalog } from '../reconciliation-diagnosis-service';

const m = vi.hoisted(() => ({ basis: vi.fn() }));
vi.mock('../internal-usage-accounting', () => ({ skuInventoryBasis: m.basis }));
const d = (value: number | string) => new Prisma.Decimal(value);
const now = new Date('2026-01-15T00:00:00Z');
const variant = { id: 'sku', skuCode: 'TEST-ATK', name: 'Synthetic supplies', primaryUnit: 'PCS', archivedAt: null, product: { productType: 'OPERATIONAL' } };
const location = { id: 'loc', name: 'Synthetic office', locationType: 'INTERNAL', packagingOwnerCustomerId: null };
const inventory = (quantity: number, cost: number | null, id = 'loc') => ({ quantity: d(quantity), averageCost: cost === null ? null : d(cost), location: { ...location, id } });
const movement = { id: 'movement', type: 'ADJUSTMENT', quantity: d(10), cost: null, createdAt: now, fromLocation: { name: 'Synthetic office' }, toLocation: null, goodsReceipt: null };
const line = { debit: d(0), credit: d(1020), currency: 'IDR', account: { code: 'INV', name: 'Inventory' } };
const journal = { id: 'journal', entryNumber: 'JE-TEST', referenceId: 'movement', entryDate: now, status: 'POSTED', referenceType: 'STOCK_ADJUSTMENT', isAutoGenerated: true, lines: [line] };
function fixture() {
    const tx = { $executeRaw: vi.fn(), productVariant: { findUnique: vi.fn().mockResolvedValue(variant), findMany: vi.fn().mockResolvedValue([variant]) },
        inventory: { findMany: vi.fn().mockResolvedValue([inventory(10, 100)]) },
        account: { findMany: vi.fn().mockResolvedValue([{ id: 'inv', code: 'INV', name: 'Inventory' }]) },
        stockMovement: { count: vi.fn().mockResolvedValue(1), findMany: vi.fn().mockResolvedValue([movement]) },
        journalEntry: { findMany: vi.fn().mockResolvedValue([journal]) },
        atkCostCorrection: { findMany: vi.fn().mockResolvedValue([]) },
    };
    const transaction = vi.fn(async (fn: (client: typeof tx) => unknown) => fn(tx));
    const db = { $transaction: transaction } as unknown as PrismaClient;
    return { db, tx, transaction, inspect: () => inspectInventoryReconciliation(db, 'sku') };
}
beforeEach(() => { vi.resetAllMocks(); m.basis.mockResolvedValue(new Map([['inv', d(980)]])); });

describe('ATK reconciliation diagnosis', () => {
    it('uses one repeatable read-only snapshot and authoritative signed source basis, not a proposed correction', async () => {
        const f = fixture(); const result = await f.inspect();
        expect(f.tx.$executeRaw.mock.calls[0][0].join('')).toContain('SET TRANSACTION READ ONLY');
        expect(f.transaction).toHaveBeenCalledWith(expect.any(Function), expect.objectContaining({ isolationLevel: 'RepeatableRead', timeout: 20000 }));
        expect(m.basis).toHaveBeenCalledWith(f.tx, 'sku');
        expect(result).toMatchObject({ stockValue: '1000.0000', basisTotal: '980.00', difference: '20.0000', healthFlagged: true,
            locations: [{ averageCost: '100.0000', companyInternal: true }], movements: [{ cost: null, from: 'Synthetic office', receiptNumber: null }],
            journals: [{ status: 'POSTED', lines: [{ credit: '1020.00' }] }] });
        expect(result.findings.map(row => row.code)).toEqual(['BASIS_SHORTFALL']);
        expect(result).not.toHaveProperty('proposal'); expect(result).not.toHaveProperty('ready');
    });
    it('distinguishes null from zero without assuming intentional zero or historical cost', async () => {
        const f = fixture(); f.tx.inventory.findMany.mockResolvedValue([inventory(1, null), inventory(2, 0, 'other')]);
        m.basis.mockResolvedValue(new Map()); f.tx.account.findMany.mockResolvedValue([]);
        const result = await f.inspect();
        expect(result.healthFlagged).toBe(true); expect(result.locations.map(row => row.averageCost)).toEqual([null, '0.0000']);
        expect(result.findings.map(row => row.code)).toEqual(['UNKNOWN_COST', 'ZERO_COST', 'NO_LINKED_BASIS']);
    });
    it('shows negative basis and stock, split sources, custody and archived warnings without summing basis per location', async () => {
        const f = fixture(); f.tx.productVariant.findUnique.mockResolvedValue({ ...variant, archivedAt: now });
        f.tx.inventory.findMany.mockResolvedValue([inventory(10, 100), { ...inventory(-1, 100, 'customer'), location: { ...location, locationType: 'EXTERNAL', packagingOwnerCustomerId: 'private-id' } }]);
        m.basis.mockResolvedValue(new Map([['inv', d(700)], ['other', d(400)], ['negative', d(-120)]]));
        f.tx.account.findMany.mockResolvedValue(['inv', 'other', 'negative'].map(id => ({ id, code: id, name: id })));
        const result = await f.inspect();
        expect(result.stockValue).toBe('1000.0000'); expect(result.basisTotal).toBe('980.00');
        expect(result.findings.map(row => row.code)).toEqual(['ARCHIVED', 'NEGATIVE_VALUE', 'BASIS_SHORTFALL', 'SPLIT_BASIS', 'CUSTODY']);
        expect(result.basis.find(row => row.accountId === 'negative')?.value).toBe('-120.00');
        expect(JSON.stringify(result)).not.toContain('private-id');
    });
    it('applies the health tolerance without calling a matched total transaction-ready', async () => {
        const f = fixture(); m.basis.mockResolvedValue(new Map([['inv', d('999.50')]]));
        const result = await f.inspect(); expect(result.healthFlagged).toBe(false); expect(result.findings).toEqual([]);
        expect(result).not.toHaveProperty('ready');
        m.basis.mockResolvedValue(new Map([['inv', d(1002)]]));
        expect((await f.inspect()).findings.map(row => row.code)).toEqual(['BASIS_EXCESS']);
        f.tx.inventory.findMany.mockResolvedValue([]);
        expect((await f.inspect()).findings.map(row => row.code)).toContain('NO_POSITIVE_STOCK');
    });
    it('labels bounded evidence and never exports descriptions or users', async () => {
        const f = fixture(); f.tx.stockMovement.count.mockResolvedValue(101);
        f.tx.journalEntry.findMany.mockResolvedValue(Array.from({ length: 101 }, (_, i) => ({ ...journal, id: `j${i}`, description: 'private narrative', createdById: 'private actor', lines: Array.from({ length: 21 }, () => line) })));
        const result = await f.inspect();
        expect(result.coverage).toEqual({ movementCount: 101, movementsTruncated: true, journalsTruncated: true, correctionsTruncated: false });
        expect(result.journals).toHaveLength(100); expect(result.journals[0].lines).toHaveLength(20); expect(result.journals[0].linesTruncated).toBe(true);
        expect(JSON.stringify(result)).not.toContain('private');
        expect(f.tx.journalEntry.findMany).toHaveBeenCalledWith(expect.objectContaining({ where: { referenceId: { in: ['movement'] } }, take: 101 }));
    });
    it('fails closed for absent/nonoperational SKU, oversized location set and database errors', async () => {
        const f = fixture(); f.tx.productVariant.findUnique.mockResolvedValue(null);
        await expect(f.inspect()).rejects.toMatchObject({ code: 'NOT_FOUND' });
        f.tx.productVariant.findUnique.mockResolvedValue({ ...variant, product: { productType: 'RAW_MATERIAL' } });
        await expect(f.inspect()).rejects.toMatchObject({ code: 'NOT_FOUND' });
        f.tx.productVariant.findUnique.mockResolvedValue(variant); f.tx.inventory.findMany.mockResolvedValue(Array.from({ length: 201 }, () => inventory(1, 100)));
        await expect(f.inspect()).rejects.toThrow('melebihi batas');
        f.tx.inventory.findMany.mockRejectedValue(new Error('DB timeout'));
        await expect(f.inspect()).rejects.toThrow('DB timeout');
    });
    it('paginates a catalog rather than applying incomplete health filtering', async () => {
        const f = fixture(); f.tx.productVariant.findMany.mockResolvedValue(Array.from({ length: 21 }, (_, i) => ({ ...variant, id: `v${i}` })));
        const result = await listReconciliationCatalog(f.db, '', 2);
        expect(result.items).toHaveLength(20); expect(result.hasMore).toBe(true); expect(result.page).toBe(2);
        expect(f.tx.productVariant.findMany).toHaveBeenCalledWith(expect.objectContaining({ skip: 20, take: 21, where: expect.objectContaining({ inventories: { some: { quantity: { not: 0 } } } }) }));
        expect(m.basis).not.toHaveBeenCalled();
        f.tx.productVariant.findMany.mockResolvedValue([]);
        expect(await listReconciliationCatalog(f.db, 'needle', 1)).toEqual({ page: 1, hasMore: false, items: [] });
        expect(f.tx.productVariant.findMany.mock.calls[1][0].where).not.toHaveProperty('inventories');
    });
});
