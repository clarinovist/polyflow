async function ledgerQuantity(
    client: PrismaClient,
    locationId: string,
    productVariantId: string,
): Promise<Prisma.Decimal> {
    const [inbound, outbound] = await Promise.all([
        client.stockMovement.aggregate({
            where: { toLocationId: locationId, productVariantId },
            _sum: { quantity: true },
        }),
        client.stockMovement.aggregate({
            where: { fromLocationId: locationId, productVariantId },
            _sum: { quantity: true },
        }),
    ]);
    return (inbound._sum.quantity ?? new Prisma.Decimal(0)).minus(
        outbound._sum.quantity ?? new Prisma.Decimal(0),
    );
}

describe.skipIf(!db)('stock quantity rounding PostgreSQL contract', () => {
    beforeEach(async () => seed(db!));
    afterAll(async () => {
        await db?.$disconnect();
    });

    it('keeps Inventory.quantity equal to 1 - sum(movements) (0.8765) when deducting 0.12345 via deductStock', async () => {
        const today = toBusinessDateString(new Date());
        const outMovement = await run(db!, () =>
            db!.$transaction(async (tx) => {
                await InventoryCoreService.validateAndLockStock(
                    tx,
                    'round-source',
                    'round-sku',
                    0.12345,
                );
                await InventoryCoreService.deductStock(
                    tx,
                    'round-source',
                    'round-sku',
                    0.12345,
                );
                return tx.stockMovement.create({
                    data: {
                        type: MovementType.OUT,
                        productVariantId: 'round-sku',
                        fromLocationId: 'round-source',
                        toLocationId: null,
                        quantity: 0.12345,
                        cost: 1000,
                        reference: 'Synthetic half-way issue',
                        createdById: actor,
                    },
                });
            }),
        );

        expect(outMovement.quantity.toFixed(4)).toBe('0.1235');

        const live = await db!.inventory.findUniqueOrThrow({
            where: {
                locationId_productVariantId: {
                    locationId: 'round-source',
                    productVariantId: 'round-sku',
                },
            },
        });
        const ledger = await ledgerQuantity(db!, 'round-source', 'round-sku');

        expect(live.quantity.toFixed(4)).toBe('0.8765');
        expect(ledger.toFixed(4)).toBe('0.8765');
        expect(live.quantity.equals(ledger)).toBe(true);
        expect(
            evaluateFinalizationVariance({
                countedQuantity: live.quantity,
                cutoffQuantity: ledger,
                liveQuantity: live.quantity,
                ledgerQuantity: ledger,
            }).ledgerMismatch,
        ).toBe(false);

        const recap = await run(db!, () =>
            getStockBalance({
                startDate: today,
                endDate: today,
                locationId: 'round-source',
            }),
        );
        expect(recap.rows[0]).toMatchObject({
            totalIn: 1,
            totalOut: 0.1235,
            closingStock: 0.8765,
        });
    });

    it('keeps live stock equal to the stock ledger at both source and destination on half-way transfer', async () => {
        const today = toBusinessDateString(new Date());
        await run(db!, () =>
            InventoryMovementService.transferStock(
                {
                    sourceLocationId: 'round-source',
                    destinationLocationId: 'round-dest',
                    productVariantId: 'round-sku',
                    quantity: 0.12345,
                    notes: 'Synthetic half-way transfer',
                    date: new Date(),
                },
                actor,
            ),
        );

        const [sourceLive, destLive, sourceLedger, destLedger] =
            await Promise.all([
                db!.inventory.findUniqueOrThrow({
                    where: {
                        locationId_productVariantId: {
                            locationId: 'round-source',
                            productVariantId: 'round-sku',
                        },
                    },
                }),
                db!.inventory.findUniqueOrThrow({
                    where: {
                        locationId_productVariantId: {
                            locationId: 'round-dest',
                            productVariantId: 'round-sku',
                        },
                    },
                }),
                ledgerQuantity(db!, 'round-source', 'round-sku'),
                ledgerQuantity(db!, 'round-dest', 'round-sku'),
            ]);

        expect(sourceLive.quantity.toFixed(4)).toBe('0.8765');
        expect(sourceLedger.toFixed(4)).toBe('0.8765');
        expect(sourceLive.quantity.equals(sourceLedger)).toBe(true);

        expect(destLive.quantity.toFixed(4)).toBe('0.1235');
        expect(destLedger.toFixed(4)).toBe('0.1235');
        expect(destLive.quantity.equals(destLedger)).toBe(true);

        const [sourceRecap, destRecap] = await Promise.all([
            run(db!, () =>
                getStockBalance({
                    startDate: today,
                    endDate: today,
                    locationId: 'round-source',
                }),
            ),
            run(db!, () =>
                getStockBalance({
                    startDate: today,
                    endDate: today,
                    locationId: 'round-dest',
                }),
            ),
        ]);
        expect(sourceRecap.rows[0]).toMatchObject({
            totalIn: 1,
            totalOut: 0.1235,
            closingStock: 0.8765,
        });
        expect(destRecap.rows[0]).toMatchObject({
            totalIn: 0.1235,
            totalOut: 0,
            closingStock: 0.1235,
        });
    });

    it('keeps live stock equal to the stock ledger on outbound stock adjustment with a half-way quantity', async () => {
        await run(db!, () =>
            InventoryMovementService.adjustStock(
                {
                    locationId: 'round-source',
                    productVariantId: 'round-sku',
                    type: 'ADJUSTMENT_OUT',
                    quantity: 0.12345,
                    reason: 'Synthetic half-way adjustment out',
                },
                actor,
            ),
        );

        const live = await db!.inventory.findUniqueOrThrow({
            where: {
                locationId_productVariantId: {
                    locationId: 'round-source',
                    productVariantId: 'round-sku',
                },
            },
        });
        const ledger = await ledgerQuantity(db!, 'round-source', 'round-sku');

        expect(live.quantity.toFixed(4)).toBe('0.8765');
        expect(ledger.toFixed(4)).toBe('0.8765');
        expect(live.quantity.equals(ledger)).toBe(true);
    });
});
