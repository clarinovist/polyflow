import { describe, expect, it } from 'vitest';
import { proveAtkOvercharge } from '../atk-recovery-proof';
import { d, proofFixture } from './atk-recovery-fixture';
const check = (f: ReturnType<typeof proofFixture>) => proveAtkOvercharge(f.moves, f.journals, f.stock, 'loss');

describe('bounded ATK historical cost proof', () => {
    it('proves a 20 refund from 1020 original credit vs 1000 source cost without using the current gap', () => {
        const f = proofFixture(); const result = check(f);
        expect(result.amount.toString()).toBe('20'); expect(result.cost.toString()).toBe('100');
        expect(result.inventoryId).toBe('inv'); expect(result.lossAccountId).toBe('loss');
        f.moves[1].cost = d(999); expect(check(f).amount.toString()).toBe('20');
    });
    it.each([
        ['no history', (f: ReturnType<typeof proofFixture>) => { f.moves = []; }],
        ['too much history', f => { f.moves = Array.from({ length: 101 }, () => f.moves[0]); }],
        ['no source', f => { f.moves[1].id = 'different'; }],
        ['inbound source', f => { f.moves[1].toLocationId = 'office'; }],
        ['transfer', f => { f.moves[0].type = 'TRANSFER'; }],
        ['return', f => { f.moves[0].reversalOfId = 'old'; }],
        ['other location', f => { f.moves[0].toLocationId = 'other'; }],
        ['customer stock', f => { f.moves[0].companyOwned = false; }],
        ['unknown cost', f => { f.moves[0].cost = null; }],
        ['zero cost', f => { f.moves[0].cost = d(0); }],
        ['tied/backdated history', f => { f.moves[0].createdAt = f.moves[1].createdAt; }],
        ['WAC mismatch', f => { f.stock.averageCost = d(101); }],
        ['quantity mismatch', f => { f.stock.quantity = d(9); }],
        ['duplicate journal', f => { f.journals.push(f.journals[0]); }],
        ['missing source journal', f => { f.journals[1].referenceId = 'other'; }],
        ['manual journal', f => { f.journals[1].isAutoGenerated = false; }],
        ['voided journal', f => { f.journals[1].status = 'VOIDED'; }],
        ['unbalanced journal', f => { f.journals[1].lines[0].debit = d(1000); }],
        ['currency', f => { f.journals[0].lines[0].currency = 'USD'; }],
        ['inactive inventory', f => { f.journals[0].lines[0].account.isActive = false; }],
        ['cash inventory', f => { f.journals[0].lines[0].account.isCashAccount = true; }],
        ['wrong loss account', f => { f.journals[1].lines[0].account.type = 'ASSET'; }],
        ['wrong receipt amount', f => { f.journals[0].lines[0].debit = d(1900); f.journals[0].lines[1].credit = d(1900); }],
        ['undercharge', f => { f.journals[1].lines[0].debit = d(990); f.journals[1].lines[1].credit = d(990); }],
    ] as Array<[string, (f: ReturnType<typeof proofFixture>) => void]>)( 'rejects %s', (_name, mutate) => {
        const f = proofFixture(); mutate(f); expect(() => check(f)).toThrow();
    });
    it('does not infer variable cost from current WAC', () => {
        const f = proofFixture(); f.moves.splice(1, 0, { ...f.moves[0], id: 'second', cost: d(200) });
        expect(() => check(f)).toThrow('konstan');
    });
});
