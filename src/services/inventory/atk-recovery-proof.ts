import { Prisma } from '@prisma/client';
import { BusinessRuleError } from '@/lib/errors/errors';

export const ATK_RECOVERY_VERSION = 'constant-cost-refund-v1';
export function rejectAtk(
    message: string,
    code: 'ATK_RECOVERY_BLOCKED' | 'PURCHASE_PRICE_CORRECTED' = 'ATK_RECOVERY_BLOCKED',
): never {
    throw new BusinessRuleError(message, undefined, code);
}
export interface AtkProofMovement {
    id: string;
    type: string;
    quantity: Prisma.Decimal;
    cost: Prisma.Decimal | null;
    fromLocationId: string | null;
    toLocationId: string | null;
    createdAt: Date;
    salesOrderId: string | null;
    productionOrderId: string | null;
    productionExecutionId?: string | null;
    reversalOfId: string | null;
    companyOwned: boolean | null;
    packagingOwnerCustomerId: string | null;
}
export interface AtkProofJournal {
    id: string;
    referenceId: string | null;
    referenceType: string | null;
    status: string;
    isAutoGenerated: boolean;
    entryDate: Date;
    lines: Array<{
        accountId: string;
        debit: Prisma.Decimal;
        credit: Prisma.Decimal;
        currency: string;
        exchangeRate: Prisma.Decimal;
        account: {
            id: string;
            type: string;
            category: string;
            isActive: boolean;
            currency: string;
            isCashAccount: boolean;
        };
    }>;
}
/** Independent constant acquisition-cost proof. Current WAC only verifies consistency. */
export function proveAtkOvercharge(
    moves: AtkProofMovement[],
    journals: AtkProofJournal[],
    stock: {
        locationId: string;
        quantity: Prisma.Decimal;
        averageCost: Prisma.Decimal | null;
    },
    sourceId: string,
) {
    if (!moves.length || moves.length > 100)
        rejectAtk('Riwayat di luar batas koreksi terbatas.');
    const source = moves.find((m) => m.id === sourceId);
    if (
        !source ||
        source.type !== 'ADJUSTMENT' ||
        source.toLocationId ||
        source.fromLocationId !== stock.locationId ||
        !source.quantity.gt(0)
    )
        rejectAtk('Pilih satu mutasi penyesuaian keluar yang sah.');
    const receipts = moves.filter((m) => m.type === 'PURCHASE');
    if (!receipts.length || moves.length !== receipts.length + 1)
        rejectAtk(
            'Koreksi memerlukan penerimaan lengkap dan tepat satu loss, tanpa opening, transfer, atau pemakaian lain.',
        );
    const cost = receipts[0].cost;
    if (!cost?.gt(0)) rejectAtk('Harga penerimaan sumber tidak tersedia.');
    for (const m of moves) {
        if (
            m.salesOrderId ||
            m.productionOrderId ||
            m.productionExecutionId ||
            m.reversalOfId ||
            m.companyOwned === false ||
            m.packagingOwnerCustomerId ||
            !m.quantity.gt(0)
        )
            rejectAtk(
                'Sumber memiliki kepemilikan atau transaksi lain yang belum didukung.',
            );
    }
    for (const r of receipts) {
        if (
            r.fromLocationId ||
            r.toLocationId !== stock.locationId ||
            !r.cost?.eq(cost) ||
            r.createdAt >= source.createdAt
        )
            rejectAtk(
                'Biaya penerimaan harus konstan, satu lokasi, dan mendahului loss dengan urutan yang jelas.',
            );
    }
    const inputQty = receipts.reduce(
        (s, r) => s.plus(r.quantity),
        new Prisma.Decimal(0),
    );
    if (
        !inputQty.minus(source.quantity).eq(stock.quantity) ||
        stock.quantity.lt(0) ||
        !stock.averageCost?.eq(cost)
    )
        rejectAtk(
            'Riwayat sumber tidak cocok dengan stok/WAC saat ini. Jangan menebak biaya historis.',
        );
    if (journals.length !== moves.length)
        rejectAtk(
            'Jumlah jurnal sumber tidak tunggal atau memiliki koreksi lain.',
        );
    let inventoryId: string | undefined;
    let lossJournal: AtkProofJournal | undefined;
    let lossAccountId = '';
    let originalLoss = new Prisma.Decimal(0);
    for (const m of moves) {
        const candidates = journals.filter((j) => j.referenceId === m.id);
        if (candidates.length !== 1)
            rejectAtk('Satu mutasi harus memiliki tepat satu jurnal sumber.');
        const j = candidates[0];
        if (
            j.status !== 'POSTED' ||
            !j.isAutoGenerated ||
            j.referenceType !==
                (m.type === 'PURCHASE'
                    ? 'GOODS_RECEIPT'
                    : 'STOCK_ADJUSTMENT') ||
            j.lines.length !== 2
        )
            rejectAtk(
                'Jurnal sumber tidak memenuhi kontrak dua baris otomatis POSTED.',
            );
        const debit = j.lines.find((l) => l.debit.gt(0) && l.credit.isZero());
        const credit = j.lines.find((l) => l.credit.gt(0) && l.debit.isZero());
        if (
            !debit ||
            !credit ||
            debit.accountId === credit.accountId ||
            !debit.debit.eq(credit.credit) ||
            j.lines.some(
                (l) =>
                    l.currency !== 'IDR' ||
                    !l.exchangeRate.eq(1) ||
                    !l.account.isActive ||
                    l.account.currency !== 'IDR',
            )
        )
            rejectAtk(
                'Akun, mata uang atau keseimbangan jurnal sumber tidak valid.',
            );
        const inv = m.type === 'PURCHASE' ? debit : credit;
        if (
            inv.account.type !== 'ASSET' ||
            inv.account.category !== 'CURRENT_ASSET' ||
            inv.account.isCashAccount
        )
            rejectAtk('Akun sumber bukan persediaan yang memenuhi syarat.');
        if (inventoryId && inventoryId !== inv.accountId)
            rejectAtk(
                'Akun kapitalisasi sumber berbeda; perlu review Finance.',
            );
        inventoryId = inv.accountId;
        if (m.type === 'PURCHASE') {
            if (
                !debit.debit.eq(m.quantity.mul(cost).toDecimalPlaces(2)) ||
                credit.account.type !== 'LIABILITY'
            )
                rejectAtk(
                    'Nilai atau akun lawan penerimaan tidak cocok dengan biaya sumber.',
                );
        } else {
            if (
                debit.account.type !== 'EXPENSE' ||
                !['OPERATING_EXPENSE', 'OTHER_EXPENSE'].includes(
                    debit.account.category,
                )
            )
                rejectAtk('Akun lawan bukan beban loss yang didukung.');
            lossJournal = j;
            lossAccountId = debit.accountId;
            originalLoss = credit.credit;
        }
    }
    const expectedLoss = source.quantity.mul(cost).toDecimalPlaces(2);
    const amount = originalLoss.minus(expectedLoss);
    if (!expectedLoss.gt(0) || !amount.gt(0) || amount.gt('9999999999999.99'))
        rejectAtk('Tidak ada kelebihan pembebanan yang dapat dikembalikan.');
    return {
        source,
        sourceJournal: lossJournal!,
        inventoryId: inventoryId!,
        lossAccountId,
        cost,
        expectedLoss,
        originalLoss,
        amount,
    };
}
