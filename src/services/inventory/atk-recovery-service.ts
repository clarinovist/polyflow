export interface AtkBackup {
    ready(): boolean;
    save(snapshot: unknown, fingerprint: string): Promise<string>;
}
type Tx = Prisma.TransactionClient;
const hash = (value: unknown) =>
    createHash('sha256').update(JSON.stringify(value)).digest('hex');
const money = (value: Prisma.Decimal) => value.toFixed(2);
const receipt = (
    row: AtkCostCorrection,
    alreadyApplied: boolean,
): AtkRecoveryReceipt => ({
    id: row.id,
    kind: row.kind,
    journalId: row.journalId,
    amount: money(row.amount),
    postingDate: toBusinessDateString(row.postingDate),
    sourceMovementId: row.sourceMovementId,
    alreadyApplied,
});

async function evidence(
    tx: Tx,
    intent: AtkRecoveryIntent,
    postingDate: string,
) {
    const source = await tx.stockMovement.findUnique({
        where: { id: intent.sourceMovementId },
    });
    if (!source) rejectAtk('Mutasi sumber tidak ditemukan di ruang kerja ini.');
    const variant = await tx.productVariant.findUnique({
        where: { id: source.productVariantId },
        include: { product: true },
    });
    if (
        !variant ||
        variant.archivedAt ||
        variant.product.productType !== 'OPERATIONAL'
    )
        rejectAtk('SKU bukan barang operasional aktif.');
    const inventories = await tx.inventory.findMany({
        where: { productVariantId: variant.id },
        include: { location: true },
        orderBy: { id: 'asc' },
        take: 3,
    });
    if (
        inventories.length !== 1 ||
        inventories[0].location.locationType !== 'INTERNAL' ||
        inventories[0].location.packagingOwnerCustomerId
    )
        rejectAtk(
            'Koreksi v1 hanya mendukung satu lokasi internal milik perusahaan.',
        );
    const moves = await tx.stockMovement.findMany({
        where: { productVariantId: variant.id },
        orderBy: { id: 'asc' },
        take: 101,
    });
    const journals = await tx.journalEntry.findMany({
        where: { referenceId: { in: moves.map((m) => m.id) } },
        include: {
            lines: { include: { account: true }, orderBy: { id: 'asc' } },
        },
        orderBy: { id: 'asc' },
        take: 102,
    });
    const proof = proveAtkOvercharge(
        moves,
        journals,
        inventories[0],
        source.id,
    );
    // No unexplained direct/manual correction on the inventory account. Broad account
    // balance is never entitlement; unattributed legacy entries require assisted review.
    const [unexplained] = await tx.$queryRaw<Array<{ count: bigint }>>`
        SELECT count(DISTINCT j.id) AS count FROM "JournalEntry" j
        JOIN "JournalLine" l ON l."journalEntryId" = j.id
        WHERE j.status = 'POSTED' AND l."accountId" = ${proof.inventoryId}
          AND NOT EXISTS (SELECT 1 FROM "AtkCostCorrection" c WHERE c."journalId" = j.id AND c.id = j."referenceId")
          AND (NOT j."isAutoGenerated" OR NOT EXISTS (
            SELECT 1 FROM "StockMovement" m WHERE m.id = j."referenceId"
              AND j."referenceType"::text = CASE WHEN m.type = 'PURCHASE' THEN 'GOODS_RECEIPT'
                WHEN m.type = 'ADJUSTMENT' THEN 'STOCK_ADJUSTMENT' ELSE 'MANUAL_ENTRY' END))`;
    if (!unexplained || unexplained.count > 0)
        rejectAtk(
            'Akun sumber memiliki jurnal tanpa atribusi yang perlu diperiksa Finance.',
        );
    const [year, month] = postingDate.split('-').map(Number);
    const period = await tx.fiscalPeriod.findUnique({
        where: { year_month: { year, month } },
    });
    if (
        !period ||
        period.status !== 'OPEN' ||
        [source.createdAt, proof.sourceJournal.entryDate].some(
            (date) =>
                toBusinessDateString(date).slice(0, 7) !==
                postingDate.slice(0, 7),
        )
    )
        rejectAtk(
            'Sumber dan posting harus dalam periode yang sama dan masih OPEN.',
        );
    const corrections = await tx.atkCostCorrection.findMany({
        where: { sourceMovementId: source.id },
        include: {
            journal: { include: { lines: { orderBy: { id: 'asc' } } } },
        },
        orderBy: { id: 'asc' },
    });
    const refund = corrections.find((c) => c.kind === 'REFUND');
    if (intent.kind === 'REFUND' && corrections.length)
        rejectAtk(
            'Sumber sudah pernah dikoreksi; refund ulang tidak didukung.',
        );
    if (intent.kind === 'COMPENSATION') {
        if (
            !refund ||
            corrections.length !== 1 ||
            refund.journal.status !== 'POSTED' ||
            !refund.amount.eq(proof.amount)
        )
            rejectAtk(
                'Pembalikan tidak tersedia atau sudah pernah diterapkan.',
            );
        if (
            toBusinessDateString(refund.postingDate).slice(0, 7) !==
            postingDate.slice(0, 7)
        )
            rejectAtk('Pembalikan harus dalam periode refund yang masih OPEN.');
    }
    const snapshot = {
        version: ATK_RECOVERY_VERSION,
        variant,
        inventories,
        moves,
        journals,
        period,
        // Snapshot only ids/amounts for historical corrections; never nest backups recursively.
        corrections: corrections.map((c) => ({
            id: c.id,
            kind: c.kind,
            amount: c.amount,
            journal: c.journal,
        })),
    };
    if (refund && intent.kind === 'COMPENSATION') {
        const original = refund.evidenceSnapshot as unknown as {
            invariantHash?: string;
        };
        const invariantHash = hash({ variant, inventories, moves, journals });
        if (original.invariantHash !== invariantHash)
            rejectAtk(
                'Stok, sumber atau metadata berubah sejak refund. Pembalikan sederhana tidak aman.',
            );
    }
    const basis = await skuInventoryBasis(tx, variant.id);
    const totals = await tx.journalLine.aggregate({
        where: {
            accountId: proof.inventoryId,
            journalEntry: { status: 'POSTED' },
        },
        _sum: { debit: true, credit: true },
    });
    const gl = new Prisma.Decimal(totals._sum.debit ?? 0).minus(
        totals._sum.credit ?? 0,
    );
    if (
        intent.kind === 'COMPENSATION' &&
        ((basis.get(proof.inventoryId) ?? new Prisma.Decimal(0)).lt(
            proof.amount,
        ) ||
            gl.lt(proof.amount))
    )
        rejectAtk('Basis SKU atau saldo GL tidak cukup untuk membalik refund.');
    const fingerprint = hash({
        snapshot,
        intent: {
            sourceMovementId: intent.sourceMovementId,
            kind: intent.kind,
        },
        postingDate,
    });
    return {
        proof,
        snapshot,
        fingerprint,
        invariantHash: hash({ variant, inventories, moves, journals }),
        basis,
        gl,
        refund,
    };
}

export async function previewAtkRecovery(
    db: PrismaClient,
    intent: AtkRecoveryIntent,
    backup: AtkBackup,
): Promise<AtkRecoveryPreview> {
    return db.$transaction(
        async (tx) => {
            await tx.$executeRaw`SET TRANSACTION READ ONLY`;
            const existing = await tx.atkCostCorrection.findUnique({
                where: { sourceMovementId_kind: intent },
            });
            if (existing)
                return {
                    status: 'already_applied',
                    message: 'Tindakan pada sumber ini sudah tercatat.',
                    receipt: receipt(existing, true),
                };
            try {
                const postingDate = toBusinessDateString(new Date());
                const data = await evidence(tx, intent, postingDate);
                return {
                    status: 'eligible',
                    message:
                        'Koreksi terbatas terbukti. Kuantitas dan WAC tidak berubah.',
                    proposal: {
                        ...intent,
                        fingerprint: data.fingerprint,
                        postingDate,
                        amount: money(data.proof.amount),
                        originalLoss: money(data.proof.originalLoss),
                        expectedLoss: money(data.proof.expectedLoss),
                        unitCost: data.proof.cost.toFixed(4),
                        inventoryAccount: data.snapshot.journals
                            .find((j) => j.id === data.proof.sourceJournal.id)!
                            .lines.find(
                                (l) => l.accountId === data.proof.inventoryId,
                            )!.account.code,
                        lossAccount: data.snapshot.journals
                            .find((j) => j.id === data.proof.sourceJournal.id)!
                            .lines.find(
                                (l) => l.accountId === data.proof.lossAccountId,
                            )!.account.code,
                        backupReady: backup.ready(),
                    },
                };
            } catch (error) {
                if (
                    error instanceof ApplicationError &&
                    error.code === 'ATK_RECOVERY_BLOCKED'
                )
                    return { status: 'blocked', message: error.message };
                throw error;
            }
        },
        { isolationLevel: 'RepeatableRead', timeout: 20000 },
    );
}

export async function getAtkRecoveryReceipt(
    db: PrismaClient,
    requestId: string,
) {
    const row = await db.atkCostCorrection.findUnique({ where: { requestId } });
    return row ? receipt(row, true) : null;
}

export async function applyAtkRecovery(
    db: PrismaClient,
    input: AtkRecoveryApply,
    actorId: string,
    backup: AtkBackup,
): Promise<AtkRecoveryReceipt> {
    const parsed = atkRecoveryApplySchema.safeParse(input);
    if (!parsed.success)
        rejectAtk('Preview, alasan dan persetujuan koreksi tidak valid.');
    input = parsed.data;
    const requestHash = hash({ ...input, actorId });
    const prior = await db.atkCostCorrection.findUnique({
        where: { requestId: input.requestId },
    });
    if (prior) {
        if (prior.requestHash !== requestHash)
            rejectAtk('Request ID sudah dipakai untuk isian berbeda.');
        return receipt(prior, true);
    }
    if (!backup.ready()) rejectAtk('Cadangan pemulihan belum tersedia.');
    if (input.postingDate !== toBusinessDateString(new Date()))
        rejectAtk('Preview bukan tanggal hari ini. Periksa ulang.');
    const before = await db.$transaction(
        async (tx) => {
            await tx.$executeRaw`SET TRANSACTION READ ONLY`;
            return evidence(tx, input, input.postingDate);
        },
        { isolationLevel: 'RepeatableRead', timeout: 20000 },
    );
    if (before.fingerprint !== input.fingerprint)
        rejectAtk('Data berubah. Periksa ulang sebelum menerapkan.');
    const backupReference = await backup.save(
        before.snapshot,
        before.fingerprint,
    );
    try {
        return await db.$transaction(
            async (tx) => {
                // Exclusive, NOWAIT, short-lived recovery window also excludes readers that
                // could otherwise validate old GL/stock then write after compensation.
                await tx.$executeRaw`LOCK TABLE "FiscalPeriod", "Product", "ProductVariant", "Location", "Inventory", "StockMovement", "JournalEntry", "JournalLine", "Account", "SystemSequence", "AtkCostCorrection", "AtkCostEvidence" IN ACCESS EXCLUSIVE MODE NOWAIT`;
                await tx.$executeRaw`SET LOCAL statement_timeout = '4000ms'`;
                await tx.$queryRaw`SELECT id FROM "User" WHERE id = ${actorId} FOR SHARE`;
                await tx.$queryRaw`SELECT id FROM "UserRole" WHERE "userId" = ${actorId} FOR SHARE`;
                const existing = await tx.atkCostCorrection.findUnique({
                    where: { requestId: input.requestId },
                });
                if (existing) {
                    if (existing.requestHash !== requestHash)
                        rejectAtk(
                            'Request ID sudah dipakai untuk isian berbeda.',
                        );
                    return receipt(existing, true);
                }
                const actor = await tx.user.findUnique({
                    where: { id: actorId },
                    select: { isActive: true, role: true, roles: true },
                });
                if (
                    !actor?.isActive ||
                    !hasAnyRole(
                        {
                            role: actor.role,
                            roles: actor.roles.map((r) => r.role),
                        },
                        ['ADMIN', 'FINANCE'],
                    )
                )
                    rejectAtk('Petugas Finance aktif diperlukan.');
                if (input.postingDate !== toBusinessDateString(new Date()))
                    rejectAtk('Tanggal berubah saat backup. Periksa ulang.');
                const current = await evidence(tx, input, input.postingDate);
                if (current.fingerprint !== input.fingerprint)
                    rejectAtk(
                        'Data sumber berubah setelah preview. Tidak ada koreksi diterapkan.',
                    );
                const id = randomUUID(),
                    proof = current.proof;
                const reversing = input.kind === 'COMPENSATION';
                const journal = await createJournalEntry(
                    {
                        entryDate: normalizeToBusinessDay(input.postingDate),
                        description: `Koreksi nilai ATK ${input.kind}`,
                        reference: `ATK-CORRECTION:${id}`,
                        referenceId: id,
                        referenceType: 'STOCK_ADJUSTMENT',
                        status: 'POSTED',
                        isAutoGenerated: true,
                        createdById: actorId,
                        lines: [
                            {
                                accountId: proof.inventoryId,
                                debit: reversing ? 0 : proof.amount.toNumber(),
                                credit: reversing ? proof.amount.toNumber() : 0,
                            },
                            {
                                accountId: proof.lossAccountId,
                                debit: reversing ? proof.amount.toNumber() : 0,
                                credit: reversing ? 0 : proof.amount.toNumber(),
                            },
                        ],
                    },
                    tx,
                );
                const row = await tx.atkCostCorrection.create({
                    data: {
                        id,
                        kind: input.kind,
                        requestId: input.requestId,
                        requestHash,
                        sourceMovementId: proof.source.id,
                        sourceJournalId: proof.sourceJournal.id,
                        journalId: journal.id,
                        reversalOfId: reversing ? current.refund!.id : null,
                        amount: proof.amount,
                        historicalUnitCost: proof.cost,
                        expectedLoss: proof.expectedLoss,
                        originalLoss: proof.originalLoss,
                        fingerprint: input.fingerprint,
                        rulesVersion: ATK_RECOVERY_VERSION,
                        reason: input.reason,
                        actorId,
                        postingDate: normalizeToBusinessDay(input.postingDate),
                        backupReference,
                        evidenceSnapshot: JSON.parse(
                            JSON.stringify({
                                ...current.snapshot,
                                invariantHash: current.invariantHash,
                            }),
                        ),
                        evidence: {
                            create: current.snapshot.moves.map((m) => ({
                                id: randomUUID(),
                                movementId: m.id,
                                journalId: current.snapshot.journals.find(
                                    (j) => j.referenceId === m.id,
                                )!.id,
                            })),
                        },
                    },
                });
                const afterBasis = await skuInventoryBasis(
                    tx,
                    current.snapshot.variant.id,
                );
                const delta = reversing ? proof.amount.negated() : proof.amount;
                if (
                    !(
                        afterBasis.get(proof.inventoryId) ??
                        new Prisma.Decimal(0)
                    ).eq(
                        (
                            current.basis.get(proof.inventoryId) ??
                            new Prisma.Decimal(0)
                        ).plus(delta),
                    )
                )
                    rejectAtk('Verifikasi basis koreksi gagal.');
                const totals = await tx.journalLine.aggregate({
                    where: {
                        accountId: proof.inventoryId,
                        journalEntry: { status: 'POSTED' },
                    },
                    _sum: { debit: true, credit: true },
                });
                if (
                    !new Prisma.Decimal(totals._sum.debit ?? 0)
                        .minus(totals._sum.credit ?? 0)
                        .eq(current.gl.plus(delta))
                )
                    rejectAtk('Verifikasi saldo jurnal koreksi gagal.');
                const unchangedStock = await tx.inventory.findMany({
                    where: { productVariantId: current.snapshot.variant.id },
                    include: { location: true },
                    orderBy: { id: 'asc' },
                    take: 3,
                });
                if (hash(unchangedStock) !== hash(current.snapshot.inventories))
                    rejectAtk(
                        'Kuantitas atau WAC berubah; koreksi dibatalkan.',
                    );
                await logActivity({
                    userId: actorId,
                    action: `ATK_COST_${input.kind}`,
                    entityType: 'AtkCostCorrection',
                    entityId: id,
                    details: input.reason,
                    changes: {
                        amount: money(proof.amount),
                        sourceMovementId: proof.source.id,
                        journalId: journal.id,
                    },
                    tx,
                });
                return receipt(row, false);
            },
            { timeout: 5000, maxWait: 2000 },
        );
    } catch (error) {
        if (
            error instanceof Prisma.PrismaClientKnownRequestError &&
            (error.code === 'P2034' ||
                error.code === 'P2028' ||
                error.meta?.code === '55P03')
        )
            rejectAtk(
                'Transaksi lain sedang aktif. Periksa riwayat/receipt, lalu periksa ulang sebelum mencoba lagi.',
            );
        throw error;
    }
}
