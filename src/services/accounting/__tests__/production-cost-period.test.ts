import { describe, expect, it, vi } from 'vitest';
import { Prisma, type StockMovement } from '@prisma/client';
import { COST_PERIOD_ACTION, costPeriodHash, costPeriodSourceHash, forwardCostMovements, readCostPeriod, type PeriodJournal } from '../production-cost-period';
import { allocateProductionWip } from '../production-wip-provenance';
const d=(n:number)=>new Prisma.Decimal(n);
function setup() {
    const move=(id:string,type:'IN'|'OUT',cost:number|null)=>({id,type,productionOrderId:'wo',productVariantId:type==='OUT'?'raw':'fg',quantity:d(1),cost:cost===null?null:d(cost),createdAt:new Date('2026-01-01'),reference:id,reversalOfId:null,salesOrderId:null,goodsReceiptId:null,companyOwned:true} as StockMovement);
    const old=move('old','OUT',100),out=move('old-output','IN',80),scrap=move('old-scrap','IN',null),fresh=move('new-material','OUT',50);
    const journal=(m:StockMovement,value:number)=>({id:'j-'+m.id,referenceId:m.id,status:'POSTED',referenceType:'MANUAL_ENTRY',isAutoGenerated:true,lines:[{id:'d',accountId:m.type==='OUT'?'wip':'stock',debit:d(value),credit:d(0),currency:'IDR',exchangeRate:d(1),account:{type:'ASSET'}},{id:'c',accountId:m.type==='OUT'?'raw':'wip',debit:d(0),credit:d(value),currency:'IDR',exchangeRate:d(1),account:{type:'ASSET'}}]} as unknown as PeriodJournal);
    const ms=[old,out,scrap,fresh],js=[journal(old,100),journal(out,80),journal(fresh,50)],executions=[{id:'old-execution'}];
    const data={version:1,orderId:'wo',movementIds:ms.slice(0,3).map(m=>m.id),executionIds:['old-execution'],sourceHash:costPeriodSourceHash(ms.slice(0,3),js.slice(0,2)),executionHash:costPeriodHash(executions),historicalBalances:[{accountId:'wip',amount:'20.00'}],fingerprint:'a'.repeat(64),nullScrapCount:1};
    const db={$queryRaw:vi.fn(),auditLog:{findUnique:vi.fn().mockResolvedValue({action:COST_PERIOD_ACTION,entityType:'ProductionOrder',entityId:'wo',changes:data})},productionExecution:{findMany:vi.fn().mockResolvedValue(executions)},stockMovement:{findMany:vi.fn(async()=>ms)},journalEntry:{findMany:vi.fn(async()=>js),findFirst:vi.fn().mockResolvedValue(null)}};
    return {tx:db as unknown as Prisma.TransactionClient,db,ms,js,data,move};
}
describe('explicit forward-only production cost boundary',()=>{
    it('funds only new material and leaves old residual/NULL records untouched',async()=>{
        const f=setup(),before=costPeriodHash({m:f.ms,j:f.js});
        expect(await allocateProductionWip(f.tx,f.move('new-output','IN',50),d(50))).toEqual([{accountId:'wip',credit:d(50)}]);
        await expect(allocateProductionWip(f.tx,f.move('new-output','IN',70),d(70))).rejects.toThrow('tidak cukup');
        expect(costPeriodHash({m:f.ms,j:f.js})).toBe(before);
    });
    it('without explicit boundary still rejects NULL historic source',async()=>{
        const f=setup();f.db.auditLog.findUnique.mockResolvedValue(null);
        await expect(allocateProductionWip(f.tx,f.move('next','IN',1),d(1))).rejects.toThrow('jurnal sumber');
    });
    it.each(['movement','journal','deleted','execution','old reversal'])('rejects baseline drift: %s',async kind=>{
        const f=setup();
        if(kind==='movement')f.ms[0].quantity=d(2);
        if(kind==='journal')f.js[0].lines[0].debit=d(101);
        if(kind==='deleted')f.ms.shift();
        if(kind==='execution')f.db.productionExecution.findMany.mockResolvedValue([]);
        if(kind==='old reversal')f.ms.push({...f.move('reversal','IN',100),reversalOfId:'old'});
        await expect(forwardCostMovements(f.tx,'wo',f.ms,f.js)).rejects.toMatchObject({code:'PRODUCTION_COST_PERIOD_INVALID'});
    });
    it('never exempts new NULL or missing journal sources',async()=>{
        const f=setup();f.ms.push(f.move('bad-new','OUT',null));
        await expect(allocateProductionWip(f.tx,f.move('next','IN',1),d(1))).rejects.toThrow('jurnal sumber');
    });
    it('rejects invalid or wrong-order receipt',async()=>{
        const f=setup();f.db.auditLog.findUnique.mockResolvedValue({action:COST_PERIOD_ACTION,entityType:'ProductionOrder',entityId:'other',changes:f.data});
        await expect(readCostPeriod(f.tx,'wo')).rejects.toThrow('bukti');
    });
});
