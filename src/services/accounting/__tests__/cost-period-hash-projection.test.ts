const models = Object.keys(LEGACY_COST_PERIOD_FIELDS) as CostPeriodModel[];
const at = new Date('2026-10-28T01:02:03.456Z');
/** Receipt-era fixture keys: independent of production allowlists and future schema additions. */
const originalKeys = {
    StockMovement: 'id type productVariantId fromLocationId toLocationId quantity reference createdById createdAt batchId cost salesOrderId goodsReceiptId productionOrderId productionExecutionId reversalOfId companyOwned packagingOwnerCustomerId',
    JournalEntry: 'id entryNumber entryDate description reference referenceType referenceId status isAutoGenerated createdById approvedById approvedAt createdAt updatedAt',
    JournalLine: 'id journalEntryId accountId description debit credit currency exchangeRate createdAt reconciledAt',
    ProductionExecution: 'id clientRequestId requestHash productionOrderId machineId operatorId shiftId quantityProduced scrapQuantity enteredQuantity enteredUnit conversionFactorSnapshot bruto bobin cekGram startTime endTime notes photoUrl createdAt updatedAt status scrapDaunQty scrapProngkolQty pieceRateSnapshot pieceEarnings pieceMachineType',
    MaterialIssue: 'id productionOrderId productVariantId quantity status issuedAt createdById batchId locationId productionExecutionId stagedSourceId',
    ScrapRecord: 'id productionOrderId productionExecutionId productVariantId quantity reason recordedAt createdById locationId',
};
function row(model: CostPeriodModel): Record<string, unknown> {
    const fields = Prisma.dmmf.datamodel.models.find((m) => m.name === model)!.fields;
    return Object.fromEntries(originalKeys[model].split(' ').map((key) => {
        const f = fields.find((f) => f.name === key)!;
        return [
        f.name,
        f.type === 'Decimal' ? new Prisma.Decimal('123.4500')
            : f.type === 'DateTime' ? at
            : f.type === 'Boolean' ? true
            : f.kind === 'enum' ? Prisma.dmmf.datamodel.enums.find((e) => e.name === f.type)!.values[0].name
            : `${model}-${f.name}`,
        ];
    }));
}
/** Original algorithm: no call to projection code, including nested account rule. */
function originalSource(movements: StockMovement[], journals: PeriodJournal[]) {
    return costPeriodHash({
        movements: [...movements].sort((a, b) => a.id.localeCompare(b.id)),
        journals: [...journals].sort((a, b) => a.id.localeCompare(b.id)).map((j) => ({
            ...j,
            lines: [...j.lines].sort((a, b) => a.id.localeCompare(b.id)).map((l) => ({
                ...l, account: { id: l.accountId, type: l.account.type },
            })),
        })),
    });
}
function fixture(version: 1 | 2, hashVersion?: CostPeriodHashVersion) {
    const movement: Record<string, unknown> = { ...row('StockMovement'), productionOrderId: 'wo', reversalOfId: null };
    const line = { ...row('JournalLine'), account: { type: 'ASSET', name: 'Display name' } };
    const journal = { ...row('JournalEntry'), referenceId: movement.id, lines: [line] };
    const execution: Record<string, unknown> = { ...row('ProductionExecution'), productionOrderId: 'wo' };
    const material: Record<string, unknown> = { ...row('MaterialIssue'), productionOrderId: 'wo' };
    const scrap: Record<string, unknown> = { ...row('ScrapRecord'), productionOrderId: 'wo', reason: null };
    const movements = [movement] as unknown as StockMovement[];
    const journals = [journal] as unknown as PeriodJournal[];
    const executions = [execution], materialIssues = [material], scrapRecords = [scrap];
    const base = {
        version, ...(hashVersion ? { hashVersion } : {}), orderId: 'wo',
        movementIds: movements.map((m) => m.id), executionIds: [String(execution.id)],
        // Old evidence is minted with the old FULL-row algorithm, not the new helper.
        sourceHash: hashVersion ? costPeriodSourceHash(movements, journals, hashVersion) : originalSource(movements, journals),
        executionHash: hashVersion ? costPeriodExecutionHash(executions, hashVersion) : costPeriodHash(executions),
        historicalBalances: [{ accountId: 'wip', amount: '20.00' }],
        fingerprint: 'a'.repeat(64), nullScrapCount: 1,
    };
    const evidence = (version === 1 ? base : {
        ...base, mode: 'REVIEWED_LEGACY_SEAL', materialIssueIds: [material.id],
        scrapRecordIds: [scrap.id], anomalies: [], netOutput: '1', nonvoidOutput: '1',
        supportHash: hashVersion ? costPeriodSupportHash(materialIssues, scrapRecords, hashVersion) : costPeriodHash({ materialIssues, scrapRecords }),
    }) as CostPeriodEvidence;
    const db = {
        auditLog: { findUnique: vi.fn().mockResolvedValue({ action: COST_PERIOD_ACTION, entityType: 'ProductionOrder', entityId: 'wo', changes: evidence }) },
        productionExecution: { findMany: vi.fn().mockResolvedValue(executions) },
        materialIssue: { findMany: vi.fn().mockResolvedValue(materialIssues) },
        scrapRecord: { findMany: vi.fn().mockResolvedValue(scrapRecords) },
    };
    const records: Record<CostPeriodModel, Record<string, unknown>> = {
        StockMovement: movement, JournalEntry: journal, JournalLine: line,
        ProductionExecution: execution, MaterialIssue: material, ScrapRecord: scrap,
    };
    return { evidence, records, db, movements, journals,
        verify: () => forwardCostMovements(db as unknown as Prisma.TransactionClient, 'wo', movements, journals) };
}

describe('immutable cost seal projections', () => {
    it('freezes all 89 original scalar columns, including null/date/Decimal serialization', () => {
        for (const model of models) {
            const original = row(model);
            expect([...LEGACY_COST_PERIOD_FIELDS[model]].sort()).toEqual(Object.keys(original).sort());
            expect(costPeriodHash(projectCostPeriodRow(model, original))).toBe(costPeriodHash(original));
        }
        expect(models.reduce((sum, model) => sum + LEGACY_COST_PERIOD_FIELDS[model].length, 0)).toBe(89);
        expect(costPeriodHash({ at, amount: new Prisma.Decimal('123.4500'), empty: null }))
            .toBe(costPeriodHash({ at: at.toISOString(), amount: '123.45', empty: null }));
        // Explicit format decisions, not automatically regenerated from the schema.
        expect({ legacy: LEGACY_COST_PERIOD_FIELDS, COST_V1: COST_V1_FIELDS }).toMatchSnapshot();
    });

    it('pins original synthetic receipt hashes independently of future hash implementations', () => {
        const { evidence } = fixture(2);
        expect({ source: evidence.sourceHash, execution: evidence.executionHash,
            support: evidence.version === 2 ? evidence.supportHash : null }).toMatchInlineSnapshot(`
              {
                "execution": "cd58fd2c49b15296b70b2c2e62991ba8686160c824196fbc9acecc46a7be6fcb",
                "source": "7f41192689d5d8bc2cf3593c8bf6038296061db3d98d411aef5e56071a2d8e05",
                "support": "981faaa1c06f9386b9315ace9f606e27669a8479ab13897ad5d4cf628742fdbf",
              }
            `);
    });
    it('never falls back to another known format after a mismatch', async () => {
        const old = fixture(2), current = fixture(2, COST_PERIOD_HASH_VERSION);
        old.evidence.hashVersion = COST_PERIOD_HASH_VERSION;
        delete current.evidence.hashVersion;
        await expect(old.verify()).rejects.toThrow('sumber historis');
        await expect(current.verify()).rejects.toThrow('sumber historis');
    });

    for (const hashVersion of [undefined, COST_PERIOD_HASH_VERSION]) {
        describe(hashVersion ?? 'original full-row v1/v2 receipts', () => {
            it.each([1, 2] as const)('verifies receipt v%i after additive schema fields and relation includes', async (version) => {
                const f = fixture(version, hashVersion);
                await expect(f.verify()).resolves.toEqual([]);
                for (const record of Object.values(f.records)) {
                    record.futureNullable = null;
                    record.futureDefault = 'new';
                    record.futureRelation = { id: 'unrelated' };
                }
                await expect(f.verify()).resolves.toEqual([]);
            });
            it('detects mutation and deletion of EVERY protected field of all six models', async () => {
                const projection = hashVersion ? COST_V1_FIELDS : LEGACY_COST_PERIOD_FIELDS;
                for (const model of models) for (const field of projection[model]) {
                    for (const operation of ['change', 'delete']) {
                        const f = fixture(2, hashVersion);
                        if (operation === 'delete') delete f.records[model][field];
                        else f.records[model][field] = f.records[model][field] === null ? 'changed' : null;
                        await expect(f.verify(), `${model}.${field} ${operation}`).rejects.toThrow();
                    }
                }
            });
            it.each(['execution', 'material', 'scrap', 'journal', 'line', 'movement'])('rejects a missing %s row', async (kind) => {
                const f = fixture(2, hashVersion);
                if (kind === 'execution') f.db.productionExecution.findMany.mockResolvedValue([]);
                if (kind === 'material') f.db.materialIssue.findMany.mockResolvedValue([]);
                if (kind === 'scrap') f.db.scrapRecord.findMany.mockResolvedValue([]);
                if (kind === 'journal') f.journals.pop();
                if (kind === 'line') f.journals[0].lines.pop();
                if (kind === 'movement') f.movements.pop();
                await expect(f.verify()).rejects.toMatchObject({ code: 'PRODUCTION_COST_PERIOD_INVALID' });
            });
            it('rejects extra journals/lines, account reclassification and cross-boundary reversals', async () => {
                for (const kind of ['journal', 'line', 'account', 'reversal']) {
                    const f = fixture(2, hashVersion);
                    if (kind === 'journal') f.journals.push({ ...f.journals[0], id: 'extra' });
                    if (kind === 'line') f.journals[0].lines.push({ ...f.journals[0].lines[0], id: 'extra' });
                    if (kind === 'account') f.journals[0].lines[0].account.type = 'EXPENSE';
                    if (kind === 'reversal') f.movements.push({ ...f.movements[0], id: 'new', reversalOfId: f.movements[0].id });
                    await expect(f.verify()).rejects.toMatchObject({ code: 'PRODUCTION_COST_PERIOD_INVALID' });
                }
            });
        });
    }
    it('excludes only explicitly reviewed metadata for new receipts, never for old ones', async () => {
        for (const model of models) {
            const excluded = LEGACY_COST_PERIOD_FIELDS[model].filter((key) => !(COST_V1_FIELDS[model] as readonly string[]).includes(key));
            for (const key of excluded) {
                const current = fixture(2, COST_PERIOD_HASH_VERSION), old = fixture(2);
                current.records[model][key] = 'changed metadata';
                old.records[model][key] = 'changed metadata';
                await expect(current.verify()).resolves.toEqual([]);
                await expect(old.verify()).rejects.toThrow();
            }
        }
    });
    it('keeps journal/line ordering and account labels outside source identity', () => {
        const f = fixture(2);
        f.movements.push({ ...f.movements[0], id: 'a' });
        f.journals.push({ ...f.journals[0], id: 'a', lines: [...f.journals[0].lines] });
        f.journals[0].lines.push({ ...f.journals[0].lines[0], id: 'a' });
        const expected = costPeriodSourceHash(f.movements, f.journals);
        f.journals[0].lines[0].account.name = 'Renamed';
        f.journals[0].lines.reverse();
        expect(costPeriodSourceHash([...f.movements].reverse(), [...f.journals].reverse())).toBe(expected);
    });
    it.each([null, '', 1, 'COST_V2', 'LEGACY'])('fails closed on unknown hashVersion %j', async (hashVersion) => {
        const f = fixture(2);
        Object.assign(f.evidence, { hashVersion });
        await expect(readCostPeriod(f.db as unknown as Prisma.TransactionClient, 'wo')).rejects.toMatchObject({ code: 'PRODUCTION_COST_PERIOD_INVALID' });
        expect(() => projectCostPeriodRow('StockMovement', {}, hashVersion as never)).toThrow();
    });
});

/** Read the checked-in schema, NOT DMMF: stale generated clients must not hide drift. */
function schemaContract(schema: string) {
    const blocks = [...schema.matchAll(/^(model|enum) (\w+) \{([\s\S]*?)^\}/gm)];
    const enums = blocks.filter((b) => b[1] === 'enum');
    const selected = blocks.filter((b) => b[1] === 'model' && models.includes(b[2] as CostPeriodModel));
    if (selected.length !== 6) throw new Error('Missing cost-sealed model');
    const enumNames = enums.filter((e) => selected.some((m) => new RegExp(`\\b${e[2]}[?\\s]`).test(m[3])) || e[2] === 'AccountType').map((e) => e[2]);
    return Object.fromEntries([...selected, ...enums.filter((e) => enumNames.includes(e[2]))].map((b) => [
        b[2], b[3].split('\n').map((line) => line.replace(/\/\/.*$/, '').trim().replace(/\s+/g, ' ')).filter(Boolean),
    ]));
}

describe('schema changes require an explicit cost hash projection decision', () => {
    const schema = readFileSync('prisma/schema.prisma', 'utf8');
    it('pins six entire model contracts and their enums; review the decision doc before updating', () => {
        expect(schemaContract(schema)).toMatchSnapshot();
    });
    it.each(models)('detects added, removed, changed and nullable columns in %s even with stale Prisma generation', (model) => {
        const contract = schemaContract(schema);
        const block = schema.match(new RegExp(`model ${model} \\{[\\s\\S]*?^\\}`, 'm'))![0];
        const idLine = /^\s+id\s+String[^\n]*/m;
        for (const changed of [
            block.replace('{', '{\n  futureCost Decimal?'),
            block.replace(idLine, '\n  id String? @id'),
            block.replace(idLine, '\n  id Int @id'),
            block.replace(idLine, ''),
            block.replace('@db.Decimal(15, 4)', '@db.Decimal(16, 4)').replace('@db.Decimal(15, 2)', '@db.Decimal(16, 2)').replace('entryDate                 DateTime', 'entryDate                 DateTime?'),
        ]) {
            expect(schemaContract(schema.replace(block, changed))).not.toEqual(contract);
        }
        // A model removal must fail closed, not shrink the contract silently.
        expect(() => schemaContract(schema.replace(`model ${model} {`, 'model Removed {'))).toThrow();
    });
});
