import { beforeEach, describe, expect, it, vi } from 'vitest';
import { Prisma, type StockMovement } from '@prisma/client';
import { reverseProductionMovementJournal } from '../production-movement-reversal';
import { logActivity } from '@/lib/tools/audit';
import { requireOpenJournalPeriod } from '@/services/finance/sales-recognition-service';
vi.mock('../journal-posting', () => ({ generateEntryNumber: vi.fn(async () => 'JE-NEW') }));
vi.mock('@/lib/tools/audit', () => ({ logActivity: vi.fn() }));
vi.mock('@/services/finance/sales-recognition-service', () => ({ requireOpenJournalPeriod: vi.fn() }));
const d = (n: Prisma.Decimal.Value) => new Prisma.Decimal(n);
const original: StockMovement = {
    id: 'source', type: 'OUT', productVariantId: 'raw', productionOrderId: 'wo',
    fromLocationId: 'warehouse', toLocationId: null, quantity: d(2), cost: d('12.34'),
    reference: 'Backflush', createdAt: new Date(), createdById: 'actor',
    salesOrderId: null, goodsReceiptId: null, productionExecutionId: null, reversalOfId: null,
    companyOwned: null, packagingOwnerCustomerId: null, batchId: null,
};
const reversed: StockMovement = { ...original, id: 'reversal', type: 'IN', reversalOfId: original.id,
    fromLocationId: null, toLocationId: 'warehouse', reference: 'VOID: Backflush' };
const line = (accountId: string, debit: string, credit: string) => ({ accountId,
    debit: d(debit), credit: d(credit), currency: 'IDR', exchangeRate: d(1), description: 'Source' });
const source = () => ({ id: 'journal-source', entryNumber: 'JE-SOURCE', status: 'POSTED',
    isAutoGenerated: true, referenceType: 'MANUAL_ENTRY', referenceId: 'source',
    lines: [line('historical-wip', '24.68', '0'), line('historical-stock', '0', '24.68')] });
const db = {
    $queryRaw: vi.fn(), journalEntry: { findMany: vi.fn(), findFirst: vi.fn(), create: vi.fn() },
    productionOrder: { findUniqueOrThrow: vi.fn() }, account: { findUniqueOrThrow: vi.fn() },
    journalLine: { aggregate: vi.fn() },
};
const tx = db as unknown as Prisma.TransactionClient;
const run = (o = original, r = reversed) => reverseProductionMovementJournal(tx, o, r, 'actor');
describe('reverseProductionMovementJournal', () => {
    beforeEach(() => {
        vi.resetAllMocks();
        db.journalEntry.findMany.mockResolvedValue([source()]);
        db.journalEntry.findFirst.mockResolvedValue(null);
        db.journalEntry.create.mockResolvedValue({ id: 'new' });
        db.productionOrder.findUniqueOrThrow.mockResolvedValue({ isMaklon: false });
        db.account.findUniqueOrThrow.mockResolvedValue({ type: 'ASSET' });
        db.journalLine.aggregate.mockResolvedValue({ _sum: { debit: d(100), credit: d(0) } });
    });
    it('inverts original accounts and cents and audits inside the same transaction', async () => {
        await run();
        const posted = db.journalEntry.create.mock.calls[0][0].data;
        expect(posted.referenceId).toBe(reversed.id);
        expect(posted.lines.create).toEqual(source().lines.map(l => ({ ...l,
            debit: l.credit, credit: l.debit, description: 'Reversal JE-SOURCE: Source' })));
        expect(logActivity).toHaveBeenCalledWith(expect.objectContaining({ tx, action: 'REVERSE_PRODUCTION_JOURNAL',
            changes: { originalJournalId: 'journal-source', originalMovementId: 'source', reversalMovementId: 'reversal' } }));
    });
    it('preserves currency and rate from historical journal', async () => {
        const j = source(); j.lines.forEach(l => { l.currency = 'USD'; l.exchangeRate = d('16000.123456'); });
        db.journalEntry.findMany.mockResolvedValue([j]); await run();
        expect(db.journalEntry.create.mock.calls[0][0].data.lines.create[0].exchangeRate).toEqual(d('16000.123456'));
    });
    it('rejects insufficient source balance before creating journal or audit', async () => {
        db.journalLine.aggregate.mockResolvedValue({ _sum: { debit: d(1), credit: d(0) } });
        await expect(run()).rejects.toThrow('Saldo akun sumber');
        expect(db.journalEntry.create).not.toHaveBeenCalled(); expect(logActivity).not.toHaveBeenCalled();
    });
    it('validates net inverse movement when inventory and WIP share an account', async () => {
        const j = source(); j.lines[1].accountId = 'historical-wip';
        db.journalEntry.findMany.mockResolvedValue([j]);
        db.journalLine.aggregate.mockResolvedValue({ _sum: { debit: null, credit: null } });
        await run(); expect(db.journalLine.aggregate).not.toHaveBeenCalled();
    });
    it('rejects closed period and existing reversal', async () => {
        vi.mocked(requireOpenJournalPeriod).mockRejectedValueOnce(new Error('closed'));
        await expect(run()).rejects.toThrow('closed');
        db.journalEntry.findFirst.mockResolvedValue({ id: 'existing' });
        await expect(run()).rejects.toThrow('sudah ada');
    });
    it('rejects absent, ambiguous, manually-created and non-posted source journals', async () => {
        for (const js of [[], [source(), source()], [{ ...source(), status: 'DRAFT' }], [{ ...source(), status: 'VOIDED' }], [{ ...source(), isAutoGenerated: false }]]) {
            db.journalEntry.findMany.mockResolvedValue(js); await expect(run()).rejects.toThrow('sumber produksi');
        }
    });
    it('only permits absent journals for evidenced zero cost or maklon', async () => {
        db.journalEntry.findMany.mockResolvedValue([]);
        await run({ ...original, cost: d(0) }, { ...reversed, cost: d(0) });
        db.productionOrder.findUniqueOrThrow.mockResolvedValue({ isMaklon: true }); await run();
        await expect(run({ ...original, companyOwned: true })).rejects.toThrow('hilang');
        expect(db.journalEntry.create).not.toHaveBeenCalled();
    });
    it('rejects invalid vectors and does not fall back to current mapping', async () => {
        for (const lines of [[], [line('wip', '25', '0'), line('stock', '0', '24')],
            [line('wip', '-1', '0'), line('stock', '0', '-1')]]) {
            db.journalEntry.findMany.mockResolvedValue([{ ...source(), lines }]); await expect(run()).rejects.toThrow('produksi');
        }
    });
    it('propagates audit failure to transaction caller', async () => {
        vi.mocked(logActivity).mockRejectedValueOnce(new Error('audit unavailable'));
        await expect(run()).rejects.toThrow('audit unavailable');
    });
    it('rejects mismatched source pair and recursive reversals', async () => {
        for (const changes of [{ reversalOfId: null }, { quantity: d(1) }, { cost: d(1) },
            { productionOrderId: 'foreign' }, { productVariantId: 'foreign' }, { toLocationId: 'foreign' },
            { salesOrderId: 'sales' }, { type: 'OUT' as const }]) {
            await expect(run(original, { ...reversed, ...changes })).rejects.toThrow('Pasangan');
        }
        await expect(run({ ...original, reversalOfId: 'prior' })).rejects.toThrow('Pasangan');
    });
});
