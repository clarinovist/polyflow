async function issue(tx: Prisma.TransactionClient, value = 100, wo = 'wo') {
    const movement = await tx.stockMovement.create({ data: {
        type: 'OUT', productVariantId: 'raw', productionOrderId: wo, fromLocationId: 'loc', quantity: 10, cost: value / 10, createdAt: at, reference: 'Synthetic issue',
    } });
    await recordInventoryMovement(movement, tx); return movement;
}
async function output(tx: Prisma.TransactionClient, value = 100, wo = 'wo') {
    const movement = await tx.stockMovement.create({ data: {
        type: 'IN', productVariantId: 'output', productionOrderId: wo, toLocationId: 'loc', quantity: 10, cost: value / 10, createdAt: at, reference: 'Synthetic output',
    } });
    await recordInventoryMovement(movement, tx, { productionOutput: true }); return movement;
}
const run = <T>(client: PrismaClient, fn: (tx: Prisma.TransactionClient) => Promise<T>) =>
    tenantContext.run(client, () => client.$transaction(fn, { timeout: 20000 }));
async function balance(client: PrismaClient, accountId: string) {
    const s = await client.journalLine.aggregate({ where: { accountId, journalEntry: { status: 'POSTED' } }, _sum: { debit: true, credit: true } });
    return d(s._sum.debit ?? 0).minus(s._sum.credit ?? 0).toNumber();
}

