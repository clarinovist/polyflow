const connection = process.env.RETURN_CREDIT_TEST_DATABASE_URL;
const db = connection ? returnTestClient(connection) : null;
const otherUrl = connection ? new URL(connection) : null;
if (otherUrl) otherUrl.pathname = '/polyflow_return_credit_tenant_test';
const other = otherUrl ? returnTestClient(otherUrl.toString()) : null;
const ids = new Map<PrismaClient, { raw: string; wip: string; legacy: string; output: string }>();
const d = (value: Prisma.Decimal.Value) => new Prisma.Decimal(value);
const at = new Date('2026-01-15T03:00:00Z');
async function seed(client: PrismaClient) {
    await verifyReturnTestDatabase(client);
    await client.$executeRaw`TRUNCATE "Product", "Location", "User", "Account", "JournalEntry", "FiscalPeriod", "SystemSequence" CASCADE`;
    const a = { raw: randomUUID(), wip: randomUUID(), legacy: randomUUID(), output: randomUUID() };
    ids.set(client, a);
    await client.user.create({ data: { id: 'actor', email: 'wip@example.invalid', password: 'synthetic-only', role: 'PRODUCTION' } });
    await client.account.createMany({ data: [
        { id: a.raw, code: '11310', name: 'Raw', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: a.wip, code: '11320', name: 'WIP', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: a.legacy, code: '12400', name: 'Retired WIP', type: 'ASSET', category: 'CURRENT_ASSET', isActive: false },
        { id: a.output, code: '11325', name: 'Intermediate', type: 'ASSET', category: 'CURRENT_ASSET' },
        { id: 'equity', code: '32000', name: 'Equity', type: 'EQUITY', category: 'CAPITAL' },
    ] });
    await client.location.create({ data: { id: 'loc', name: 'Synthetic', slug: 'synthetic' } });
    await client.product.createMany({ data: [
        { id: 'raw', name: 'Synthetic raw', productType: 'RAW_MATERIAL', inventoryAccountId: a.raw, wipAccountId: a.legacy },
        { id: 'output', name: 'Synthetic output', productType: 'INTERMEDIATE' },
    ] });
    for (const id of ['raw', 'output']) await client.productVariant.create({ data: { id, productId: id, name: id, skuCode: id, primaryUnit: 'KG', standardCost: 10 } });
    await client.bom.create({ data: { id: 'bom', name: 'Synthetic', productVariantId: 'output', category: 'MIXING' } });
    for (const id of ['wo', 'other-wo']) await client.productionOrder.create({ data: {
        id, orderNumber: id, bomId: 'bom', locationId: 'loc', plannedQuantity: 100, actualQuantity: 0, plannedStartDate: at, status: 'IN_PROGRESS',
    } });
    await client.fiscalPeriod.create({ data: { name: 'Synthetic', year: 2026, month: 1, startDate: new Date('2026-01-01'), endDate: new Date('2026-02-01'), status: 'OPEN' } });
    const now = new Date();
    if (now.getUTCFullYear() !== 2026 || now.getUTCMonth() !== 0) await client.fiscalPeriod.create({ data: {
        name: 'Current', year: now.getUTCFullYear(), month: now.getUTCMonth() + 1,
        startDate: new Date(now.getUTCFullYear(), now.getUTCMonth(), 1), endDate: new Date(now.getUTCFullYear(), now.getUTCMonth() + 1, 1), status: 'OPEN',
    } });
    await client.journalEntry.create({ data: { entryNumber: 'OPENING', entryDate: at, status: 'POSTED', description: 'Synthetic opening', isAutoGenerated: true,
        lines: { create: [{ accountId: a.raw, debit: 10000 }, { accountId: a.wip, debit: 10 }, { accountId: 'equity', credit: 10010 }] },
    } });
}
async function issue(tx: Prisma.TransactionClient, value = 100, wo = 'wo') {
    const movement = await tx.stockMovement.create({ data: {
        type: 'OUT', productVariantId: 'raw', productionOrderId: wo, fromLocationId: 'loc', quantity: 10, cost: value / 10, createdAt: at, reference: 'Synthetic issue',
    } });
    await recordInventoryMovement(movement, tx); return movement;
}
async function output(tx: Prisma.TransactionClient, value = 100, wo = 'wo') {
    const movement = await tx.stockMovement.create({ data: {
        type: 'IN', productVariantId: 'output', productionOrderId: wo, toLocationId: 'loc', quantity: 10, cost: value / 10, createdAt: at, reference: 'Synthetic output',
    } });
    await recordInventoryMovement(movement, tx, { productionOutput: true }); return movement;
}
const run = <T>(client: PrismaClient, fn: (tx: Prisma.TransactionClient) => Promise<T>) =>
    tenantContext.run(client, () => client.$transaction(fn, { timeout: 20000 }));
async function balance(client: PrismaClient, accountId: string) {
    const s = await client.journalLine.aggregate({ where: { accountId, journalEntry: { status: 'POSTED' } }, _sum: { debit: true, credit: true } });
    return d(s._sum.debit ?? 0).minus(s._sum.credit ?? 0).toNumber();
}

describe.skipIf(!db)('production WIP PostgreSQL contracts', () => {
    beforeEach(async () => { await seed(db!); });
    afterAll(async () => { await Promise.all([db?.$disconnect(), other?.$disconnect()]); });
    it('posts split-mapping output using historical source WIP, then reverses exact accounts after mapping change', async () => {
        const movements = await run(db!, async tx => ({ issue: await issue(tx), output: await output(tx) }));
        const a = ids.get(db!)!;
        expect(await balance(db!, a.legacy)).toBe(0); expect(await balance(db!, a.output)).toBe(100);
        await db!.product.update({ where: { id: 'raw' }, data: { wipAccountId: a.wip } });
        await run(db!, async tx => {
            for (const original of [movements.output, movements.issue]) {
                const reversal = await tx.stockMovement.create({ data: {
                    type: original.type === 'IN' ? 'OUT' : 'IN', productVariantId: original.productVariantId,
                    productionOrderId: 'wo', reversalOfId: original.id, quantity: original.quantity, cost: original.cost,
                    fromLocationId: original.toLocationId, toLocationId: original.fromLocationId, reference: `VOID: ${original.reference}`,
                } });
                await reverseProductionMovementJournal(tx, original, reversal, 'actor');
            }
        });
        expect(await balance(db!, a.raw)).toBe(10000); expect(await balance(db!, a.legacy)).toBe(0);
        expect(await balance(db!, a.wip)).toBe(10); expect(await balance(db!, a.output)).toBe(0);
        expect(await db!.auditLog.count({ where: { action: 'REVERSE_PRODUCTION_JOURNAL' } })).toBe(2);
    });
    it('persists exact output cents, replays unchanged and reverses the original monetary vector', async () => {
        const a = ids.get(db!)!;
        await db!.journalLine.updateMany({ where: { accountId: a.raw }, data: { debit: 10000000 } });
        await db!.journalLine.updateMany({ where: { accountId: 'equity' }, data: { credit: 10000010 } });
        const original = await run(db!, async tx => {
            for (const [quantity, cost] of [[350, 3570.1728], [350, 11818.1818], [11, 21080.2253]]) {
                const material = await tx.stockMovement.create({ data: {
                    type: 'OUT', productVariantId: 'raw', productionOrderId: 'wo', fromLocationId: 'loc', quantity, cost, reference: 'Synthetic issue',
                } });
                await recordInventoryMovement(material, tx);
            }
            const order = await tx.productionOrder.update({ where: { id: 'wo' }, data: { actualQuantity: 711 }, include: { bom: true } });
            await recordFinishedGoodsOutput({ tx, productionOrderId: 'wo', order: order as unknown as ProductionExecutionOrder,
                quantityProduced: 711, reference: 'Synthetic exact output' });
            return tx.stockMovement.findFirstOrThrow({ where: { productionOrderId: 'wo', type: 'IN' } });
        });
        expect(original.cost?.toString()).toBe('7901.2751');
        expect(await balance(db!, a.output)).toBe(5617806.59);
        expect(await balance(db!, a.legacy)).toBe(0);
        await run(db!, tx => recordInventoryMovement(original, tx, { productionOutput: true }));
        expect(await db!.journalEntry.count({ where: { referenceId: original.id } })).toBe(1);
        expect(await balance(db!, a.output)).toBe(5617806.59);
        await run(db!, async tx => {
            const reversal = await tx.stockMovement.create({ data: {
                type: 'OUT', productVariantId: 'output', productionOrderId: 'wo', fromLocationId: 'loc',
                quantity: original.quantity, cost: original.cost, reversalOfId: original.id, reference: 'VOID: Synthetic exact output',
            } });
            await reverseProductionMovementJournal(tx, original, reversal, 'actor');
        });
        expect(await balance(db!, a.output)).toBe(0);
        expect(await balance(db!, a.legacy)).toBe(5617806.59);
    });
    it('keeps partial outputs funded when the same material price has fractional cents', async () => {
        for (const quantity of [6.71, 62.1, 27.76, 74.06, 69.24]) {
            await run(db!, async tx => {
                const material = await tx.stockMovement.create({ data: {
                    type: 'OUT', productVariantId: 'raw', productionOrderId: 'wo', fromLocationId: 'loc', quantity, cost: 14.5299,
                } });
                await recordInventoryMovement(material, tx);
                const order = await tx.productionOrder.update({ where: { id: 'wo' },
                    data: { actualQuantity: { increment: quantity } }, include: { bom: true } });
                await recordFinishedGoodsOutput({ tx, productionOrderId: 'wo', order: order as unknown as ProductionExecutionOrder,
                    quantityProduced: quantity, reference: 'Synthetic partial' });
            });
            expect(await balance(db!, ids.get(db!)!.legacy)).toBe(0);
        }
    });
    it('does not borrow another WO funds and rolls back a rejected movement', async () => {
        await run(db!, tx => issue(tx, 100, 'other-wo'));
        await expect(run(db!, tx => output(tx))).rejects.toThrow('tidak cukup');
        expect(await db!.stockMovement.count({ where: { productionOrderId: 'wo' } })).toBe(0);
    });
    it('serializes concurrent output claims so only one consumes the same WIP', async () => {
        await run(db!, tx => issue(tx));
        const claim = () => run(db!, async tx => {
            // Match the real pipeline: the WO header update precedes movement creation.
            await tx.productionOrder.update({ where: { id: 'wo' }, data: { actualQuantity: { increment: 10 } } });
            return output(tx);
        });
        const results = await Promise.allSettled([claim(), claim()]);
        expect(results.filter(r => r.status === 'fulfilled')).toHaveLength(1);
        expect(await db!.stockMovement.count({ where: { type: 'IN' } })).toBe(1);
        expect(await balance(db!, ids.get(db!)!.legacy)).toBe(0);
    });
    it('rolls back source reversal and audit together on failure', async () => {
        const original = await run(db!, tx => issue(tx));
        await expect(run(db!, async tx => {
            const reversal = await tx.stockMovement.create({ data: { type: 'IN', productVariantId: 'raw', productionOrderId: 'wo',
                reversalOfId: original.id, toLocationId: 'loc', quantity: original.quantity, cost: original.cost, reference: 'VOID: source' } });
            await reverseProductionMovementJournal(tx, original, reversal, 'actor');
            throw new Error('forced rollback');
        })).rejects.toThrow('forced rollback');
        expect(await db!.auditLog.count()).toBe(0);
        expect(await db!.stockMovement.count()).toBe(1);
    });
    it('preserves cumulative COGM and rejects underfunded cutover rather than lowering cost', async () => {
        await run(db!, async tx => {
            await issue(tx, 500); await output(tx, 500);
            await tx.productionOrder.update({ where: { id: 'wo' }, data: { actualQuantity: 10 } });
        });
        await db!.product.update({ where: { id: 'raw' }, data: { wipAccountId: ids.get(db!)!.wip } });
        await expect(run(db!, async tx => {
            await issue(tx, 250); await tx.productionOrder.update({ where: { id: 'wo' }, data: { actualQuantity: 20 } });
            const cost = await ProductionCostService.calculateBatchCOGM('wo', tx);
            expect(cost).toBe(37.5); await output(tx, cost * 10);
        })).rejects.toThrow('tidak cukup');
        expect(await db!.stockMovement.count()).toBe(2);
    });
    it('resolves same account codes independently across two databases with different UUIDs', async () => {
        await seed(other!);
        for (const client of [db!, other!, db!]) {
            await client.product.update({ where: { id: 'raw' }, data: { inventoryAccountId: null, wipAccountId: null } });
            await run(client, tx => issue(tx));
        }
        expect(await balance(db!, ids.get(db!)!.wip)).toBe(210);
        expect(await balance(other!, ids.get(other!)!.wip)).toBe(110);
    });
});
