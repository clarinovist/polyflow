import { Prisma, type StockMovement } from '@prisma/client';
import { BusinessRuleError } from '@/lib/errors/errors';
import { logActivity } from '@/lib/tools/audit';
import { generateEntryNumber } from './journal-posting';
import { requireOpenJournalPeriod } from '@/services/finance/sales-recognition-service';

/** Exact financial inverse for legacy production. Caller owns stock reversal + tx. */
export async function reverseProductionMovementJournal(
    tx: Prisma.TransactionClient,
    original: StockMovement,
    reversal: StockMovement,
    userId: string,
) {
    if (!userId || !original.productionOrderId || original.id === reversal.id ||
        !['IN', 'OUT'].includes(original.type) ||
        reversal.type !== (original.type === 'IN' ? 'OUT' : 'IN') ||
        reversal.reversalOfId !== original.id || original.reversalOfId ||
        original.reference?.startsWith('VOID:') ||
        reversal.productionOrderId !== original.productionOrderId ||
        original.productVariantId !== reversal.productVariantId ||
        original.salesOrderId || reversal.salesOrderId || original.goodsReceiptId || reversal.goodsReceiptId ||
        !original.quantity.isFinite() || !original.quantity.gt(0) ||
        !original.quantity.eq(reversal.quantity) ||
        original.cost?.toString() !== reversal.cost?.toString() ||
        !((original.type === 'IN' && original.toLocationId && !original.fromLocationId &&
            reversal.fromLocationId === original.toLocationId && !reversal.toLocationId) ||
          (original.type === 'OUT' && original.fromLocationId && !original.toLocationId &&
            reversal.toLocationId === original.fromLocationId && !reversal.fromLocationId))) {
        throw new BusinessRuleError('Pasangan pembalik produksi tidak valid.');
    }
    await tx.$queryRaw`SELECT id FROM "JournalEntry" WHERE "referenceId" = ${original.id} ORDER BY id FOR UPDATE`;
    const sources = await tx.journalEntry.findMany({
        where: { referenceId: original.id }, include: { lines: true },
    });
    if (await tx.journalEntry.findFirst({ where: { referenceId: reversal.id }, select: { id: true } })) {
        throw new BusinessRuleError('Jurnal pembalik produksi sudah ada.');
    }
    if (!sources.length) {
        const order = await tx.productionOrder.findUniqueOrThrow({
            where: { id: original.productionOrderId }, select: { isMaklon: true },
        });
        if (original.cost?.isZero() ||
            (order.isMaklon && original.companyOwned !== true)) return;
        throw new BusinessRuleError('Jurnal sumber produksi hilang; rekonsiliasi diperlukan.');
    }
    await requireOpenJournalPeriod(tx, reversal.createdAt);
    const source = sources[0];
    if (await tx.journalEntry.findFirst({
        where: { referenceId: source.id, status: { not: 'VOIDED' } }, select: { id: true },
    })) throw new BusinessRuleError('Jurnal sumber produksi sudah dibalik secara terpisah.');
    if (sources.length !== 1 || source.status !== 'POSTED' || !source.isAutoGenerated ||
        source.referenceType !== 'MANUAL_ENTRY' || source.referenceId !== original.id || source.lines.length < 2) {
        throw new BusinessRuleError('Jurnal sumber produksi belum diposting atau ambigu.');
    }
    let debit = new Prisma.Decimal(0), credit = new Prisma.Decimal(0);
    const netCredits = new Map<string, Prisma.Decimal>();
    for (const line of source.lines) {
        if (!line.debit.isFinite() || !line.credit.isFinite() || line.debit.lt(0) || line.credit.lt(0) ||
            (line.debit.gt(0) && line.credit.gt(0)) ||
            !line.currency.trim() || !line.exchangeRate.isFinite() || !line.exchangeRate.gt(0)) {
            throw new BusinessRuleError('Nilai jurnal sumber produksi tidak valid.');
        }
        debit = debit.plus(line.debit);
        credit = credit.plus(line.credit);
        netCredits.set(line.accountId,
            (netCredits.get(line.accountId) ?? new Prisma.Decimal(0)).plus(line.debit).minus(line.credit));
    }
    if (!debit.gt(0) || !debit.eq(credit)) throw new BusinessRuleError('Jurnal sumber produksi tidak seimbang.');
    // Preserve the existing negative-asset guard, including same-account pairs.
    // The WO/source lock serializes this operation. Do not add an Account lock
    // after earlier journal inserts: their FK key-share locks cannot be upgraded
    // safely across concurrent WOs (and not all journal writers lock accounts).
    for (const [accountId, amount] of netCredits) {
        const account = await tx.account.findUniqueOrThrow({ where: { id: accountId } });
        if (account.type !== 'ASSET' || amount.lte(0)) continue;
        const sums = await tx.journalLine.aggregate({
            where: { accountId, journalEntry: { status: 'POSTED' } },
            _sum: { debit: true, credit: true },
        });
        const balance = new Prisma.Decimal(sums._sum.debit ?? 0).minus(sums._sum.credit ?? 0);
        if (balance.lt(amount)) throw new BusinessRuleError('Saldo akun sumber tidak cukup untuk pembatalan produksi.');
    }
    const journal = await tx.journalEntry.create({ data: {
        entryNumber: await generateEntryNumber(reversal.createdAt, tx), entryDate: reversal.createdAt,
        reference: reversal.reference ?? reversal.id, referenceId: reversal.id, referenceType: 'MANUAL_ENTRY',
        description: `Production reversal of ${source.entryNumber}`, status: 'POSTED', isAutoGenerated: true,
        createdById: userId, approvedById: userId, approvedAt: new Date(),
        lines: { create: source.lines.map(line => ({
            accountId: line.accountId, debit: line.credit, credit: line.debit,
            currency: line.currency, exchangeRate: line.exchangeRate,
            description: `Reversal ${source.entryNumber}: ${line.description ?? ''}`,
        })) },
    } });
    await logActivity({
        userId, action: 'REVERSE_PRODUCTION_JOURNAL', entityType: 'JournalEntry', entityId: journal.id,
        details: `Exact inverse of ${source.entryNumber}.`,
        changes: { originalJournalId: source.id, originalMovementId: original.id, reversalMovementId: reversal.id }, tx,
    });
}
