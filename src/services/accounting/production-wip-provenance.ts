import { Prisma, type StockMovement } from '@prisma/client';
import { BusinessRuleError } from '@/lib/errors/errors';

type Source = Prisma.JournalEntryGetPayload<{
    include: { lines: { include: { account: true } } };
}>;
const zero = () => new Prisma.Decimal(0);

function unresolved(reason: string): never {
    throw new BusinessRuleError(
        `Sumber nilai WIP WO belum dapat direkonsiliasi: ${reason}. Minta Finance memeriksa jurnal sumber; jangan menambah stok atau saldo untuk melewati validasi.`,
        {}, 'PRODUCTION_WIP_UNRESOLVED',
    );
}

/** Production auto-postings are IDR. Never infer accounting from current master mappings. */
function wipLines(movement: StockMovement, journal: Source) {
    if (journal.status !== 'POSTED' || !journal.isAutoGenerated ||
        journal.referenceType !== 'MANUAL_ENTRY' || journal.referenceId !== movement.id ||
        journal.lines.length < 2) unresolved('jurnal hilang, belum diposting, atau ambigu');
    let debit = zero(), credit = zero();
    for (const line of journal.lines) {
        if (!line.debit.isFinite() || !line.credit.isFinite() ||
            line.debit.lt(0) || line.credit.lt(0) ||
            (line.debit.gt(0) && line.credit.gt(0)) ||
            line.currency !== 'IDR' || !line.exchangeRate.eq(1) ||
            line.account.type !== 'ASSET') unresolved('vektor jurnal tidak valid');
        debit = debit.plus(line.debit);
        credit = credit.plus(line.credit);
    }
    if (!debit.gt(0) || !debit.eq(credit)) unresolved('jurnal tidak seimbang');
    // Production issue: Dr WIP / Cr inventory. Output: Dr inventory / Cr WIP.
    // Linked reversals naturally invert this direction; same-account inventory
    // and WIP lines must NOT be netted together before extracting the WIP leg.
    return journal.lines.filter(line => movement.type === 'OUT' ? line.debit.gt(0) : line.credit.gt(0));
}

/**
 * Allocate an output's credit only from posted WIP legs belonging to this WO.
 * Caller holds the WO lock and owns the posting transaction. No bridging journal,
 * revaluation, inactive-account activation, or borrowing another WO's balance.
 */
export async function allocateProductionWip(
    tx: Prisma.TransactionClient,
    output: StockMovement,
    amount: Prisma.Decimal,
): Promise<Array<{ accountId: string; credit: Prisma.Decimal }>> {
    if (!output.productionOrderId || output.type !== 'IN' || output.reversalOfId ||
        !amount.isFinite() || !amount.gt(0) || amount.decimalPlaces() > 2) {
        unresolved('identitas hasil/nilai tidak valid');
    }
    const movements = await tx.stockMovement.findMany({
        where: {
            productionOrderId: output.productionOrderId,
            id: { not: output.id }, type: { in: ['IN', 'OUT'] },
        },
        orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    });
    // Lock source rows before deriving their vector. This is not a substitute for
    // the separate Finance reversal guard; already-linked reversals reject below.
    if (movements.length) {
        await tx.$queryRaw(Prisma.sql`SELECT id FROM "JournalEntry"
            WHERE "referenceId" IN (${Prisma.join(movements.map(m => m.id))}) ORDER BY id FOR UPDATE`);
    }
    const sources = await tx.journalEntry.findMany({
        where: { referenceId: { in: movements.map(m => m.id) } },
        include: { lines: { include: { account: true } } },
    });
    const byMovement = new Map<string, Source[]>();
    for (const source of sources) {
        if (!source.referenceId) unresolved('referensi jurnal kosong');
        const entries = byMovement.get(source.referenceId) ?? [];
        entries.push(source);
        byMovement.set(source.referenceId, entries);
    }
    const reversedJournals = await tx.journalEntry.findFirst({
        where: { referenceId: { in: sources.map(j => j.id) }, status: { not: 'VOIDED' } },
        select: { id: true },
    });
    if (reversedJournals) unresolved('jurnal sumber telah dibalik di luar mutasi produksi');
    const movementById = new Map(movements.map(m => [m.id, m]));
    const balances = new Map<string, Prisma.Decimal>();
    for (const movement of movements) {
        if (movement.goodsReceiptId || movement.salesOrderId || movement.companyOwned === false) {
            unresolved('kepemilikan atau sumber bukan produksi perusahaan');
        }
        if (movement.reversalOfId) {
            const original = movementById.get(movement.reversalOfId);
            if (!original || original.reversalOfId || original.type === movement.type ||
                original.productVariantId !== movement.productVariantId ||
                !original.quantity.eq(movement.quantity)) unresolved('tautan pembalik tidak valid');
        } else if (/^(VOID:|CORRECTION:)/.test(movement.reference ?? '')) {
            // Old time-window reversals have no reliable source edge. Do not
            // silently attribute them using today's mapping or string guesses.
            unresolved('pembalik historis belum memiliki tautan sumber');
        }
        const journals = byMovement.get(movement.id) ?? [];
        if (!journals.length && movement.cost?.isZero()) continue;
        if (journals.length !== 1) unresolved('jumlah jurnal sumber bukan satu');
        if (movement.reversalOfId) {
            const originals = byMovement.get(movement.reversalOfId) ?? [];
            if (originals.length !== 1) unresolved('jurnal asli pembalik tidak lengkap');
            const vector = (lines: Source['lines'], inverse: boolean) => lines.map(l =>
                [l.accountId, l.currency, l.exchangeRate.toString(),
                    (inverse ? l.credit : l.debit).toString(), (inverse ? l.debit : l.credit).toString()].join('|'),
            ).sort().join(';');
            if (vector(originals[0].lines, true) !== vector(journals[0].lines, false)) {
                unresolved('jurnal pembalik tidak sesuai jurnal asli');
            }
        }
        for (const line of wipLines(movement, journals[0])) {
            const delta = movement.type === 'OUT' ? line.debit : line.credit.negated();
            balances.set(line.accountId, (balances.get(line.accountId) ?? zero()).plus(delta));
        }
    }
    // A negative pool is a historical inconsistency, not permission to fund it
    // with an unrelated positive account. Reconcile before accepting more output.
    if ([...balances.values()].some(value => value.lt(0))) unresolved('sisa nilai akun WIP WO negatif');
    const available = [...balances.values()].reduce((sum, value) => sum.plus(value), zero());
    if (available.lt(amount)) unresolved('debit bahan WO tidak cukup untuk nilai hasil kumulatif');
    let remaining = amount;
    const allocation: Array<{ accountId: string; credit: Prisma.Decimal }> = [];
    // Stable first-source order; each positive pool is consumed at most once.
    for (const [accountId, value] of balances) {
        const credit = Prisma.Decimal.min(value, remaining);
        if (credit.gt(0)) allocation.push({ accountId, credit });
        remaining = remaining.minus(credit);
        if (remaining.isZero()) break;
    }
    return allocation;
}
