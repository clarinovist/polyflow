import type {
    StockMovement, JournalEntry, JournalLine, ProductionExecution,
    MaterialIssue, ScrapRecord,
} from '@prisma/client';
import { BusinessRuleError } from '@/lib/errors/errors';

/** Independent of receipt version: v1 STRICT and v2 REVIEWED keep their meaning. */
export const COST_PERIOD_HASH_VERSION = 'COST_V1' as const;
export type CostPeriodHashVersion = typeof COST_PERIOD_HASH_VERSION;

/**
 * Immutable scalar shape used by the original v1/v2 writers (introduced after
 * the actual-packaging migration). No generated DMMF/Object.keys(row) here:
 * adding a Prisma field must not change any already-issued seal.
 * Keep even non-cost metadata for old receipts: it was part of their evidence.
 */
export const LEGACY_COST_PERIOD_FIELDS = {
    StockMovement: [
        'id', 'type', 'productVariantId', 'fromLocationId', 'toLocationId',
        'quantity', 'reference', 'createdById', 'createdAt', 'batchId', 'cost',
        'salesOrderId', 'goodsReceiptId', 'productionOrderId',
        'productionExecutionId', 'reversalOfId', 'companyOwned',
        'packagingOwnerCustomerId',
    ] satisfies readonly (keyof StockMovement)[],
    JournalEntry: [
        'id', 'entryNumber', 'entryDate', 'description', 'reference',
        'referenceType', 'referenceId', 'status', 'isAutoGenerated',
        'createdById', 'approvedById', 'approvedAt', 'createdAt', 'updatedAt',
    ] satisfies readonly (keyof JournalEntry)[],
    JournalLine: [
        'id', 'journalEntryId', 'accountId', 'description', 'debit', 'credit',
        'currency', 'exchangeRate', 'createdAt', 'reconciledAt',
    ] satisfies readonly (keyof JournalLine)[],
    ProductionExecution: [
        'id', 'clientRequestId', 'requestHash', 'productionOrderId', 'machineId',
        'operatorId', 'shiftId', 'quantityProduced', 'scrapQuantity',
        'enteredQuantity', 'enteredUnit', 'conversionFactorSnapshot', 'bruto',
        'bobin', 'cekGram', 'startTime', 'endTime', 'notes', 'photoUrl',
        'createdAt', 'updatedAt', 'status', 'scrapDaunQty', 'scrapProngkolQty',
        'pieceRateSnapshot', 'pieceEarnings', 'pieceMachineType',
    ] satisfies readonly (keyof ProductionExecution)[],
    MaterialIssue: [
        'id', 'productionOrderId', 'productVariantId', 'quantity', 'status',
        'issuedAt', 'createdById', 'batchId', 'locationId',
        'productionExecutionId', 'stagedSourceId',
    ] satisfies readonly (keyof MaterialIssue)[],
    ScrapRecord: [
        'id', 'productionOrderId', 'productionExecutionId', 'productVariantId',
        'quantity', 'reason', 'recordedAt', 'createdById', 'locationId',
    ] satisfies readonly (keyof ScrapRecord)[],
} as const;

/**
 * COST_V1: identity, amounts/UOM, ownership, provenance, lifecycle, payroll
 * snapshots and event timestamps. Retain creator/approval identity for evidence.
 * Excludes only presentation, transport deduplication and unrelated bank matching
 * metadata. Never edit this format in place; add a new format for new cost fields.
 * See cost-period-hash-projection.md for the schema-change decision procedure.
 */
export const COST_V1_FIELDS = {
    StockMovement: LEGACY_COST_PERIOD_FIELDS.StockMovement,
    JournalEntry: [
        'id', 'entryNumber', 'entryDate', 'reference', 'referenceType',
        'referenceId', 'status', 'isAutoGenerated', 'createdById', 'approvedById',
        'approvedAt', 'createdAt',
    ] satisfies readonly (keyof JournalEntry)[],
    JournalLine: [
        'id', 'journalEntryId', 'accountId', 'debit', 'credit', 'currency',
        'exchangeRate', 'createdAt',
    ] satisfies readonly (keyof JournalLine)[],
    ProductionExecution: [
        'id', 'productionOrderId', 'machineId', 'operatorId', 'shiftId',
        'quantityProduced', 'scrapQuantity', 'enteredQuantity', 'enteredUnit',
        'conversionFactorSnapshot', 'bruto', 'bobin', 'startTime', 'endTime',
        'createdAt', 'status', 'scrapDaunQty', 'scrapProngkolQty',
        'pieceRateSnapshot', 'pieceEarnings', 'pieceMachineType',
    ] satisfies readonly (keyof ProductionExecution)[],
    MaterialIssue: LEGACY_COST_PERIOD_FIELDS.MaterialIssue,
    ScrapRecord: [
        'id', 'productionOrderId', 'productionExecutionId', 'productVariantId',
        'quantity', 'recordedAt', 'createdById', 'locationId',
    ] satisfies readonly (keyof ScrapRecord)[],
} as const;

export type CostPeriodModel = keyof typeof LEGACY_COST_PERIOD_FIELDS;

export function projectCostPeriodRow(
    model: CostPeriodModel,
    row: object,
    hashVersion?: CostPeriodHashVersion,
): Record<string, unknown> {
    // Callers validate receipt formats before reaching here. Also fail closed for
    // untyped callers: never guess a legacy projection for an unknown format.
    if (hashVersion !== undefined && hashVersion !== COST_PERIOD_HASH_VERSION)
        throw new BusinessRuleError(
            'Versi proyeksi batas biaya SPK tidak dikenal.',
            undefined,
            'PRODUCTION_COST_PERIOD_INVALID',
        );
    const fields = hashVersion === undefined
        ? LEGACY_COST_PERIOD_FIELDS[model]
        : COST_V1_FIELDS[model];
    const data = row as Record<string, unknown>;
    // Do not fill absent keys with null/defaults: deletion must change the hash.
    return Object.fromEntries(fields.map((key) => [key, data[key]]));
}
