import { Prisma, type StockMovement } from '@prisma/client';
import { BusinessRuleError } from '@/lib/errors/errors';
import { generateEntryNumber } from './journal-posting';
import { requireOpenJournalPeriod } from '@/services/finance/sales-recognition-service';

/** Preserve historical accounts and amounts, not today's product account mappings. */
export async function reversePackagingJournal(tx: Prisma.TransactionClient, original: StockMovement, reversal: StockMovement, userId: string) {
    await requireOpenJournalPeriod(tx, reversal.createdAt);
    const sources = await tx.journalEntry.findMany({ where: {
        referenceId: original.id, status: { not: 'VOIDED' },
    }, include: { lines: true } });
    if (!sources.length && (original.companyOwned === false || original.cost?.isZero())) return;
    if (sources.length !== 1 || sources[0].status !== 'POSTED') throw new BusinessRuleError('Jurnal sumber produksi tidak lengkap atau ambigu.');
    const source = sources[0];
    const debit = source.lines.reduce((sum, line) => sum.plus(line.debit), new Prisma.Decimal(0));
    const credit = source.lines.reduce((sum, line) => sum.plus(line.credit), new Prisma.Decimal(0));
    if (!debit.gt(0) || !debit.equals(credit)) throw new BusinessRuleError('Jurnal sumber produksi tidak seimbang.');
    await tx.journalEntry.create({ data: {
        entryNumber: await generateEntryNumber(reversal.createdAt, tx), entryDate: reversal.createdAt,
        reference: reversal.reference, referenceId: reversal.id, referenceType: 'MANUAL_ENTRY',
        description: `Production reversal of ${source.entryNumber}`, status: 'POSTED', isAutoGenerated: true,
        createdById: userId, approvedById: userId, approvedAt: new Date(),
        lines: { create: source.lines.map((line) => ({
            accountId: line.accountId, debit: line.credit, credit: line.debit,
            currency: line.currency, exchangeRate: line.exchangeRate, description: `Reversal ${source.entryNumber}`,
        })) },
    } });
}
