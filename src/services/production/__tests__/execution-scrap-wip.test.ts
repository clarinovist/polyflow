import { beforeEach, describe, expect, it, vi } from 'vitest';
import { Prisma, type StockMovement } from '@prisma/client';
import { ProductionMaterialService } from '../material-service';
import { recordInventoryMovement } from '@/services/accounting/inventory-link-service';
import { allocateProductionWip } from '@/services/accounting/production-wip-provenance';
import { InventoryCoreService } from '@/services/inventory/core-service';

vi.mock('@/services/inventory/core-service', () => ({ InventoryCoreService: {
    incrementStock: vi.fn(), incrementStockWithCost: vi.fn(),
} }));
vi.mock('@/services/accounting/accounting-service', () => ({ AccountingService: {
    recordInventoryMovement: (...args: Parameters<typeof recordInventoryMovement>) => recordInventoryMovement(...args),
} }));

const d = (value: number) => new Prisma.Decimal(value);
function setup(isMaklon = false) {
    const movements: StockMovement[] = [];
    const db = {
        $queryRaw: vi.fn(),
        productionOrder: { findUnique: vi.fn().mockResolvedValue({ orderNumber: 'WO-SYNTHETIC', isMaklon }) },
        productionExecution: { findUnique: vi.fn().mockResolvedValue({ productionOrderId: 'wo', status: 'COMPLETED' }) },
        productVariant: { findUnique: vi.fn(async ({ where }: { where: { id: string } }) => ({
            id: where.id, standardCost: where.id === 'leaf' ? d(0) : null, buyPrice: null, price: d(7000),
            product: { productType: 'SCRAP' },
        })) },
        stockMovement: {
            create: vi.fn(async ({ data }: { data: Prisma.StockMovementUncheckedCreateInput }) => {
                const move = { ...data, id: `scrap-${movements.length}`, type: 'IN',
                    quantity: d(Number(data.quantity)), cost: data.cost == null ? null : d(Number(data.cost)),
                    reversalOfId: null, goodsReceiptId: null, salesOrderId: null, createdAt: new Date(),
                } as StockMovement;
                movements.push(move); return move;
            }),
            findMany: vi.fn(async () => movements),
        },
        scrapRecord: { create: vi.fn(async () => ({ id: 'scrap-record' })), findUnique: vi.fn() },
        journalEntry: { findFirst: vi.fn().mockResolvedValue(null), findMany: vi.fn().mockResolvedValue([]) },
    };
    return { db, tx: db as unknown as Prisma.TransactionClient, movements };
}
const scrap = { productionOrderId: 'wo', locationId: 'scrap-store', quantity: 2,
    productionExecutionId: 'execution', userId: 'actor', reason: 'Automatic process scrap' };

describe('automatic execution scrap WIP contract', () => {
    beforeEach(() => vi.clearAllMocks());
    it.each([false, true])('persists zero allocated cost, exact linkage and order ownership (maklon=%s)', async isMaklon => {
        const { db, tx, movements } = setup(isMaklon);
        for (const productVariantId of ['leaf', 'lump']) {
            await ProductionMaterialService.recordScrap({ ...scrap, productVariantId }, tx);
        }
        expect(movements).toHaveLength(2);
        for (const movement of movements) {
            expect(movement.cost?.toString()).toBe('0');
            expect(movement.companyOwned).toBe(!isMaklon);
            expect(movement.productionExecutionId).toBe('execution');
            expect(movement.quantity.toNumber()).toBe(2);
        }
        expect(InventoryCoreService.incrementStock).not.toHaveBeenCalled();
        expect(InventoryCoreService.incrementStockWithCost).toHaveBeenCalledWith(tx, 'scrap-store', 'lump', 2, 0);
        expect(db.scrapRecord.create).toHaveBeenCalledWith({ data: expect.objectContaining({ productionExecutionId: 'execution' }) });
    });
    it('keeps the next output funded only by its new material after a fully absorbed prior output and scrap', async () => {
        const { db, tx, movements } = setup();
        for (const productVariantId of ['leaf', 'lump']) await ProductionMaterialService.recordScrap({ ...scrap, productVariantId }, tx);
        const move = (id: string, type: 'IN' | 'OUT') => ({ ...movements[0], id, type, cost: d(10), companyOwned: true });
        const source = (m: StockMovement, debitAccount: string, creditAccount: string, amount: number) => ({
            id: `journal-${m.id}`, referenceId: m.id, referenceType: 'MANUAL_ENTRY', status: 'POSTED', isAutoGenerated: true,
            lines: [
                { accountId: debitAccount, debit: d(amount), credit: d(0), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' } },
                { accountId: creditAccount, debit: d(0), credit: d(amount), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' } },
            ],
        });
        const firstIssue = move('first-issue', 'OUT'), firstOutput = move('first-output', 'IN'), nextIssue = move('next-issue', 'OUT');
        db.stockMovement.findMany.mockResolvedValue([firstIssue, firstOutput, ...movements, nextIssue]);
        db.journalEntry.findMany.mockResolvedValue([
            source(firstIssue, 'wip', 'raw', 100), source(firstOutput, 'finished', 'wip', 100), source(nextIssue, 'wip', 'raw', 50),
        ] as never);
        expect(await allocateProductionWip(tx, move('next-output', 'IN'), d(50))).toEqual([{ accountId: 'wip', credit: d(50) }]);
        await expect(allocateProductionWip(tx, move('next-output', 'IN'), d(51))).rejects.toThrow('tidak cukup');
    });
    it.each(['missing', 'other-wo', 'voided'])('rejects invalid execution provenance before stock changes: %s', async kind => {
        const { db, tx } = setup();
        db.productionExecution.findUnique.mockResolvedValue(kind === 'missing' ? null : {
            productionOrderId: kind === 'other-wo' ? 'other' : 'wo', status: kind === 'voided' ? 'VOIDED' : 'COMPLETED',
        } as never);
        await expect(ProductionMaterialService.recordScrap({ ...scrap, productVariantId: 'leaf' }, tx)).rejects.toThrow();
        expect(db.stockMovement.create).not.toHaveBeenCalled();
        expect(InventoryCoreService.incrementStockWithCost).not.toHaveBeenCalled();
    });
    it('rejects a missing order before stock changes', async () => {
        const { db, tx } = setup();
        db.productionOrder.findUnique.mockResolvedValue(null);
        await expect(ProductionMaterialService.recordScrap({ ...scrap, productVariantId: 'leaf' }, tx)).rejects.toThrow();
        expect(InventoryCoreService.incrementStockWithCost).not.toHaveBeenCalled();
    });
    it('rejects standalone deletion of execution-owned scrap before touching stock', async () => {
        const { db, tx } = setup();
        // The public deletion method owns its transaction; use the tenant client seam.
        const { tenantContext } = await import('@/lib/core/prisma');
        db.scrapRecord.findUnique.mockResolvedValue({ ...scrap, quantity: d(2), productVariantId: 'leaf' } as never);
        const client = { $transaction: (fn: (inner: Prisma.TransactionClient) => Promise<unknown>) => fn(tx) };
        await expect(tenantContext.run(client as never, () => ProductionMaterialService.deleteScrap('scrap', 'wo'))).rejects.toThrow('eksekusi');
        expect(db.stockMovement.create).not.toHaveBeenCalled();
    });
});
