import { beforeEach, describe, expect, it, vi } from 'vitest';
import { Prisma, type StockMovement } from '@prisma/client';
import { allocateProductionWip } from '@/services/accounting/production-wip-provenance';
import { recordFinishedGoodsOutput } from '../execution-output-posting';
import type { ProductionExecutionOrder } from '../execution-types';

vi.mock('@/lib/core/prisma', () => ({ prisma: {} }));
vi.mock('@/services/inventory/core-service', () => ({
    InventoryCoreService: { incrementStockWithCost: vi.fn() },
}));
vi.mock('@/services/accounting/accounting-service', () => ({
    AccountingService: { recordInventoryMovement: vi.fn() },
}));

const d = (value: Prisma.Decimal.Value) => new Prisma.Decimal(value);
type Line = { accountId: string; debit: Prisma.Decimal; credit: Prisma.Decimal; currency: string; exchangeRate: Prisma.Decimal; account: { type: string } };
type Journal = { id: string; status: string; isAutoGenerated: boolean; referenceType: string; referenceId: string; lines: Line[] };

const state = {
    order: { id: 'wo', orderNumber: 'WO-SYNTH', actualQuantity: d(0), isMaklon: false, estimatedConversionCost: null as Prisma.Decimal | null,
        actualPackagingEnabled: false, bom: { productVariantId: 'fg' } },
    movements: [] as StockMovement[],
    journals: [] as Journal[],
};
const line = (accountId: string, debit: Prisma.Decimal.Value, credit: Prisma.Decimal.Value): Line => ({
    accountId, debit: d(debit), credit: d(credit), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' },
});
const tx = {
    $queryRaw: vi.fn(),
    productionOrder: {
        findUnique: vi.fn(async () => state.order),
        findUniqueOrThrow: vi.fn(async () => state.order),
    },
    productionOutputGroup: { findMany: vi.fn(async () => []) },
    maklonCostItem: { findMany: vi.fn(async () => [{ amount: d(300) }]) },
    productVariant: { findUnique: vi.fn(async () => ({ standardCost: d(999), buyPrice: d(999), price: d(7000) })) },
    bom: { findFirst: vi.fn(async () => null) },
    stockMovement: {
        findMany: vi.fn(async ({ where }: { where: { id?: { not: string } } }) =>
            state.movements.filter(m => m.id !== where.id?.not)),
        create: vi.fn(async ({ data }: { data: Partial<StockMovement> & { quantity: number; cost: number } }) => {
            const movement = base(`m${state.movements.length + 1}`, 'IN', {
                ...data, quantity: d(data.quantity).toDecimalPlaces(4), cost: d(data.cost).toDecimalPlaces(4),
            });
            state.movements.push(movement);
            return movement;
        }),
    },
    journalEntry: {
        findMany: vi.fn(async ({ where }: { where: { referenceId: { in: string[] } } }) =>
            state.journals.filter(j => where.referenceId.in.includes(j.referenceId))),
        findFirst: vi.fn(async () => null),
    },
};
const client = tx as unknown as Prisma.TransactionClient;

function base(id: string, type: 'IN' | 'OUT', extra: Partial<StockMovement> = {}): StockMovement {
    return { id, type, productVariantId: type === 'OUT' ? 'raw' : 'fg', productionOrderId: 'wo', quantity: d(1), cost: d(0),
        createdAt: new Date(), reference: id, fromLocationId: null, toLocationId: null, salesOrderId: null, goodsReceiptId: null,
        reversalOfId: null, productionExecutionId: null, companyOwned: null, packagingOwnerCustomerId: null, batchId: null,
        createdById: null, ...extra };
}
/** Material backflush: Dr WIP / Cr raw at the movement's own cents. */
function issue(quantity: Prisma.Decimal.Value, cost: Prisma.Decimal.Value) {
    const movement = base(`m${state.movements.length + 1}`, 'OUT', { quantity: d(quantity), cost: d(cost) });
    state.movements.push(movement);
    const amount = d(quantity).mul(cost).toDecimalPlaces(2);
    if (amount.gt(0)) state.journals.push({ id: `j-${movement.id}`, status: 'POSTED', isAutoGenerated: true,
        referenceType: 'MANUAL_ENTRY', referenceId: movement.id, lines: [line('wip', amount, 0), line('raw', 0, amount)] });
}
async function produce(quantity: number) {
    state.order = { ...state.order, actualQuantity: state.order.actualQuantity.plus(quantity) };
    await recordFinishedGoodsOutput({ tx: client, productionOrderId: 'wo', order: state.order as unknown as ProductionExecutionOrder,
        quantityProduced: quantity, reference: 'Production Output: WO#WO-SYNTH' });
    return state.journals.at(-1)!.lines[0].debit.toString();
}
const remainingWip = () => state.journals.flatMap(j => j.lines).filter(l => l.accountId === 'wip')
    .reduce((sum, l) => sum.plus(l.debit).minus(l.credit), d(0)).toString();

describe('general production output takes the WO remaining posted WIP', () => {
    beforeEach(async () => {
        vi.clearAllMocks();
        state.order = { ...state.order, actualQuantity: d(0), isMaklon: false, estimatedConversionCost: null };
        state.movements = [];
        state.journals = [];
        const { AccountingService } = await import('@/services/accounting/accounting-service');
        // The real linker funds production output only from this WO's posted WIP.
        vi.mocked(AccountingService.recordInventoryMovement).mockImplementation(async (movement, db, options) => {
            // Maklon output is customer property: the linker posts no company journal.
            if (!options?.productionOutput || state.order.isMaklon) return;
            const amount = d(options.journalTotal ?? d(movement.quantity).mul(movement.cost ?? 0).toDecimalPlaces(2));
            if (amount.isZero()) return; // the real linker posts no journal for a zero amount
            const credits = await allocateProductionWip(db as Prisma.TransactionClient, movement, amount);
            state.journals.push({ id: `j-${movement.id}`, status: 'POSTED', isAutoGenerated: true, referenceType: 'MANUAL_ENTRY',
                referenceId: movement.id, lines: [line('fg-stock', amount, 0), ...credits.map(c => line(c.accountId, 0, c.credit))] });
        });
    });

    it('accepts a more efficient second batch at its own remaining material value', async () => {
        issue(120, 1); expect(await produce(100)).toBe('120');
        issue(100, 1); expect(await produce(100)).toBe('100');
        expect(remainingWip()).toBe('0');
    });

    it('absorbs a more wasteful second batch completely instead of leaving WIP behind', async () => {
        issue(100, 1); expect(await produce(100)).toBe('100');
        issue(120, 1); expect(await produce(100)).toBe('120');
        expect(remainingWip()).toBe('0');
    });

    it('lets the next output absorb material consumed by an affal-only execution', async () => {
        issue(100, 1); await produce(100);
        issue('5.30822', 1000);
        issue(100, 1); expect(await produce(100)).toBe('5408.22');
        expect(remainingWip()).toBe('0');
    });

    it('funds every cent of fractional material values across partial outputs', async () => {
        for (const quantity of [6.71, 62.1, 27.76, 74.06, 69.24]) {
            issue(quantity, '14.5299'); await produce(quantity);
        }
        expect(remainingWip()).toBe('0');
    });

    it('posts an output with no remaining WO cost at Rp0 without a journal, never a master or sale price', async () => {
        issue(100, 1); await produce(100);
        const journals = state.journals.length;
        await produce(10);
        const output = state.movements.at(-1)!;
        expect(output.type).toBe('IN');
        expect(output.cost?.toString()).toBe('0');
        expect(state.journals).toHaveLength(journals);
        expect(remainingWip()).toBe('0');
        expect(tx.productVariant.findUnique).not.toHaveBeenCalled();
        expect(tx.bom.findFirst).not.toHaveBeenCalled();
    });

    it('rejects a non-maklon conversion cost that has no posted WIP source', async () => {
        state.order = { ...state.order, estimatedConversionCost: d(50) };
        issue(100, 1);
        await expect(produce(100)).rejects.toMatchObject({ code: 'PRODUCTION_CONVERSION_UNFUNDED' });
        expect(state.movements.filter(m => m.type === 'IN')).toHaveLength(0);
    });

    it('keeps maklon output on the order-average service cost path', async () => {
        state.order = { ...state.order, isMaklon: true };
        state.order = { ...state.order, actualQuantity: d(100) };
        await recordFinishedGoodsOutput({ tx: client, productionOrderId: 'wo', order: state.order as unknown as ProductionExecutionOrder,
            quantityProduced: 100, reference: 'Production Output: WO#WO-SYNTH' });
        expect(state.movements.at(-1)?.cost?.toString()).toBe('3');
    });
});
