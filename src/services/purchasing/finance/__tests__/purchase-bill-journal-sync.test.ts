import { Prisma } from '@prisma/client';
import { beforeEach, describe, expect, it, vi } from 'vitest';

vi.mock('@/lib/tools/audit', () => ({
    logActivity: vi.fn(),
}));

vi.mock('@/services/accounting/accounting-service', () => ({
    AccountingService: { createJournalEntry: vi.fn() },
}));

vi.mock('@/services/finance/sales-recognition-service', () => ({
    requireOpenJournalPeriod: vi.fn(),
}));

import { logActivity } from '@/lib/tools/audit';
import { AccountingService } from '@/services/accounting/accounting-service';
import { requireOpenJournalPeriod } from '@/services/finance/sales-recognition-service';
import {
    calculatePurchaseJournalAmounts,
    syncPurchaseBillAndJournal,
} from '../purchase-bill-journal-sync';

const accounts = {
    grClearingAccountId: 'acc-grir',
    vatInputAccountId: 'acc-vat',
    accountsPayableAccountId: 'acc-ap',
};

const invoiceDate = new Date('2026-09-08T03:00:00.000Z');

function line(
    accountId: string,
    debit: number,
    credit: number,
) {
    return {
        accountId,
        debit: new Prisma.Decimal(debit),
        credit: new Prisma.Decimal(credit),
    };
}

function journal(
    id: string,
    status: 'DRAFT' | 'POSTED',
    lines: ReturnType<typeof line>[],
) {
    return {
        id,
        status,
        entryDate: invoiceDate,
        isAutoGenerated: true,
        lines,
    };
}

function invoice(overrides: Record<string, unknown> = {}) {
    return {
        id: 'bill-1',
        invoiceNumber: 'BILL-001',
        invoiceDate,
        totalAmount: new Prisma.Decimal(100),
        paidAmount: new Prisma.Decimal(0),
        status: 'UNPAID',
        ...overrides,
    };
}

function makeTx(options?: {
    invoice?: ReturnType<typeof invoice>;
    journals?: ReturnType<typeof journal>[];
}) {
    return {
        $queryRaw: vi.fn().mockResolvedValue([]),
        purchaseInvoice: {
            findUnique: vi.fn().mockResolvedValue(options?.invoice ?? invoice()),
            update: vi.fn().mockImplementation(async ({ data }) => ({
                ...(options?.invoice ?? invoice()),
                ...data,
            })),
        },
        journalEntry: {
            findMany: vi.fn().mockResolvedValue(options?.journals ?? []),
            update: vi.fn().mockResolvedValue({ id: 'je-draft' }),
        },
    };
}

function postedAt(total: number, tax = 0) {
    return journal('je-posted', 'POSTED', [
        line('acc-grir', total - tax, 0),
        ...(tax ? [line('acc-vat', tax, 0)] : []),
        line('acc-ap', 0, total),
    ]);
}

describe('calculatePurchaseJournalAmounts', () => {
    it('preserves the existing proportional PO VAT formula with cent rounding', () => {
        expect(calculatePurchaseJournalAmounts(123.45, 110, 10)).toEqual({
            total: 123.45,
            subtotal: 112.23,
            tax: 11.22,
        });
    });
});

describe('syncPurchaseBillAndJournal', () => {
    const sync = (tx: ReturnType<typeof makeTx>, targetTotal: number) => syncPurchaseBillAndJournal(tx as never, {
        invoiceId: 'bill-1', targetTotal: new Prisma.Decimal(targetTotal),
        poTotal: new Prisma.Decimal(100), poTax: new Prisma.Decimal(0), userId: 'user-1', accounts,
    });

    it('records an exact one-cent change rather than silently dropping it', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });
        await sync(tx, 100.01);
        expect(tx.purchaseInvoice.update).toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).toHaveBeenCalledWith(
            expect.objectContaining({ lines: expect.arrayContaining([expect.objectContaining({ accountId: 'acc-ap', credit: 0.01 })]) }), tx,
        );
    });

    it.each([-1, NaN, Infinity, 100.001])('rejects invalid or sub-cent target %s before financial writes', async (amount) => {
        const tx = makeTx({ journals: [postedAt(100)] });
        await expect(sync(tx, amount)).rejects.toThrow();
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
    });

    it('does not hide an unrelated pre-existing invoice/GL mismatch', async () => {
        const tx = makeTx({ journals: [postedAt(55)] });
        await expect(sync(tx, 150)).rejects.toThrow();
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
    });

    it('rejects a mismatched DRAFT journal before rewriting the invoice or journal', async () => {
        const tx = makeTx({ journals: [journal('je-draft', 'DRAFT', [
            line('acc-grir', 80, 0),
            line('acc-ap', 0, 80),
        ])] });

        await expect(sync(tx, 150)).rejects.toMatchObject({
            code: 'PURCHASE_JOURNAL_MISMATCH',
        });
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(tx.journalEntry.update).not.toHaveBeenCalled();
    });

    it('rejects duplicate account roles before locks or financial writes', async () => {
        const tx = makeTx();

        await expect(syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(100),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts: {
                grClearingAccountId: 'acc-shared',
                vatInputAccountId: 'acc-vat',
                accountsPayableAccountId: 'acc-shared',
            },
        })).rejects.toMatchObject({ code: 'PURCHASE_JOURNAL_ACCOUNT_CONFLICT' });

        expect(tx.$queryRaw).not.toHaveBeenCalled();
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
    });

    it('does not append posted accounting to a DRAFT source', async () => {
        const tx = makeTx({ invoice: invoice({ status: 'DRAFT' }), journals: [postedAt(100)] });
        await expect(sync(tx, 150)).rejects.toThrow();
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
    });

    it('checks the old draft journal period before relocating its date', async () => {
        const oldDate = new Date('2026-08-20T00:00:00Z');
        const tx = makeTx({ journals: [{ ...postedAt(100), status: 'DRAFT', entryDate: oldDate }] });
        vi.mocked(requireOpenJournalPeriod).mockImplementation(async (_tx, value) => {
            if (value.getTime() === oldDate.getTime()) throw new Error('closed old period');
        });
        await expect(sync(tx, 150)).rejects.toThrow('closed old period');
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
    });

    beforeEach(() => {
        vi.clearAllMocks();
        vi.mocked(requireOpenJournalPeriod).mockResolvedValue(undefined);
        vi.mocked(AccountingService.createJournalEntry).mockResolvedValue({
            id: 'je-new',
        } as never);
    });

    it('locks the bill and appends a POSTED increase delta without overwriting the original journal', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        expect(tx.$queryRaw).toHaveBeenCalledTimes(2);
        expect(tx.journalEntry.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).toHaveBeenCalledWith(
            expect.objectContaining({
                entryDate: invoiceDate,
                referenceType: 'PURCHASE_INVOICE',
                referenceId: 'bill-1',
                status: 'POSTED',
                lines: [
                    expect.objectContaining({ accountId: 'acc-grir', debit: 50, credit: 0 }),
                    expect.objectContaining({ accountId: 'acc-ap', debit: 0, credit: 50 }),
                ],
            }),
            tx,
        );
        expect(tx.purchaseInvoice.update).toHaveBeenCalledWith({
            where: { id: 'bill-1' },
            data: { totalAmount: new Prisma.Decimal(150) },
        });
        expect(logActivity).toHaveBeenCalledWith(
            expect.objectContaining({ tx, action: 'SYNC_BILL_FROM_GR' }),
        );
    });

    it('appends a balanced reversal delta when the bill decreases', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(60),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        const input = vi.mocked(AccountingService.createJournalEntry).mock.calls[0][0];
        expect(input.lines).toEqual([
            expect.objectContaining({ accountId: 'acc-grir', debit: 0, credit: 40 }),
            expect.objectContaining({ accountId: 'acc-ap', debit: 40, credit: 0 }),
        ]);
    });

    it('reverses all active POSTED accounting when the last GR makes the target zero', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(0),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        const input = vi.mocked(AccountingService.createJournalEntry).mock.calls[0][0];
        expect(input.lines).toEqual([
            expect.objectContaining({ accountId: 'acc-grir', debit: 0, credit: 100 }),
            expect.objectContaining({ accountId: 'acc-ap', debit: 100, credit: 0 }),
        ]);
    });

    it('uses VAT-aware deltas and keeps cent-rounded lines balanced', async () => {
        const tx = makeTx({ invoice: invoice({ totalAmount: new Prisma.Decimal(55) }), journals: [postedAt(55, 5)] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(110),
            poTotal: new Prisma.Decimal(110),
            poTax: new Prisma.Decimal(10),
            userId: 'user-1',
            accounts,
        });

        const input = vi.mocked(AccountingService.createJournalEntry).mock.calls[0][0];
        expect(input.lines).toEqual([
            expect.objectContaining({ accountId: 'acc-grir', debit: 50, credit: 0 }),
            expect.objectContaining({ accountId: 'acc-vat', debit: 5, credit: 0 }),
            expect.objectContaining({ accountId: 'acc-ap', debit: 0, credit: 55 }),
        ]);
    });

    it('refreshes the only DRAFT journal in place within the caller transaction', async () => {
        const tx = makeTx({ journals: [journal('je-draft', 'DRAFT', [
            line('acc-grir', 100, 0),
            line('acc-ap', 0, 100),
        ])] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
        expect(tx.journalEntry.update).toHaveBeenCalledWith({
            where: { id: 'je-draft' },
            data: expect.objectContaining({
                lines: {
                    deleteMany: {},
                    create: [
                        expect.objectContaining({ accountId: 'acc-grir', debit: 150, credit: 0 }),
                        expect.objectContaining({ accountId: 'acc-ap', debit: 0, credit: 150 }),
                    ],
                },
            }),
        });
    });

    it('accepts an empty zero-total DRAFT journal as a repeatable no-op', async () => {
        const tx = makeTx({
            invoice: invoice({
                totalAmount: new Prisma.Decimal(0),
                status: 'DRAFT',
            }),
            journals: [journal('je-draft', 'DRAFT', [])],
        });

        const result = await sync(tx, 0);

        expect(result.action).toBe('noop');
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(tx.journalEntry.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
    });

    it('can refresh an empty zero-total DRAFT journal when a later GR becomes positive', async () => {
        const tx = makeTx({
            invoice: invoice({ totalAmount: new Prisma.Decimal(0) }),
            journals: [journal('je-draft', 'DRAFT', [])],
        });

        await sync(tx, 50);

        expect(tx.purchaseInvoice.update).toHaveBeenCalledWith({
            where: { id: 'bill-1' },
            data: { totalAmount: new Prisma.Decimal(50) },
        });
        expect(tx.journalEntry.update).toHaveBeenCalledWith({
            where: { id: 'je-draft' },
            data: expect.objectContaining({
                status: 'POSTED',
                lines: {
                    deleteMany: {},
                    create: [
                        expect.objectContaining({ accountId: 'acc-grir', debit: 50, credit: 0 }),
                        expect.objectContaining({ accountId: 'acc-ap', debit: 0, credit: 50 }),
                    ],
                },
            }),
        });
    });

    it('forms a missing journal with the same transaction client', async () => {
        const tx = makeTx({ journals: [] });

        await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(100),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        expect(AccountingService.createJournalEntry).toHaveBeenCalledWith(
            expect.objectContaining({
                status: 'POSTED',
                lines: expect.any(Array),
            }),
            tx,
        );
    });

    it('rejects mixed DRAFT and POSTED journals as ambiguous before changing the bill', async () => {
        const tx = makeTx({ journals: [
            postedAt(100),
            journal('je-draft', 'DRAFT', [line('acc-grir', 10, 0), line('acc-ap', 0, 10)]),
        ] });

        await expect(syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        })).rejects.toMatchObject({ code: 'PURCHASE_JOURNAL_AMBIGUOUS' });

        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
    });

    it('rejects legacy account mappings instead of forcing a balancing delta', async () => {
        const tx = makeTx({ journals: [journal('legacy', 'POSTED', [
            line('acc-legacy', 100, 0),
            line('acc-ap', 0, 100),
        ])] });

        await expect(syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        })).rejects.toMatchObject({ code: 'PURCHASE_JOURNAL_MISMATCH' });

        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
    });

    it('is a no-op on repeat when bill and active POSTED sums already match', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });

        const result = await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(100),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        expect(result.action).toBe('noop');
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
        expect(logActivity).not.toHaveBeenCalled();
    });

    it.each([
        ['PARTIAL', 1],
        ['PAID', 100],
        ['UNPAID', 1],
    ])('protects %s bills with paid amount %s from automatic resync', async (status, paidAmount) => {
        const tx = makeTx({ invoice: invoice({
            status,
            paidAmount: new Prisma.Decimal(paidAmount),
        }) });

        const result = await syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        });

        expect(result.action).toBe('protected');
        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(tx.journalEntry.findMany).not.toHaveBeenCalled();
    });

    it('fails before mutation when the invoice business period is closed', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });
        vi.mocked(requireOpenJournalPeriod).mockRejectedValueOnce(
            Object.assign(new Error('closed'), { code: 'FISCAL_PERIOD_CLOSED' }),
        );

        await expect(syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        })).rejects.toMatchObject({ code: 'FISCAL_PERIOD_CLOSED' });

        expect(tx.purchaseInvoice.update).not.toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).not.toHaveBeenCalled();
    });

    it('propagates journal creation failure so the enclosing transaction can roll back the bill update', async () => {
        const tx = makeTx({ journals: [postedAt(100)] });
        vi.mocked(AccountingService.createJournalEntry).mockRejectedValueOnce(
            new Error('journal write failed'),
        );

        await expect(syncPurchaseBillAndJournal(tx as never, {
            invoiceId: 'bill-1',
            targetTotal: new Prisma.Decimal(150),
            poTotal: new Prisma.Decimal(100),
            poTax: new Prisma.Decimal(0),
            userId: 'user-1',
            accounts,
        })).rejects.toThrow('journal write failed');

        expect(tx.purchaseInvoice.update).toHaveBeenCalled();
        expect(AccountingService.createJournalEntry).toHaveBeenCalledWith(
            expect.any(Object),
            tx,
        );
        expect(logActivity).not.toHaveBeenCalled();
    });
});
