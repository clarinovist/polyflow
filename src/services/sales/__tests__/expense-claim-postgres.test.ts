import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import { PrismaClient } from '@prisma/client';
import { tenantContext } from '@/lib/core/prisma';
import {
    returnTestClient,
    verifyReturnTestDatabase,
} from '../../finance/__tests__/return-credit-postgres-fixture';
import { approveClaim, cancelClaim, rejectClaim, submitClaim } from '../expense-claim-service';
import { payClaim } from '../expense-claim-payment';

const connection = process.env.RETURN_CREDIT_TEST_DATABASE_URL;
const db = connection ? returnTestClient(connection) : null;
const run = <T>(fn: () => Promise<T>) => tenantContext.run(db!, fn);

const TENANT = 'synthetic';
const SUBMITTER = 'claim-submitter';
const OTHER = 'claim-other';
const MANAGER = { id: 'claim-manager', isAdmin: false };
const PAYER = { id: 'claim-payer' };
// Fixed dates: the period and the "now" never depend on the day CI runs.
const NOW = new Date('2026-01-20T05:00:00Z');
const PAYMENT_DATE = '2026-01-15';
const ACCOUNTS = { expenseAccountId: 'claim-exp', paymentAccountId: 'claim-cash', paymentDate: PAYMENT_DATE };
const receipt = (userId = SUBMITTER, stamp = 1700000000000) =>
    `/api/images/${TENANT}/expense-receipt/${userId}/${stamp}.jpg`;
let nextStamp = 1800000000000;
const freshReceipt = (userId: string) => receipt(userId, nextStamp++);
const submitInput = (patch: Record<string, unknown> = {}) => ({
    expenseDate: '2026-01-15',
    category: 'BBM',
    amount: 125000.5,
    description: 'Synthetic fuel',
    receiptUrl: receipt(),
    ...patch,
});
const submit = (patch: Record<string, unknown> = {}, userId = SUBMITTER) =>
    run(() => submitClaim(userId, submitInput({ receiptUrl: freshReceipt(userId), ...patch }), { tenant: TENANT }, NOW));
const pay = (claimId: string, accounts: Record<string, unknown> = ACCOUNTS) =>
    run(() => payClaim(claimId, PAYER, accounts, NOW));

async function seedClaim(client: PrismaClient, id: string, status: 'SUBMITTED' | 'APPROVED') {
    return client.expenseClaim.create({
        data: {
            id,
            claimNumber: `RMB-202601-${id}`,
            userId: SUBMITTER,
            expenseDate: new Date('2026-01-14T17:00:00Z'),
            category: 'TOL',
            amount: 80000,
            description: 'Synthetic toll',
            receiptUrl: receipt(),
            status,
        },
    });
}

async function seed(client: PrismaClient) {
    await verifyReturnTestDatabase(client);
    await client.$executeRaw`TRUNCATE "ExpenseClaim", "JournalLine", "JournalEntry", "AuditLog", "SalesVisit", "Customer", "Account", "FiscalPeriod", "SystemSequence", "User" CASCADE`;
    for (const [id, role] of [[SUBMITTER, 'SALES'], [OTHER, 'SALES'], [MANAGER.id, 'MARKETING'], [PAYER.id, 'FINANCE']]) {
        await client.user.create({ data: { id, email: `${id}@example.invalid`, password: 'synthetic-only', role: role as never } });
    }
    await client.account.createMany({
        data: [
            { id: 'claim-exp', code: '61100', name: 'Synthetic expense', type: 'EXPENSE', category: 'OPERATING_EXPENSE' },
            { id: 'claim-cash', code: '11110', name: 'Synthetic cash', type: 'ASSET', category: 'CURRENT_ASSET', isCashAccount: true },
            { id: 'claim-ar', code: '11210', name: 'Synthetic receivable', type: 'ASSET', category: 'CURRENT_ASSET' },
        ],
    });
    await client.fiscalPeriod.create({
        data: { name: 'January', year: 2026, month: 1, status: 'OPEN', startDate: new Date('2026-01-01'), endDate: new Date('2026-01-31') },
    });
    await client.systemSequence.create({ data: { key: 'JOURNAL_ENTRY_2026', value: 100 } });
}

const journalsFor = (client: PrismaClient, claimId: string) =>
    client.journalEntry.findMany({
        where: { referenceType: 'EXPENSE_CLAIM', referenceId: claimId },
        include: { lines: true },
    });

describe.skipIf(!db)('expense claim PostgreSQL contracts', () => {
    beforeEach(async () => seed(db!));
    afterAll(async () => { await db?.$disconnect(); });

    it('pays an approved claim into exactly one balanced POSTED journal linked to the claim', async () => {
        await seedClaim(db!, 'c1', 'APPROVED');

        const paid = await pay('c1');

        const claim = await db!.expenseClaim.findUniqueOrThrow({ where: { id: 'c1' } });
        const journals = await journalsFor(db!, 'c1');
        expect(paid.status).toBe('PAID');
        expect(claim).toMatchObject({ status: 'PAID', paidById: PAYER.id, expenseAccountId: 'claim-exp', paymentAccountId: 'claim-cash' });
        expect(journals).toHaveLength(1);
        expect(claim.journalEntryId).toBe(journals[0].id);
        expect(journals[0]).toMatchObject({ status: 'POSTED', isAutoGenerated: true, reference: 'RMB-202601-c1' });
        const byAccount = Object.fromEntries(journals[0].lines.map((l) => [l.accountId, [Number(l.debit), Number(l.credit)]]));
        expect(byAccount).toEqual({ 'claim-exp': [80000, 0], 'claim-cash': [0, 80000] });
        expect(await db!.auditLog.count({ where: { action: 'PAY_EXPENSE_CLAIM', entityId: 'c1' } })).toBe(1);
    });

    it('lets exactly one of two parallel payments succeed and posts exactly one journal', async () => {
        await seedClaim(db!, 'c2', 'APPROVED');

        const outcomes = await Promise.allSettled([pay('c2'), pay('c2')]);

        expect(outcomes.filter((o) => o.status === 'fulfilled')).toHaveLength(1);
        const failed = outcomes.find((o) => o.status === 'rejected') as PromiseRejectedResult;
        expect(failed.reason).toMatchObject({ code: expect.stringMatching(/STALE_STATUS|INVALID_EXPENSE_CLAIM_STATUS/) });
        expect(await journalsFor(db!, 'c2')).toHaveLength(1);
        expect(await db!.expenseClaim.count({ where: { id: 'c2', status: 'PAID', journalEntryId: { not: null } } })).toBe(1);
        expect(await db!.auditLog.count({ where: { action: 'PAY_EXPENSE_CLAIM', entityId: 'c2' } })).toBe(1);
    });

    it('leaves the claim APPROVED and posts nothing when the period is closed', async () => {
        await seedClaim(db!, 'c3', 'APPROVED');
        await db!.fiscalPeriod.updateMany({ data: { status: 'CLOSED' } });

        await expect(pay('c3')).rejects.toMatchObject({ code: 'FISCAL_PERIOD_CLOSED' });

        expect((await db!.expenseClaim.findUniqueOrThrow({ where: { id: 'c3' } })).status).toBe('APPROVED');
        expect(await journalsFor(db!, 'c3')).toHaveLength(0);
    });

    it('refuses a non-cash source account and an expense account that is not an expense', async () => {
        await seedClaim(db!, 'c4', 'APPROVED');

        await expect(pay('c4', { ...ACCOUNTS, paymentAccountId: 'claim-ar' })).rejects.toMatchObject({ code: 'INVALID_PAYMENT_ACCOUNT' });
        await expect(pay('c4', { ...ACCOUNTS, expenseAccountId: 'claim-cash', paymentAccountId: 'claim-exp' })).rejects.toMatchObject({ code: 'INVALID_EXPENSE_ACCOUNT' });

        expect((await db!.expenseClaim.findUniqueOrThrow({ where: { id: 'c4' } })).status).toBe('APPROVED');
        expect(await journalsFor(db!, 'c4')).toHaveLength(0);
    });

    it('lets exactly one of two parallel approvals succeed', async () => {
        await seedClaim(db!, 'c5', 'SUBMITTED');
        const approve = () => run(() => approveClaim('c5', MANAGER, NOW));

        const outcomes = await Promise.allSettled([approve(), approve()]);

        expect(outcomes.filter((o) => o.status === 'fulfilled')).toHaveLength(1);
        const failed = outcomes.find((o) => o.status === 'rejected') as PromiseRejectedResult;
        expect(failed.reason).toMatchObject({ code: expect.stringMatching(/STALE_STATUS|INVALID_EXPENSE_CLAIM_STATUS/) });
        expect(await db!.expenseClaim.count({ where: { id: 'c5', status: 'APPROVED', reviewedById: MANAGER.id } })).toBe(1);
        expect(await db!.auditLog.count({ where: { action: 'APPROVE_EXPENSE_CLAIM', entityId: 'c5' } })).toBe(1);
    });

    it('resolves a parallel approve and reject to a single final decision', async () => {
        await seedClaim(db!, 'c6', 'SUBMITTED');

        const outcomes = await Promise.allSettled([
            run(() => approveClaim('c6', MANAGER, NOW)),
            run(() => rejectClaim('c6', MANAGER, 'Synthetic reason', NOW)),
        ]);

        expect(outcomes.filter((o) => o.status === 'fulfilled')).toHaveLength(1);
        const claim = await db!.expenseClaim.findUniqueOrThrow({ where: { id: 'c6' } });
        expect(['APPROVED', 'REJECTED']).toContain(claim.status);
    });

    it('stores one claim per clientClaimId even when two submits race', async () => {
        const outcomes = await Promise.allSettled([submit({ clientClaimId: 'offline-1' }), submit({ clientClaimId: 'offline-1' })]);

        expect(outcomes.every((o) => o.status === 'fulfilled')).toBe(true);
        expect(await db!.expenseClaim.count({ where: { userId: SUBMITTER, clientClaimId: 'offline-1' } })).toBe(1);
        const ids = outcomes.map((o) => (o as PromiseFulfilledResult<{ id: string }>).value.id);
        expect(new Set(ids).size).toBe(1);
    });

    it('allocates distinct RMB numbers for parallel submits by retrying on collision', async () => {
        const outcomes = await Promise.allSettled([submit(), submit(), submit()]);

        expect(outcomes.every((o) => o.status === 'fulfilled')).toBe(true);
        const numbers = (await db!.expenseClaim.findMany({ select: { claimNumber: true } })).map((c) => c.claimNumber).sort();
        expect(numbers).toHaveLength(3);
        expect(new Set(numbers).size).toBe(3);
        expect(numbers.every((n) => /^RMB-202601-\d{3}$/.test(n))).toBe(true);
    });

    it('rejects a receipt already backing a live claim and frees it once that claim is cancelled or rejected', async () => {
        const shared = receipt(SUBMITTER, 1900000000000);
        const first = await submit({ receiptUrl: shared });

        await expect(submit({ receiptUrl: shared })).rejects.toMatchObject({ code: 'DUPLICATE_RECEIPT' });
        await run(() => cancelClaim(first.id, SUBMITTER));
        const second = await submit({ receiptUrl: shared });
        await run(() => rejectClaim(second.id, MANAGER, 'Synthetic reason', NOW));
        const third = await submit({ receiptUrl: shared });

        expect(third.status).toBe('SUBMITTED');
        await run(() => approveClaim(third.id, MANAGER, NOW));
        await expect(submit({ receiptUrl: shared })).rejects.toMatchObject({ code: 'DUPLICATE_RECEIPT' });
        expect(await db!.expenseClaim.count({ where: { receiptUrl: shared } })).toBe(3);
    });

    it('lets exactly one of two parallel submits with the same receipt succeed', async () => {
        const shared = receipt(SUBMITTER, 1950000000000);

        const outcomes = await Promise.allSettled([submit({ receiptUrl: shared }), submit({ receiptUrl: shared })]);

        expect(outcomes.filter((o) => o.status === 'fulfilled')).toHaveLength(1);
        const failed = outcomes.find((o) => o.status === 'rejected') as PromiseRejectedResult;
        expect(failed.reason).toMatchObject({ code: 'DUPLICATE_RECEIPT' });
        expect(await db!.expenseClaim.count({ where: { receiptUrl: shared } })).toBe(1);
        expect(await db!.auditLog.count({ where: { action: 'SUBMIT_EXPENSE_CLAIM' } })).toBe(1);
    });

    it('returns the stored claim for a racing retry that reuses both clientClaimId and receipt', async () => {
        const shared = receipt(SUBMITTER, 1970000000000);

        const outcomes = await Promise.allSettled([
            submit({ receiptUrl: shared, clientClaimId: 'offline-2' }),
            submit({ receiptUrl: shared, clientClaimId: 'offline-2' }),
        ]);

        expect(outcomes.every((o) => o.status === 'fulfilled')).toBe(true);
        const ids = outcomes.map((o) => (o as PromiseFulfilledResult<{ id: string }>).value.id);
        expect(new Set(ids).size).toBe(1);
        expect(await db!.expenseClaim.count({ where: { receiptUrl: shared } })).toBe(1);
    });

    it('rejects a visit owned by another user and links an owned visit', async () => {
        await db!.customer.create({ data: { id: 'claim-customer', name: 'Synthetic Customer' } });
        await db!.salesVisit.create({
            data: {
                id: 'claim-visit', customerId: 'claim-customer', userId: SUBMITTER, checkInTime: NOW, checkOutTime: NOW,
                durationSeconds: 60, latitude: 1, longitude: 1, distance: 0,
            },
        });

        await expect(submit({ salesVisitId: 'claim-visit' }, OTHER)).rejects.toMatchObject({ code: 'VISIT_NOT_OWNED' });
        const claim = await submit({ salesVisitId: 'claim-visit' });

        expect(claim.salesVisitId).toBe('claim-visit');
        expect(claim.salesVisit?.customer.name).toBe('Synthetic Customer');
        expect(await db!.expenseClaim.count()).toBe(1);
    });

    it('rejects another user\'s receipt URL and lets only the owner cancel a SUBMITTED claim', async () => {
        await expect(submit({ receiptUrl: receipt(OTHER) })).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
        const claim = await submit();

        await expect(run(() => cancelClaim(claim.id, OTHER))).rejects.toMatchObject({ code: 'NOT_FOUND' });
        const cancelled = await run(() => cancelClaim(claim.id, SUBMITTER));

        expect(cancelled.status).toBe('CANCELLED');
        await expect(run(() => approveClaim(claim.id, MANAGER, NOW))).rejects.toMatchObject({ code: 'INVALID_EXPENSE_CLAIM_STATUS' });
    });

    it('blocks a non-admin from approving their own claim but lets an admin do it', async () => {
        const claim = await submit();

        await expect(run(() => approveClaim(claim.id, { id: SUBMITTER, isAdmin: false }, NOW))).rejects.toMatchObject({
            code: 'SELF_APPROVAL_NOT_ALLOWED',
        });
        await expect(run(() => approveClaim(claim.id, { id: SUBMITTER, isAdmin: true }, NOW))).resolves.toMatchObject({ status: 'APPROVED' });
    });
});
