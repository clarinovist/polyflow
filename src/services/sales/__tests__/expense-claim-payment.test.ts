import { beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => {
    const tx = {
        expenseClaim: {
            findUnique: vi.fn(),
            findUniqueOrThrow: vi.fn(),
            updateMany: vi.fn(),
            update: vi.fn(),
        },
        account: { findMany: vi.fn() },
    };
    return {
        tx,
        db: { $transaction: vi.fn() },
        audit: vi.fn(),
        createJournal: vi.fn(),
        postJournal: vi.fn(),
        isPeriodOpen: vi.fn(),
    };
});

vi.mock('@/lib/core/prisma', () => ({ prisma: mocks.db }));
vi.mock('@/lib/tools/audit', () => ({ logActivity: mocks.audit }));
vi.mock('@/services/accounting/journal-posting', () => ({
    createJournalEntry: mocks.createJournal,
    postJournal: mocks.postJournal,
}));
vi.mock('@/services/accounting/periods-service', () => ({
    isPeriodOpen: mocks.isPeriodOpen,
}));

import { payClaim } from '../expense-claim-payment';

const NOW = new Date('2026-11-24T05:00:00Z');
const PAYER = { id: 'fin-1' };
const accounts = { expenseAccountId: 'acc-exp', paymentAccountId: 'acc-cash' };
const account = (overrides: Record<string, unknown> = {}) => ({
    isActive: true,
    isCashAccount: false,
    _count: { children: 0 },
    ...overrides,
});
const expenseAcc = (o: Record<string, unknown> = {}) =>
    account({ id: 'acc-exp', code: '61100', type: 'EXPENSE', ...o });
const cashAcc = (o: Record<string, unknown> = {}) =>
    account({ id: 'acc-cash', code: '11110', type: 'ASSET', isCashAccount: true, ...o });
const claim = (o: Record<string, unknown> = {}) => ({
    id: 'claim-1',
    claimNumber: 'RMB-202611-001',
    amount: '75000.50',
    status: 'APPROVED',
    ...o,
});

beforeEach(() => {
    vi.resetAllMocks();
    mocks.db.$transaction.mockImplementation((fn: (tx: unknown) => unknown) => fn(mocks.tx));
    mocks.tx.expenseClaim.findUnique.mockResolvedValue(claim());
    mocks.tx.expenseClaim.findUniqueOrThrow.mockResolvedValue({ id: 'claim-1', status: 'PAID' });
    mocks.tx.expenseClaim.updateMany.mockResolvedValue({ count: 1 });
    mocks.tx.account.findMany.mockResolvedValue([expenseAcc(), cashAcc()]);
    mocks.isPeriodOpen.mockResolvedValue(true);
    mocks.createJournal.mockResolvedValue({ id: 'je-1' });
    mocks.postJournal.mockResolvedValue({ id: 'je-1', status: 'POSTED' });
});

describe('payClaim', () => {
    it('posts a balanced journal Dr expense / Cr source for the claim amount', async () => {
        await payClaim('claim-1', PAYER, accounts, NOW);

        const [input, tx] = mocks.createJournal.mock.calls[0];
        expect(tx).toBe(mocks.tx);
        expect(input).toMatchObject({
            entryDate: new Date('2026-11-23T17:00:00.000Z'),
            reference: 'RMB-202611-001',
            referenceType: 'EXPENSE_CLAIM',
            referenceId: 'claim-1',
            isAutoGenerated: true,
            createdById: 'fin-1',
        });
        expect(input.lines).toEqual([
            expect.objectContaining({ accountId: 'acc-exp', debit: 75000.5, credit: 0 }),
            expect.objectContaining({ accountId: 'acc-cash', debit: 0, credit: 75000.5 }),
        ]);
        const debit = input.lines.reduce((sum: number, l: { debit: number }) => sum + l.debit, 0);
        const credit = input.lines.reduce((sum: number, l: { credit: number }) => sum + l.credit, 0);
        expect(debit).toBe(credit);
        expect(mocks.postJournal).toHaveBeenCalledWith('je-1', 'fin-1', mocks.tx);
    });

    it('flips APPROVED to PAID with a compare-and-set, links the journal and audits in the transaction', async () => {
        await payClaim('claim-1', PAYER, accounts, NOW);

        expect(mocks.tx.expenseClaim.updateMany).toHaveBeenCalledWith({
            where: { id: 'claim-1', status: 'APPROVED' },
            data: {
                status: 'PAID',
                paidById: 'fin-1',
                paidAt: NOW,
                expenseAccountId: 'acc-exp',
                paymentAccountId: 'acc-cash',
            },
        });
        expect(mocks.tx.expenseClaim.update).toHaveBeenCalledWith({
            where: { id: 'claim-1' },
            data: { journalEntryId: 'je-1' },
        });
        expect(mocks.audit).toHaveBeenCalledWith(
            expect.objectContaining({
                userId: 'fin-1',
                action: 'PAY_EXPENSE_CLAIM',
                fromStatus: 'APPROVED',
                toStatus: 'PAID',
                tx: mocks.tx,
            }),
        );
    });

    it('uses the explicit payment date for the period check and the journal', async () => {
        await payClaim('claim-1', PAYER, { ...accounts, paymentDate: '2026-11-10' }, NOW);

        expect(mocks.isPeriodOpen).toHaveBeenCalledWith(new Date('2026-11-09T17:00:00.000Z'), mocks.tx);
        expect(mocks.createJournal.mock.calls[0][0].entryDate).toEqual(new Date('2026-11-09T17:00:00.000Z'));
    });

    it('creates no journal when the compare-and-set matches no row (already paid by a concurrent call)', async () => {
        mocks.tx.expenseClaim.updateMany.mockResolvedValue({ count: 0 });

        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({
            code: 'STALE_STATUS',
        });
        expect(mocks.createJournal).not.toHaveBeenCalled();
        expect(mocks.postJournal).not.toHaveBeenCalled();
        expect(mocks.audit).not.toHaveBeenCalled();
    });

    it('rejects a closed fiscal period without changing the status', async () => {
        mocks.isPeriodOpen.mockResolvedValue(false);

        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({
            code: 'FISCAL_PERIOD_CLOSED',
        });
        expect(mocks.tx.expenseClaim.updateMany).not.toHaveBeenCalled();
        expect(mocks.createJournal).not.toHaveBeenCalled();
    });

    it('propagates a journal failure so the surrounding transaction rolls back', async () => {
        const failure = new Error('journal failed');
        mocks.postJournal.mockRejectedValue(failure);

        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toBe(failure);
        expect(mocks.tx.expenseClaim.update).not.toHaveBeenCalled();
        expect(mocks.audit).not.toHaveBeenCalled();
    });

    it('propagates a createJournalEntry failure (unbalanced / closed period) the same way', async () => {
        const failure = new Error('unbalanced');
        mocks.createJournal.mockRejectedValue(failure);
        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toBe(failure);
        expect(mocks.postJournal).not.toHaveBeenCalled();
    });

    it.each([
        ['a non-expense account', [expenseAcc({ type: 'REVENUE' }), cashAcc()], 'INVALID_EXPENSE_ACCOUNT'],
        ['an inactive expense account', [expenseAcc({ isActive: false }), cashAcc()], 'INVALID_EXPENSE_ACCOUNT'],
        ['a parent expense account', [expenseAcc({ _count: { children: 2 } }), cashAcc()], 'INVALID_EXPENSE_ACCOUNT'],
        ['a liability source account', [expenseAcc(), cashAcc({ type: 'LIABILITY' })], 'INVALID_PAYMENT_ACCOUNT'],
        ['a non-cash asset source (e.g. receivable)', [expenseAcc(), cashAcc({ isCashAccount: false })], 'INVALID_PAYMENT_ACCOUNT'],
        ['an inactive source account', [expenseAcc(), cashAcc({ isActive: false })], 'INVALID_PAYMENT_ACCOUNT'],
        ['a parent source account', [expenseAcc(), cashAcc({ _count: { children: 1 } })], 'INVALID_PAYMENT_ACCOUNT'],
    ])('rejects %s', async (_label, rows, code) => {
        mocks.tx.account.findMany.mockResolvedValue(rows);

        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({ code });
        expect(mocks.tx.expenseClaim.updateMany).not.toHaveBeenCalled();
        expect(mocks.createJournal).not.toHaveBeenCalled();
    });

    it('reports a missing account as not found', async () => {
        mocks.tx.account.findMany.mockResolvedValue([cashAcc()]);
        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({ code: 'NOT_FOUND' });

        mocks.tx.account.findMany.mockResolvedValue([expenseAcc()]);
        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({ code: 'NOT_FOUND' });
    });

    it('rejects using the same account on both sides before opening a transaction', async () => {
        await expect(
            payClaim('claim-1', PAYER, { expenseAccountId: 'same', paymentAccountId: 'same' }, NOW),
        ).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
        expect(mocks.db.$transaction).not.toHaveBeenCalled();
    });

    it('rejects a future payment date and malformed input', async () => {
        await expect(
            payClaim('claim-1', PAYER, { ...accounts, paymentDate: '2026-12-01' }, NOW),
        ).rejects.toMatchObject({ code: 'PAYMENT_DATE_IN_FUTURE' });
        await expect(payClaim('claim-1', PAYER, { expenseAccountId: '' }, NOW)).rejects.toMatchObject({
            code: 'VALIDATION_ERROR',
        });
        expect(mocks.db.$transaction).not.toHaveBeenCalled();
    });

    it('reports not found for a missing claim', async () => {
        mocks.tx.expenseClaim.findUnique.mockResolvedValue(null);
        await expect(payClaim('nope', PAYER, accounts, NOW)).rejects.toMatchObject({ code: 'NOT_FOUND' });
    });

    it.each(['SUBMITTED', 'REJECTED', 'PAID', 'CANCELLED'])('refuses to pay a %s claim', async (status) => {
        mocks.tx.expenseClaim.findUnique.mockResolvedValue(claim({ status }));

        await expect(payClaim('claim-1', PAYER, accounts, NOW)).rejects.toMatchObject({
            code: 'INVALID_EXPENSE_CLAIM_STATUS',
        });
        expect(mocks.createJournal).not.toHaveBeenCalled();
    });
});
