import { AccountType, ExpenseClaimStatus, ReferenceType } from '@prisma/client';
import type { Prisma } from '@prisma/client';
import { prisma } from '@/lib/core/prisma';
import {
    BusinessRuleError,
    NotFoundError,
    ValidationError,
} from '@/lib/errors/errors';
import { logActivity } from '@/lib/tools/audit';
import {
    parseClaimInput,
    payClaimAccountsSchema,
    resolvePaymentDate,
    type ExpenseClaimActor,
} from '@/lib/sales/expense-claim';
import {
    createJournalEntry,
    postJournal,
} from '@/services/accounting/journal-posting';
import { isPeriodOpen } from '@/services/accounting/periods-service';
import { CLAIM_VIEW_SELECT, type ClaimView } from './expense-claim-select';

const ENTITY_TYPE = 'ExpenseClaim';

type Tx = Prisma.TransactionClient;

interface AccountRow {
    id: string;
    code: string;
    type: AccountType;
    isActive: boolean;
    isCashAccount: boolean;
    _count: { children: number };
}

async function loadAccounts(tx: Tx, expenseId: string, paymentId: string) {
    const rows: AccountRow[] = await tx.account.findMany({
        where: { id: { in: [expenseId, paymentId] } },
        select: {
            id: true,
            code: true,
            type: true,
            isActive: true,
            isCashAccount: true,
            _count: { select: { children: true } },
        },
    });
    const expense = rows.find((row) => row.id === expenseId);
    const payment = rows.find((row) => row.id === paymentId);
    if (!expense) throw new NotFoundError('Akun biaya', expenseId);
    if (!payment) throw new NotFoundError('Akun sumber dana', paymentId);
    return { expense, payment };
}

/**
 * Expense side: an active, postable (leaf) EXPENSE account. Source side: an
 * active, postable (leaf) ASSET account flagged as cash/bank. Both must differ.
 */
function assertPayableAccounts(expense: AccountRow, payment: AccountRow): void {
    if (
        expense.type !== AccountType.EXPENSE ||
        !expense.isActive ||
        expense._count.children > 0
    ) {
        throw new BusinessRuleError(
            `Akun biaya ${expense.code} harus akun BIAYA yang aktif dan bukan akun induk`,
            { accountId: expense.id },
            'INVALID_EXPENSE_ACCOUNT',
        );
    }
    if (
        payment.type !== AccountType.ASSET ||
        !payment.isActive ||
        !payment.isCashAccount ||
        payment._count.children > 0
    ) {
        throw new BusinessRuleError(
            `Akun sumber dana ${payment.code} harus akun kas/bank yang aktif dan bukan akun induk`,
            { accountId: payment.id },
            'INVALID_PAYMENT_ACCOUNT',
        );
    }
}

async function postClaimJournal(
    tx: Tx,
    claim: { id: string; claimNumber: string; amount: Prisma.Decimal | number },
    accounts: { expenseId: string; paymentId: string },
    entryDate: Date,
    actorId: string,
) {
    const amount = Number(claim.amount);
    const description = `Reimburse klaim ${claim.claimNumber}`;
    const journal = await createJournalEntry(
        {
            entryDate,
            description,
            reference: claim.claimNumber,
            referenceType: ReferenceType.EXPENSE_CLAIM,
            referenceId: claim.id,
            // Auto-generated: Finance cannot void/edit it and leave a PAID claim
            // pointing at a voided entry; corrections are a manual reversing entry.
            isAutoGenerated: true,
            createdById: actorId,
            lines: [
                {
                    accountId: accounts.expenseId,
                    debit: amount,
                    credit: 0,
                    description,
                },
                {
                    accountId: accounts.paymentId,
                    debit: 0,
                    credit: amount,
                    description,
                },
            ],
        },
        tx,
    );
    await postJournal(journal.id, actorId, tx);
    return journal;
}

/**
 * Finance pays an APPROVED claim. One transaction: validate accounts and period,
 * flip APPROVED -> PAID (compare-and-set), post a balanced journal and link it.
 * Any failure rolls everything back, so a claim is never PAID without a journal.
 */
export async function payClaim(
    claimId: string,
    actor: Pick<ExpenseClaimActor, 'id'>,
    raw: unknown,
    now: Date = new Date(),
): Promise<ClaimView> {
    const input = parseClaimInput(payClaimAccountsSchema, raw);
    if (input.expenseAccountId === input.paymentAccountId) {
        throw new ValidationError(
            'Akun biaya dan akun sumber dana harus berbeda',
        );
    }
    const entryDate = resolvePaymentDate(input.paymentDate, now);

    return prisma.$transaction(async (tx) => {
        const claim = await tx.expenseClaim.findUnique({
            where: { id: claimId },
            select: { id: true, claimNumber: true, amount: true, status: true },
        });
        if (!claim) throw new NotFoundError('Klaim reimburse', claimId);
        if (claim.status !== ExpenseClaimStatus.APPROVED) {
            throw new BusinessRuleError(
                `Hanya klaim berstatus APPROVED yang dapat dibayar. Status saat ini: ${claim.status}`,
                { claimId: claim.id, status: claim.status },
                'INVALID_EXPENSE_CLAIM_STATUS',
            );
        }
        const { expense, payment } = await loadAccounts(
            tx,
            input.expenseAccountId,
            input.paymentAccountId,
        );
        assertPayableAccounts(expense, payment);
        if (!(await isPeriodOpen(entryDate, tx))) {
            throw new BusinessRuleError(
                'Tidak dapat membayar klaim di periode fiskal yang sudah ditutup.',
                { entryDate },
                'FISCAL_PERIOD_CLOSED',
            );
        }

        const { count } = await tx.expenseClaim.updateMany({
            where: { id: claim.id, status: ExpenseClaimStatus.APPROVED },
            data: {
                status: ExpenseClaimStatus.PAID,
                paidById: actor.id,
                paidAt: now,
                expenseAccountId: expense.id,
                paymentAccountId: payment.id,
            },
        });
        if (count !== 1) {
            throw new BusinessRuleError(
                `Klaim ${claim.id} sudah berubah status, silakan refresh`,
                { claimId: claim.id, count },
                'STALE_STATUS',
            );
        }

        const journal = await postClaimJournal(
            tx,
            claim,
            { expenseId: expense.id, paymentId: payment.id },
            entryDate,
            actor.id,
        );
        await tx.expenseClaim.update({
            where: { id: claim.id },
            data: { journalEntryId: journal.id },
        });
        await logActivity({
            userId: actor.id,
            action: 'PAY_EXPENSE_CLAIM',
            entityType: ENTITY_TYPE,
            entityId: claim.id,
            details: `Klaim ${claim.claimNumber} dibayar (jurnal ${journal.id})`,
            fromStatus: ExpenseClaimStatus.APPROVED,
            toStatus: ExpenseClaimStatus.PAID,
            changes: {
                amount: Number(claim.amount),
                expenseAccountId: expense.id,
                paymentAccountId: payment.id,
                journalEntryId: journal.id,
            },
            tx,
        });
        return tx.expenseClaim.findUniqueOrThrow({
            where: { id: claim.id },
            select: CLAIM_VIEW_SELECT,
        });
    });
}
