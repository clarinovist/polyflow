import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import { PrismaClient } from '@prisma/client';
import { diagnoseCogsEconomicCompleteness } from '../cogs-economic-diagnosis-service';

const connection = process.env.TEST_DATABASE_URL;
const db = (() => {
    if (!connection) return null;
    const url = new URL(connection);
    if (
        !['postgres:', 'postgresql:'].includes(url.protocol) ||
        url.hostname !== '127.0.0.1' ||
        url.pathname !== '/polyflow_recognition_test'
    ) {
        throw new Error('Only disposable localhost polyflow_recognition_test is allowed');
    }
    return new PrismaClient({ datasources: { db: { url: connection } } });
})();

const period = { startDate: '2026-08-01', endDate: '2026-08-31' };
const start = new Date('2026-07-31T17:00:00.000Z');
const end = new Date('2026-08-31T16:59:59.999Z');
const middle = new Date('2026-08-15T00:00:00.000Z');

async function journal(input: {
    id: string;
    referenceId: string;
    entryDate?: Date;
    debitAccount: string;
    creditAccount: string;
    amount: number;
}) {
    return db!.journalEntry.create({
        data: {
            id: input.id,
            entryNumber: input.id,
            entryDate: input.entryDate ?? middle,
            description: 'Synthetic COGS diagnosis fixture',
            reference: input.id,
            referenceType: 'MANUAL_ENTRY',
            referenceId: input.referenceId,
            status: 'POSTED',
            isAutoGenerated: true,
            lines: {
                create: [
                    { accountId: input.debitAccount, debit: input.amount, credit: 0 },
                    { accountId: input.creditAccount, debit: 0, credit: input.amount },
                ],
            },
        },
    });
}

async function movement(input: {
    id: string;
    type?: 'IN' | 'OUT' | 'RETURN_IN' | 'ADJUSTMENT';
    variant?: string;
    quantity?: number;
    cost?: number | null;
    reference?: string;
    createdAt?: Date;
    salesOrderId?: string | null;
    productionOrderId?: string | null;
    fromLocationId?: string | null;
    toLocationId?: string | null;
}) {
    return db!.stockMovement.create({
        data: {
            id: input.id,
            type: input.type ?? 'OUT',
            productVariantId: input.variant ?? 'fg-variant',
            quantity: input.quantity ?? 1,
            cost: input.cost,
            reference: input.reference ?? input.id,
            createdAt: input.createdAt ?? middle,
            salesOrderId: input.salesOrderId,
            productionOrderId: input.productionOrderId,
            fromLocationId: input.fromLocationId,
            toLocationId: input.toLocationId,
        },
    });
}

async function seedBase() {
    await db!.$executeRaw`TRUNCATE "User", "Account", "Product", "Location", "Customer", "FiscalPeriod" CASCADE`;
    await db!.user.create({
        data: {
            id: 'actor',
            email: 'cogs-diagnosis@example.invalid',
            password: 'fixture-not-a-real-account',
            role: 'FINANCE',
        },
    });
    await db!.location.create({
        data: { id: 'warehouse', name: 'Synthetic warehouse', slug: 'cogs-diagnosis' },
    });
    await db!.customer.create({ data: { id: 'customer', name: 'Synthetic customer' } });
    await db!.account.createMany({
        data: [
            { id: 'inventory-raw', code: 'TENANT-RAW', name: 'Raw stock', type: 'ASSET', category: 'CURRENT_ASSET' },
            { id: 'inventory-fg', code: 'TENANT-FG', name: 'Finished stock', type: 'ASSET', category: 'CURRENT_ASSET' },
            { id: 'wip', code: 'TENANT-WIP', name: 'Work in process', type: 'ASSET', category: 'CURRENT_ASSET' },
            { id: 'cogs', code: 'TENANT-HPP', name: 'Cost of sales', type: 'EXPENSE', category: 'COGS' },
            { id: 'opex', code: 'TENANT-OPEX', name: 'Operating expense', type: 'EXPENSE', category: 'OPERATING_EXPENSE' },
            { id: 'revenue', code: 'TENANT-REV', name: 'Revenue', type: 'REVENUE', category: 'OPERATING_REVENUE' },
            { id: 'ar', code: 'TENANT-AR', name: 'Receivable', type: 'ASSET', category: 'CURRENT_ASSET' },
        ],
    });
    await db!.product.create({
        data: {
            id: 'raw', name: 'Synthetic raw material', productType: 'RAW_MATERIAL',
            inventoryAccountId: 'inventory-raw', wipAccountId: 'wip', cogsAccountId: 'cogs',
            variants: { create: { id: 'raw-variant', name: 'Raw variant', skuCode: 'COGS-RAW', primaryUnit: 'KG' } },
        },
    });
    await db!.product.create({
        data: {
            id: 'fg', name: 'Synthetic finished item', productType: 'FINISHED_GOOD',
            inventoryAccountId: 'inventory-fg', wipAccountId: 'wip', cogsAccountId: 'cogs',
            variants: { create: { id: 'fg-variant', name: 'Finished variant', skuCode: 'COGS-FG', primaryUnit: 'KG' } },
        },
    });
    await db!.salesOrder.create({
        data: {
            id: 'order', orderNumber: 'SO-COGS-DIAG', customerId: 'customer', status: 'SHIPPED', totalAmount: 10_000,
            items: { create: { id: 'order-line', productVariantId: 'fg-variant', quantity: 100, deliveredQty: 100, unitPrice: 100, subtotal: 10_000 } },
        },
    });
    await db!.deliveryOrder.create({
        data: {
            id: 'delivery', orderNumber: 'DO-COGS-DIAG', salesOrderId: 'order', sourceLocationId: 'warehouse', status: 'SHIPPED',
            items: { create: { productVariantId: 'fg-variant', quantity: 100 } },
        },
    });
    await db!.bom.create({
        data: {
            id: 'bom', name: 'Synthetic BOM', productVariantId: 'fg-variant', outputQuantity: 1,
            items: { create: { productVariantId: 'raw-variant', quantity: 5 } },
        },
    });
    await db!.productionOrder.create({
        data: {
            id: 'production', orderNumber: 'WO-COGS-DIAG', bomId: 'bom', plannedQuantity: 1,
            plannedStartDate: middle, locationId: 'warehouse', status: 'COMPLETED', actualQuantity: 1,
        },
    });
}

async function diagnose() {
    return db!.$transaction(tx => diagnoseCogsEconomicCompleteness(tx, period));
}

describe.skipIf(!db)('COGS economic diagnosis on disposable PostgreSQL', () => {
    beforeEach(seedBase);
    afterAll(async () => db?.$disconnect());

    it('executes all SQL branches and distinguishes zero, non-COGS, valid, return asymmetry and aggregate cost flow', async () => {
        const reference = 'Shipment for SO-COGS-DIAG via DO-COGS-DIAG';
        await movement({ id: 'shipment-covered', quantity: 10, reference, salesOrderId: 'order', fromLocationId: 'warehouse' });
        await journal({ id: 'journal-covered', referenceId: 'shipment-covered', debitAccount: 'cogs', creditAccount: 'inventory-fg', amount: 1_000 });
        await movement({ id: 'shipment-zero', quantity: 20, reference, salesOrderId: 'order', fromLocationId: 'warehouse' });
        await movement({ id: 'shipment-opex', quantity: 15, cost: 40, reference, salesOrderId: 'order', fromLocationId: 'warehouse' });
        await journal({ id: 'journal-opex', referenceId: 'shipment-opex', debitAccount: 'opex', creditAccount: 'inventory-fg', amount: 600 });

        await movement({ id: 'production-issue', variant: 'raw-variant', quantity: 5, cost: 100, productionOrderId: 'production', fromLocationId: 'warehouse' });
        await journal({ id: 'journal-issue', referenceId: 'production-issue', debitAccount: 'wip', creditAccount: 'inventory-raw', amount: 500 });
        await movement({ id: 'production-output', type: 'IN', quantity: 1, cost: 500, productionOrderId: 'production', toLocationId: 'warehouse' });
        await journal({ id: 'journal-output', referenceId: 'production-output', debitAccount: 'inventory-fg', creditAccount: 'wip', amount: 500 });
        await movement({ id: 'adjustment', type: 'ADJUSTMENT', variant: 'raw-variant', quantity: 1, cost: 10, fromLocationId: 'warehouse' });

        const returnMovement = await movement({
            id: 'return-movement', type: 'RETURN_IN', quantity: 1, cost: 100,
            reference: 'Return SR-COGS-DIAG; source shipment-covered', salesOrderId: 'order', toLocationId: 'warehouse',
        });
        const returnJournal = await journal({ id: 'return-journal', referenceId: returnMovement.id, debitAccount: 'inventory-fg', creditAccount: 'cogs', amount: 100 });
        await db!.salesReturn.create({
            data: {
                id: 'return', returnNumber: 'SR-COGS-DIAG', salesOrderId: 'order', customerId: 'customer',
                returnLocationId: 'warehouse', status: 'COMPLETED', totalAmount: 500, createdById: 'actor',
                items: { create: {
                    id: 'return-item', productVariantId: 'fg-variant', returnedQty: 1, unitPrice: 500, condition: 'GOOD',
                    receipt: { create: { sourceMovementId: 'shipment-covered', movementId: returnMovement.id, journalId: returnJournal.id, quantity: 1, restockValue: 100, receivedAt: middle, createdById: 'actor' } },
                } },
            },
        });
        await db!.auditLog.create({
            data: { id: 'audit-return', userId: 'actor', action: 'COMPLETE_SALES_RETURN', entityType: 'SalesReturn', entityId: 'return', toStatus: 'COMPLETED', createdAt: middle },
        });

        const result = await diagnose();
        expect(result.bookkeeping).toEqual({ reportCogs: 900, journalCogs: 900, difference: 0 });
        expect(result.shipments).toMatchObject({ count: 3, activeCount: 3, coveredCount: 1, incompleteSalesValue: 3_500 });
        expect(result.findings.map(row => row.code)).toEqual(expect.arrayContaining([
            'ZERO_VALUED_SALES_SHIPMENT',
            'SHIPMENT_COST_OUTSIDE_COGS',
            'COMPLETED_RETURN_WITHOUT_COMMERCIAL_CREDIT',
            'COGS_REVERSAL_WITHOUT_COMMERCIAL_REVERSAL',
            'INVENTORY_ADJUSTMENT_OUTSIDE_COGS',
            'COST_FLOW_UNATTRIBUTED',
        ]));
        expect(result.findings.find(row => row.code === 'SHIPMENT_COST_OUTSIDE_COGS')).toMatchObject({ amount: 600, amountBasis: 'posted_cost_journal' });
        expect(result.returns).toMatchObject({ goodReceiptCount: 1, physicalRestockValue: 100, activeCommercialCreditValue: 0 });
        expect(result.productionFlow.materialIssue).toMatchObject({ movementValue: 500, journalValue: 500 });
        expect(result.productionFlow.wipToOutput).toMatchObject({ movementValue: 500, journalValue: 500 });
        expect(result.productionFlow.sideFlows.adjustmentCount).toBe(1);
        expect(result.coverage.mandatoryComplete).toBe(false);
    });

    it('only suppresses an in-period shipment or production flow after a valid exact-inverse journal', async () => {
        const reference = 'Shipment for SO-COGS-DIAG via DO-COGS-DIAG';
        await movement({ id: 'shipment', quantity: 2, reference, salesOrderId: 'order', fromLocationId: 'warehouse' });
        await journal({ id: 'shipment-journal', referenceId: 'shipment', debitAccount: 'cogs', creditAccount: 'inventory-fg', amount: 200 });
        await movement({ id: 'bad-reversal', type: 'IN', quantity: 2, reference: `VOID: ${reference} [SOURCE:delivery]`, salesOrderId: 'order', toLocationId: 'warehouse' });

        await movement({ id: 'issue', variant: 'raw-variant', quantity: 2, cost: 50, productionOrderId: 'production', fromLocationId: 'warehouse', reference: 'ISSUE' });
        await journal({ id: 'issue-journal', referenceId: 'issue', debitAccount: 'wip', creditAccount: 'inventory-raw', amount: 100 });
        await movement({ id: 'bad-production-reversal', type: 'IN', variant: 'raw-variant', quantity: 2, cost: 50, productionOrderId: 'production', toLocationId: 'warehouse', reference: 'VOID: ISSUE [SOURCE:issue]' });

        const invalid = await diagnose();
        expect(invalid.shipments).toMatchObject({ activeCount: 1, reversedCount: 0 });
        expect(invalid.findings.map(row => row.code)).toEqual(expect.arrayContaining([
            'SHIPMENT_REVERSAL_INVALID',
            'PRODUCTION_REVERSAL_JOURNAL_INVALID',
        ]));

        await journal({ id: 'shipment-reversal-journal', referenceId: 'bad-reversal', debitAccount: 'inventory-fg', creditAccount: 'cogs', amount: 200 });
        await journal({ id: 'production-reversal-journal', referenceId: 'bad-production-reversal', debitAccount: 'inventory-raw', creditAccount: 'wip', amount: 100 });
        const valid = await diagnose();
        expect(valid.shipments).toMatchObject({ activeCount: 0, reversedCount: 1 });
        expect(valid.productionFlow.materialIssue.count).toBe(0);
    });

    it('keeps cross-period reversals visible and preserves stable aggregate totals when samples truncate', async () => {
        const reference = 'Shipment for SO-COGS-DIAG via DO-COGS-DIAG';
        const rows = Array.from({ length: 22 }, (_, index) => ({
            id: `zero-${String(index).padStart(2, '0')}`, type: 'OUT' as const, productVariantId: 'fg-variant',
            fromLocationId: 'warehouse', quantity: 1, salesOrderId: 'order', reference, createdAt: index === 0 ? start : index === 21 ? end : middle,
        }));
        await db!.stockMovement.createMany({ data: rows });
        await movement({
            id: 'later-reversal', type: 'IN', quantity: 1, reference: `VOID: ${reference} [SOURCE:delivery]`,
            createdAt: new Date('2026-09-01T00:00:00.000Z'), salesOrderId: 'order', toLocationId: 'warehouse',
        });
        const result = await diagnose();
        expect(result.shipments).toMatchObject({ count: 22, activeCount: 22, reversedCount: 0, incompleteSalesValue: 2_200 });
        const zeroOrMissing = result.findings.find(row => ['ZERO_VALUED_SALES_SHIPMENT', 'SHIPMENT_JOURNAL_MISSING', 'SHIPMENT_REVERSAL_INVALID'].includes(row.code));
        expect(zeroOrMissing).toMatchObject({ count: 22, amount: 2_200 });
        expect(zeroOrMissing?.samples).toHaveLength(20);
        expect(result.findings.map(row => row.code)).toContain('SHIPMENT_REVERSAL_INVALID');
        expect(result.coverage.dimensions).toContainEqual(expect.objectContaining({ code: 'BOUNDED_SAMPLES', status: 'partial' }));
    });
});
