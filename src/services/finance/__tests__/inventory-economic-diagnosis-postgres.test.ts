const end = new Date('2026-08-31T16:59:59.999Z');
const middle = new Date('2026-08-15T00:00:00.000Z');

async function movement(input: {
    id: string;
    type: 'IN' | 'OUT' | 'TRANSFER' | 'ADJUSTMENT' | 'PURCHASE' | 'RETURN_IN' | 'RETURN_OUT';
    variant?: string;
    quantity?: number;
    cost?: number | null;
    reference?: string | null;
    createdAt?: Date;
    salesOrderId?: string | null;
    goodsReceiptId?: string | null;
    productionOrderId?: string | null;
    fromLocationId?: string | null;
    toLocationId?: string | null;
}) {
    return db!.stockMovement.create({
        data: {
            id: input.id,
            type: input.type,
            productVariantId: input.variant ?? 'fg-variant',
            quantity: input.quantity ?? 1,
            cost: input.cost,
            reference:
                input.reference === undefined ? input.id : input.reference,
            createdAt: input.createdAt ?? middle,
            salesOrderId: input.salesOrderId,
            goodsReceiptId: input.goodsReceiptId,
            productionOrderId: input.productionOrderId,
            fromLocationId: input.fromLocationId,
            toLocationId: input.toLocationId,
        },
    });
}

async function journal(input: {
    id: string;
    referenceId: string | null;
    debitAccount: string;
    creditAccount: string;
    amount: number;
    referenceType?: 'MANUAL_ENTRY' | 'GOODS_RECEIPT' | 'STOCK_ADJUSTMENT';
    reference?: string | null;
    entryDate?: Date;
    isAutoGenerated?: boolean;
}) {
    return db!.journalEntry.create({
        data: {
            id: input.id,
            entryNumber: input.id,
            entryDate: input.entryDate ?? middle,
            description: 'Synthetic inventory diagnosis fixture',
            reference:
                input.reference === undefined ? input.id : input.reference,
            referenceType: input.referenceType ?? 'MANUAL_ENTRY',
            referenceId: input.referenceId,
            status: 'POSTED',
            isAutoGenerated: input.isAutoGenerated ?? true,
            lines: {
                create: [
                    {
                        accountId: input.debitAccount,
                        debit: input.amount,
                        credit: 0,
                    },
                    {
                        accountId: input.creditAccount,
                        debit: 0,
                        credit: input.amount,
                    },
                ],
            },
        },
    });
}

