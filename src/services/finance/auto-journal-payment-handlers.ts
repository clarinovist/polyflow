import { JournalStatus, ReferenceType, type Prisma } from '@prisma/client';

import { prisma } from '@/lib/core/prisma';
import { BusinessRuleError, NotFoundError } from '@/lib/errors/errors';
import { AccountingService } from '../accounting/accounting-service';

import {
    getAccountByRole,
    resolvePaymentBankAccount,
} from './auto-journal-shared';

export async function handleSalesPayment(
    paymentId: string,
    amount: number,
    method: string = 'Bank Transfer',
    // Tanggal buku jurnal. Default: payment.paymentDate (jalur direct-entry, finance input
    // sendiri saat itu). Jalur verifikasi remittance mengirim tanggal verifikasi finance —
    // sama dengan paymentDate-nya, jadi jurnal dan payment selalu jatuh di hari yang sama.
    journalDate?: Date,
    tx?: Prisma.TransactionClient,
) {
    const db = tx ?? prisma;
    // Zero/negative amounts have no journal to post — skip by design. Anything
    // else must be loud (call sites log it) so the repair pass can pick it up.
    if (!amount || amount <= 0 || !isFinite(amount)) {
        console.warn(
            `[AutoJournal] Invalid payment amount: ${amount} for paymentId=${paymentId}`,
        );
        return;
    }

    const payment = await db.payment.findUnique({
        where: { id: paymentId },
        include: { invoice: true },
    });
    const invoice = payment?.invoice;
    if (!payment || !invoice) {
        throw new NotFoundError('Payment', paymentId);
    }
    if (payment.barterSettlementId || payment.method === 'Barter') {
        throw new BusinessRuleError(
            'Kaki pembayaran barter hanya boleh dijurnal melalui header settlement.',
            { paymentId },
            'BARTER_PAYMENT_JOURNAL_FORBIDDEN',
        );
    }

    // Idempotency guard: payment call sites run post-commit with swallowed
    // errors — a retry must not double-credit AR for the same payment.
    const existing = await db.journalEntry.findFirst({
        where: {
            referenceType: ReferenceType.SALES_PAYMENT,
            referenceId: paymentId,
            status: { not: JournalStatus.VOIDED },
        },
        select: { id: true },
    });
    if (existing) return;

    const paymentMethod = payment.method || method;
    const paymentAcc = await resolvePaymentBankAccount(
        paymentMethod,
        payment.destinationBank,
    );
    const arAcc = await getAccountByRole('accounts-receivable');

    const entry = {
        entryDate: journalDate ?? payment.paymentDate,
        description: `Payment Receipt (${paymentMethod}) for ${invoice.invoiceNumber}`,
        reference: payment.paymentNumber || `PAY-${invoice.invoiceNumber}`,
        referenceType: ReferenceType.SALES_PAYMENT,
        referenceId: payment.id,
        isAutoGenerated: true,
        status: JournalStatus.POSTED,
        lines: [
            {
                accountId: paymentAcc.id,
                debit: amount,
                credit: 0,
                description: 'Payment In',
            },
            {
                accountId: arAcc.id,
                debit: 0,
                credit: amount,
                description: 'AR Payment',
            },
        ],
    };
    if (tx) await AccountingService.createJournalEntry(entry, tx);
    else await AccountingService.createJournalEntry(entry);
}

export async function handlePurchasePayment(
    paymentId: string,
    amount: number,
    method: string = 'Bank Transfer',
    journalDate?: Date,
    tx?: Prisma.TransactionClient,
) {
    const db = tx ?? prisma;
    // Zero/negative amounts have no journal to post — skip by design.
    if (!amount || amount <= 0 || !isFinite(amount)) {
        console.warn(
            `[AutoJournal] Invalid payment amount: ${amount} for paymentId=${paymentId}`,
        );
        return;
    }

    const payment = await db.payment.findUnique({
        where: { id: paymentId },
        include: { purchaseInvoice: true },
    });
    const invoice = payment?.purchaseInvoice;
    if (!payment || !invoice) {
        throw new NotFoundError('Payment', paymentId);
    }
    if (payment.barterSettlementId || payment.method === 'Barter') {
        throw new BusinessRuleError(
            'Kaki offset barter hanya boleh dijurnal melalui header settlement.',
            { paymentId },
            'BARTER_PAYMENT_JOURNAL_FORBIDDEN',
        );
    }

    // Idempotency guard — same rationale as the sales side.
    const existing = await db.journalEntry.findFirst({
        where: {
            referenceType: ReferenceType.PURCHASE_PAYMENT,
            referenceId: paymentId,
            status: { not: JournalStatus.VOIDED },
        },
        select: { id: true },
    });
    if (existing) return;

    const paymentMethod = payment.method || method;
    const paymentAcc = await resolvePaymentBankAccount(
        paymentMethod,
        payment.destinationBank,
    );
    const apAcc = await getAccountByRole('accounts-payable');

    const entry = {
        entryDate: journalDate ?? payment.paymentDate,
        description: `Payment (${paymentMethod}) for Purchase Invoice ${invoice.invoiceNumber}`,
        reference: payment.paymentNumber || `PAY-${invoice.invoiceNumber}`,
        referenceType: ReferenceType.PURCHASE_PAYMENT,
        referenceId: payment.id,
        isAutoGenerated: true,
        status: JournalStatus.POSTED,
        lines: [
            {
                accountId: apAcc.id,
                debit: amount,
                credit: 0,
                description: 'AP Payment',
            },
            {
                accountId: paymentAcc.id,
                debit: 0,
                credit: amount,
                description: 'Payment Out',
            },
        ],
    };
    if (tx) await AccountingService.createJournalEntry(entry, tx);
    else await AccountingService.createJournalEntry(entry);
}
