import { createHash } from 'node:crypto';
import { Prisma, type PrismaClient } from '@prisma/client';

/**
 * Operator-only normalization of legacy automatic scrap on a fully absorbed WO.
 * Before the scrap-cost fix, automatic scrap entered with cost NULL and no journal,
 * which the WIP allocator rightly rejects. When every material value already went
 * into the single good output, the scrap's allocated cost is provably zero: record
 * that explicitly. No journal, quantity, inventory or WAC is written. Never called
 * by output posting; dry-run is read-only and apply requires its fingerprint.
 */
export const ABSORBED_SCRAP_ACTION = 'NORMALIZE_ABSORBED_PRODUCTION_SCRAP';
export type AbsorbedScrapSkip =
    | 'AFFAL_ONLY_DEFERRED'
    | 'PARTIAL_ABSORPTION'
    | 'JOURNALED_SCRAP'
    | 'VALUED_SCRAP_STOCK'
    | 'UNSUPPORTED_HISTORY'
    | 'SOURCE_MISMATCH';
export class AbsorbedScrapRejection extends Error {
    constructor(
        readonly code: AbsorbedScrapSkip,
        message: string,
    ) {
        super(message);
    }
}
export interface AbsorbedScrapRequest {
    database: string;
    orderId: string;
    orderNumber: string;
    actorId: string;
    reason: string;
    expectedFingerprint?: string;
    backupReference?: string;
}

const ACTIVE_STATUSES = [
    'DRAFT',
    'RELEASED',
    'IN_PROGRESS',
    'WAITING_MATERIAL',
];
const SCRAP_LINK_WINDOW_MS = 30000;
const zero = () => new Prisma.Decimal(0);
const hash = (value: unknown) =>
    createHash('sha256').update(JSON.stringify(value)).digest('hex');
function skip(code: AbsorbedScrapSkip, message: string): never {
    throw new AbsorbedScrapRejection(code, message);
}
function fail(message: string): never {
    throw new Error(message);
}
type Tx = Prisma.TransactionClient;
type Journal = Prisma.JournalEntryGetPayload<{
    include: { lines: { include: { account: true } } };
}>;
type Movement = Prisma.StockMovementGetPayload<object>;

/** Same journal shape the WIP allocator accepts for a production source. */
function journalValue(journal: Journal, movement: Movement) {
    if (
        journal.status !== 'POSTED' ||
        !journal.isAutoGenerated ||
        journal.referenceType !== 'MANUAL_ENTRY' ||
        journal.referenceId !== movement.id ||
        journal.lines.length < 2
    )
        skip('SOURCE_MISMATCH', 'Jurnal sumber tidak valid.');
    for (const line of journal.lines) {
        if (
            line.account.type !== 'ASSET' ||
            line.currency !== 'IDR' ||
            !line.exchangeRate.eq(1) ||
            line.debit.lt(0) ||
            line.credit.lt(0) ||
            line.debit.gt(0) === line.credit.gt(0)
        )
            skip('SOURCE_MISMATCH', 'Vektor jurnal sumber tidak valid.');
    }
    const debit = journal.lines.reduce(
        (sum, line) => sum.plus(line.debit),
        zero(),
    );
    const credit = journal.lines.reduce(
        (sum, line) => sum.plus(line.credit),
        zero(),
    );
    if (
        !debit.gt(0) ||
        !debit.eq(credit) ||
        !debit.eq(movement.quantity.mul(movement.cost!).toDecimalPlaces(2))
    ) {
        skip(
            'SOURCE_MISMATCH',
            'Nilai jurnal sumber tidak sama dengan kuantitas × biaya.',
        );
    }
    return debit;
}

async function loadOrder(tx: Tx, orderId: string, orderNumber: string) {
    const order = await tx.productionOrder.findUnique({
        where: { id: orderId },
        include: { bom: true },
    });
    if (!order || order.orderNumber !== orderNumber)
        skip('SOURCE_MISMATCH', 'SPK tidak ditemukan atau nomornya berbeda.');
    if (
        order.status !== 'IN_PROGRESS' ||
        order.isMaklon ||
        order.actualPackagingEnabled ||
        (order.estimatedConversionCost &&
            !order.estimatedConversionCost.isZero())
    )
        skip(
            'UNSUPPORTED_HISTORY',
            'Jenis/status SPK di luar mode penyerapan penuh.',
        );
    const executions = await tx.productionExecution.findMany({
        where: { productionOrderId: order.id },
        orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    });
    if (executions.some((e) => e.status === 'VOIDED'))
        skip('UNSUPPORTED_HISTORY', 'SPK memiliki eksekusi yang di-void.');
    const scrapReported = (e: (typeof executions)[number]) =>
        e.scrapQuantity.plus(e.scrapProngkolQty).plus(e.scrapDaunQty);
    if (
        executions.some(
            (e) => e.quantityProduced.isZero() && scrapReported(e).gt(0),
        )
    ) {
        skip(
            'AFFAL_ONLY_DEFERRED',
            'SPK memiliki eksekusi affal-only/sisa WIP; kebijakan biayanya belum diputuskan Finance.',
        );
    }
    const positive = executions.filter((e) => e.quantityProduced.gt(0));
    if (positive.length !== 1)
        skip('UNSUPPORTED_HISTORY', 'SPK bukan satu hasil tunggal.');
    const execution = positive[0];
    if (
        execution.status !== 'COMPLETED' ||
        !execution.endTime ||
        !order.actualQuantity?.eq(execution.quantityProduced)
    ) {
        skip(
            'SOURCE_MISMATCH',
            'Eksekusi hasil tidak cocok dengan jumlah aktual SPK.',
        );
    }
    return { order, executions, execution };
}

async function loadSources(
    tx: Tx,
    order: Awaited<ReturnType<typeof loadOrder>>['order'],
    execution: Awaited<ReturnType<typeof loadOrder>>['execution'],
) {
    const movements = await tx.stockMovement.findMany({
        where: { productionOrderId: order.id },
        orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    });
    if (
        movements.some(
            (m) =>
                !['IN', 'OUT'].includes(m.type) ||
                m.reversalOfId ||
                m.goodsReceiptId ||
                m.salesOrderId ||
                m.companyOwned === false ||
                m.productionExecutionId ||
                !m.quantity.gt(0) ||
                /^(VOID:|CORRECTION:)/.test(m.reference ?? ''),
        ) ||
        (await tx.stockMovement.count({
            where: { reversalOfId: { in: movements.map((m) => m.id) } },
        }))
    ) {
        skip(
            'UNSUPPORTED_HISTORY',
            'Riwayat movement SPK di luar pola legacy (pembalik/tautan/pihak luar).',
        );
    }
    const issues = movements.filter((m) => m.type === 'OUT');
    const outputs = movements.filter(
        (m) =>
            m.type === 'IN' &&
            m.productVariantId === order.bom.productVariantId,
    );
    const scraps = movements.filter(
        (m) =>
            m.type === 'IN' &&
            m.productVariantId !== order.bom.productVariantId,
    );
    if (
        outputs.length !== 1 ||
        !outputs[0].quantity.eq(execution.quantityProduced) ||
        !issues.length ||
        !scraps.length ||
        scraps.length > 2 ||
        [...issues, outputs[0]].some((m) => m.cost == null)
    )
        skip('SOURCE_MISMATCH', 'Komposisi bahan/hasil/affal tidak sesuai.');
    const journals = await tx.journalEntry.findMany({
        where: { referenceId: { in: movements.map((m) => m.id) } },
        include: {
            lines: { include: { account: true }, orderBy: { id: 'asc' } },
        },
        orderBy: { id: 'asc' },
    });
    const forMove = (id: string) =>
        journals.filter((j) => j.referenceId === id);
    if (scraps.some((m) => forMove(m.id).length))
        skip(
            'JOURNALED_SCRAP',
            'Ada affal berjurnal; gunakan rekonsiliasi affal berjurnal, bukan mode ini.',
        );
    return { movements, issues, output: outputs[0], scraps, journals, forMove };
}

/** Every WIP leg debited by material must be credited by the good output. */
async function provenAbsorption(
    tx: Tx,
    sources: Awaited<ReturnType<typeof loadSources>>,
) {
    const { issues, output, journals, forMove } = sources;
    const vector = new Map<string, Prisma.Decimal>();
    const add = (accountId: string, value: Prisma.Decimal) =>
        vector.set(accountId, (vector.get(accountId) ?? zero()).plus(value));
    for (const movement of [...issues, output]) {
        const own = forMove(movement.id);
        if (own.length !== 1)
            skip('SOURCE_MISMATCH', 'Jurnal sumber bahan/hasil bukan satu.');
        journalValue(own[0], movement);
        for (const line of own[0].lines) {
            if (movement.type === 'OUT' && line.debit.gt(0))
                add(line.accountId, line.debit);
            if (movement.type === 'IN' && line.credit.gt(0))
                add(line.accountId, line.credit.negated());
        }
    }
    if (
        await tx.journalEntry.count({
            where: { referenceId: { in: journals.map((j) => j.id) } },
        })
    )
        skip('UNSUPPORTED_HISTORY', 'Jurnal sumber telah dibalik.');
    if ([...vector.values()].some((value) => !value.isZero()))
        skip(
            'PARTIAL_ABSORPTION',
            'Biaya bahan belum seluruhnya terserap hasil (ada sisa WIP).',
        );
    return journalValue(forMove(output.id)[0], output);
}

async function provenScraps(
    tx: Tx,
    orderNumber: string,
    execution: Awaited<ReturnType<typeof loadOrder>>['execution'],
    scraps: Movement[],
    orderId: string,
) {
    const records = await tx.scrapRecord.findMany({
        where: { productionOrderId: orderId },
        orderBy: { id: 'asc' },
    });
    const reported = [execution.scrapProngkolQty, execution.scrapDaunQty]
        .filter((q) => q.gt(0))
        .map(String)
        .sort()
        .join('|');
    if (
        records.length !== scraps.length ||
        new Set(scraps.map((m) => m.productVariantId)).size !== scraps.length ||
        reported !==
            scraps
                .map((m) => m.quantity.toString())
                .sort()
                .join('|')
    )
        skip('SOURCE_MISMATCH', 'Rincian affal eksekusi tidak sesuai sumber.');
    const inventories = [];
    for (const m of scraps) {
        const variant = await tx.productVariant.findUnique({
            where: { id: m.productVariantId },
            include: { product: true },
        });
        const matches = records.filter(
            (r) =>
                r.productVariantId === m.productVariantId &&
                r.quantity.eq(m.quantity) &&
                r.locationId === m.toLocationId &&
                r.productionExecutionId === execution.id,
        );
        if (
            variant?.product.productType !== 'SCRAP' ||
            m.cost !== null ||
            !m.toLocationId ||
            m.fromLocationId ||
            m.reference !== `Production Scrap: ${orderNumber}` ||
            matches.length !== 1 ||
            Math.abs(m.createdAt.getTime() - execution.createdAt.getTime()) >
                SCRAP_LINK_WINDOW_MS
        )
            skip('SOURCE_MISMATCH', 'Atribusi affal historis tidak terbukti.');
        const inventory = await tx.inventory.findUnique({
            where: {
                locationId_productVariantId: {
                    locationId: m.toLocationId,
                    productVariantId: m.productVariantId,
                },
            },
        });
        if (!inventory)
            skip('SOURCE_MISMATCH', 'Persediaan affal tidak ditemukan.');
        // A positive WAC means the legacy receipt inflated stock value: that needs a valuation
        // correction, not this metadata-only mode. NULL/0 stays exactly as it is.
        if (inventory.averageCost && !inventory.averageCost.isZero())
            skip(
                'VALUED_SCRAP_STOCK',
                'Stok affal sudah bernilai; perlu koreksi valuasi terpisah.',
            );
        inventories.push(inventory);
    }
    return { records, inventories };
}

async function inspect(
    tx: Tx,
    database: string,
    orderId: string,
    orderNumber: string,
) {
    const { order, executions, execution } = await loadOrder(
        tx,
        orderId,
        orderNumber,
    );
    const sources = await loadSources(tx, order, execution);
    const absorbedValue = await provenAbsorption(tx, sources);
    const { records, inventories } = await provenScraps(
        tx,
        order.orderNumber,
        execution,
        sources.scraps,
        order.id,
    );
    const fingerprint = hash({
        database,
        order,
        executions,
        movements: sources.movements,
        journals: sources.journals,
        records,
        inventories,
    });
    return {
        order,
        execution,
        scraps: sources.scraps,
        inventories,
        absorbedValue,
        fingerprint,
    };
}
type Evidence = Awaited<ReturnType<typeof inspect>>;

function preview(evidence: Evidence) {
    return {
        changed: false,
        alreadyApplied: false,
        fingerprint: evidence.fingerprint,
        orderNumber: evidence.order.orderNumber,
        executionId: evidence.execution.id,
        absorbedValue: evidence.absorbedValue.toString(),
        scraps: evidence.scraps.map((m, i) => ({
            movementId: m.id,
            quantity: m.quantity.toString(),
            averageCost:
                evidence.inventories[i].averageCost?.toString() ?? null,
        })),
    };
}

async function assertTarget(tx: Tx, database: string) {
    const [identity] = await tx.$queryRaw<
        Array<{ name: string }>
    >`SELECT current_database() AS name`;
    if (identity?.name !== database)
        fail('Database bukan target yang disetujui.');
}

/** Read-only classification of every active WO holding legacy NULL-cost unjournaled scrap. */
export async function scanAbsorbedScrap(
    db: PrismaClient,
    { database }: { database: string },
) {
    return db.$transaction(
        async (tx) => {
            await tx.$executeRaw`SET TRANSACTION READ ONLY`;
            await assertTarget(tx, database);
            const candidates = await tx.$queryRaw<
                Array<{ id: string; orderNumber: string }>
            >`
            SELECT DISTINCT o.id, o."orderNumber" FROM "ProductionOrder" o
            JOIN "StockMovement" m ON m."productionOrderId" = o.id
            JOIN "ProductVariant" v ON v.id = m."productVariantId" JOIN "Product" p ON p.id = v."productId"
            WHERE o.status::text IN (${Prisma.join(ACTIVE_STATUSES)}) AND m.type = 'IN' AND p."productType" = 'SCRAP'
              AND m.cost IS NULL AND NOT EXISTS (SELECT 1 FROM "JournalEntry" j WHERE j."referenceId" = m.id)
            ORDER BY o."orderNumber"`;
            const results = [];
            for (const candidate of candidates) {
                try {
                    const evidence = await inspect(
                        tx,
                        database,
                        candidate.id,
                        candidate.orderNumber,
                    );
                    results.push({
                        orderId: candidate.id,
                        eligible: true,
                        ...preview(evidence),
                    });
                } catch (error) {
                    if (!(error instanceof AbsorbedScrapRejection)) throw error;
                    results.push({
                        orderId: candidate.id,
                        orderNumber: candidate.orderNumber,
                        eligible: false,
                        code: error.code,
                        reason: error.message,
                    });
                }
            }
            return results;
        },
        {
            isolationLevel: Prisma.TransactionIsolationLevel.RepeatableRead,
            timeout: 30000,
        },
    );
}

export async function normalizeAbsorbedScrap(
    db: PrismaClient,
    input: AbsorbedScrapRequest,
    execute = false,
) {
    if (
        !input.database ||
        !input.orderId ||
        !input.orderNumber ||
        !input.actorId ||
        input.reason.trim().length < 12
    ) {
        fail('Identitas/bukti koreksi wajib lengkap.');
    }
    if (
        execute &&
        (!/^[a-f0-9]{64}$/.test(input.expectedFingerprint ?? '') ||
            !input.backupReference?.trim())
    ) {
        fail(
            'Eksekusi wajib fingerprint dry-run dan referensi backup terverifikasi.',
        );
    }
    return db.$transaction(
        async (tx) => {
            if (!execute) await tx.$executeRaw`SET TRANSACTION READ ONLY`;
            await assertTarget(tx, input.database);
            const actor = await tx.user.findUnique({
                where: { id: input.actorId },
                select: { role: true },
            });
            if (
                input.actorId !== 'system' &&
                !['ADMIN', 'FINANCE'].includes(actor?.role ?? '')
            )
                fail('Aktor koreksi tidak diizinkan.');
            // Serializes against output posting and void, which both lock the WO first.
            if (execute)
                await tx.$queryRaw`SELECT id FROM "ProductionOrder" WHERE id = ${input.orderId} FOR UPDATE`;
            const dedupeKey = `${ABSORBED_SCRAP_ACTION}:${input.orderId}`;
            const previous = await tx.auditLog.findUnique({
                where: { dedupeKey },
            });
            if (previous) {
                const saved = previous.changes as Prisma.JsonObject | null;
                if (
                    !saved ||
                    saved.orderNumber !== input.orderNumber ||
                    saved.database !== input.database ||
                    (execute && saved.fingerprint !== input.expectedFingerprint)
                )
                    fail('Identitas koreksi terdahulu berbeda.');
                return {
                    changed: false,
                    alreadyApplied: true,
                    auditId: previous.id,
                    fingerprint: String(saved.fingerprint),
                };
            }
            const evidence = await inspect(
                tx,
                input.database,
                input.orderId,
                input.orderNumber,
            );
            const result = preview(evidence);
            if (!execute) return result;
            if (evidence.fingerprint !== input.expectedFingerprint)
                fail(
                    'Data berubah setelah dry-run; tidak ada koreksi diterapkan.',
                );
            await tx.$queryRaw(
                Prisma.sql`SELECT id FROM "StockMovement" WHERE id IN (${Prisma.join(evidence.scraps.map((m) => m.id))}) ORDER BY id FOR UPDATE`,
            );
            for (const m of evidence.scraps) {
                const updated = await tx.stockMovement.updateMany({
                    where: {
                        id: m.id,
                        cost: null,
                        productionExecutionId: null,
                    },
                    data: {
                        cost: 0,
                        companyOwned: true,
                        productionExecutionId: evidence.execution.id,
                    },
                });
                if (updated.count !== 1)
                    fail(
                        'Affal berubah bersamaan; tidak ada koreksi diterapkan.',
                    );
            }
            const audit = await tx.auditLog.create({
                data: {
                    userId: input.actorId,
                    action: ABSORBED_SCRAP_ACTION,
                    entityType: 'ProductionOrder',
                    entityId: evidence.order.id,
                    dedupeKey,
                    details: input.reason,
                    changes: JSON.parse(
                        JSON.stringify({
                            database: input.database,
                            orderNumber: input.orderNumber,
                            fingerprint: evidence.fingerprint,
                            backupReference: input.backupReference,
                            executionId: evidence.execution.id,
                            absorbedValue: evidence.absorbedValue,
                            originalMovements: evidence.scraps,
                            inventories: evidence.inventories,
                            netPhysicalQuantityChange: 0,
                            journalsCreated: 0,
                        }),
                    ) as Prisma.InputJsonObject,
                },
            });
            return { ...result, changed: true, auditId: audit.id };
        },
        {
            isolationLevel: Prisma.TransactionIsolationLevel.Serializable,
            timeout: 30000,
        },
    );
}
