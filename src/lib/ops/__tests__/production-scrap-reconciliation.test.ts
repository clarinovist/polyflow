import { describe, expect, it, vi } from 'vitest';
import { Prisma, type PrismaClient } from '@prisma/client';
import { reconcileProductionScrap, type ScrapReconciliationRequest } from '../production-scrap-reconciliation';
import { parseScrapReconciliationArgs } from '../../../../scripts/reconcile-production-scrap';

const at = new Date('2026-10-01T01:00:00Z');
const d = (value: number) => new Prisma.Decimal(value);
const input: ScrapReconciliationRequest = { database: 'synthetic_test', orderId: 'wo', orderNumber: 'WO-SYNTHETIC',
    executionId: 'exec', actorId: 'system', reason: 'Verified full-absorption correction' };
function fixture() {
    const movement = (id: string, type: 'IN' | 'OUT', productVariantId: string, quantity: number, cost: number | null) => ({
        id, type, productVariantId, quantity: d(quantity), cost: cost == null ? null : d(cost), productionOrderId: 'wo',
        toLocationId: type === 'IN' ? (productVariantId === 'fg' ? 'fg-store' : 'scrap-store') : null,
        fromLocationId: type === 'OUT' ? 'raw-store' : null, createdAt: at, reversalOfId: null, goodsReceiptId: null,
        salesOrderId: null, companyOwned: null, productionExecutionId: null,
        reference: productVariantId === 'leaf' || productVariantId === 'lump' ? 'Production Scrap: WO-SYNTHETIC' : id,
    });
    const movements = [movement('issue', 'OUT', 'raw', 14, 10), movement('output', 'IN', 'fg', 10, 14),
        movement('lump-move', 'IN', 'lump', 2, null), movement('leaf-move', 'IN', 'leaf', 2, null)];
    const journal = (id: string, debitAccount: string, creditAccount: string, value: number) => ({
        id: `j-${id}`, entryNumber: `JE-${id}`, status: 'POSTED', isAutoGenerated: true, referenceId: id, referenceType: 'MANUAL_ENTRY',
        lines: [{ accountId: debitAccount, debit: d(value), credit: d(0), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' } },
            { accountId: creditAccount, debit: d(0), credit: d(value), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' } }],
    });
    const journals = [journal('issue', 'wip', 'raw-account', 140), journal('output', 'fg-account', 'wip', 140), journal('lump-move', 'scrap-account', 'old-wip', 14)];
    const execution = { id: 'exec', productionOrderId: 'wo', status: 'COMPLETED', endTime: at, createdAt: at, quantityProduced: d(10), scrapQuantity: d(0), scrapProngkolQty: d(2), scrapDaunQty: d(2) };
    const records = ['leaf', 'lump'].map(id => ({ id: `record-${id}`, productionOrderId: 'wo', productionExecutionId: 'exec', productVariantId: id, quantity: d(2), locationId: 'scrap-store' }));
    const inventories = ['leaf', 'lump'].map(id => ({ id: `inventory-${id}`, productVariantId: id, locationId: 'scrap-store', quantity: d(12), averageCost: d(50) }));
    const order = { id: 'wo', orderNumber: 'WO-SYNTHETIC', status: 'IN_PROGRESS', isMaklon: false, actualPackagingEnabled: false, estimatedConversionCost: null,
        actualQuantity: d(10), bom: { productVariantId: 'fg' } };
    const tx = {
        $executeRaw: vi.fn(), $queryRaw: vi.fn().mockResolvedValue([{ name: 'synthetic_test' }]),
        user: { findUnique: vi.fn().mockResolvedValue({ role: 'ADMIN' }) },
        auditLog: { findUnique: vi.fn().mockResolvedValue(null), findMany: vi.fn().mockResolvedValue([]), create: vi.fn().mockResolvedValue({ id: 'audit' }) },
        productionOrder: { findUniqueOrThrow: vi.fn(async () => order) },
        productionExecution: { findUniqueOrThrow: vi.fn(async () => execution), count: vi.fn().mockResolvedValue(1) },
        stockMovement: { findMany: vi.fn(async ({ where }) => where.productionOrderId ? movements : []), count: vi.fn(async (_args: { where: { createdAt?: unknown } }) => 0),
            create: vi.fn(async ({ data }) => ({ ...data, id: `created-${data.type}` })), update: vi.fn() },
        scrapRecord: { findMany: vi.fn(async (_args: { where: { productionOrderId: string } }) => records) },
        productVariant: { findUniqueOrThrow: vi.fn().mockResolvedValue({ primaryUnit: 'KG', product: { productType: 'SCRAP' } }) },
        journalEntry: { findMany: vi.fn(async (_args: { where: { referenceId: { in: string[] } } }) => journals), count: vi.fn().mockResolvedValue(0), create: vi.fn().mockResolvedValue({ id: 'reverse-journal' }) },
        inventory: { findUniqueOrThrow: vi.fn(async ({ where }) => inventories.find(i => i.productVariantId === where.locationId_productVariantId.productVariantId)), update: vi.fn() },
        fiscalPeriod: { findFirst: vi.fn().mockResolvedValue({ id: 'period', status: 'OPEN' }) },
        journalLine: { aggregate: vi.fn().mockResolvedValue({ _sum: { debit: d(1000), credit: d(0) } }) },
    };
    const db = { $transaction: vi.fn(async fn => fn(tx)) } as unknown as PrismaClient;
    return { db, tx, movements, journals, order, execution, inventories };
}

describe('bounded historical scrap reconciliation', () => {
    it('previews in read-only transaction without any business write', async () => {
        const { db, tx } = fixture();
        const result = await reconcileProductionScrap(db, input);
        expect(result.changed).toBe(false);
        expect(result.fingerprint).toMatch(/^[a-f0-9]{64}$/);
        expect('inventory' in result && result.inventory[0].newAverage).toBe('41.6667');
        expect(tx.$executeRaw).toHaveBeenCalled();
        for (const writer of [tx.stockMovement.create, tx.stockMovement.update, tx.inventory.update, tx.journalEntry.create, tx.auditLog.create]) expect(writer).not.toHaveBeenCalled();
    });
    it('appends exact journal inverse and replacement, saves originals and never writes quantities', async () => {
        const { db, tx, journals, movements } = fixture();
        const original = JSON.stringify({ journals, movements });
        const preview = await reconcileProductionScrap(db, input);
        const result = await reconcileProductionScrap(db, { ...input, expectedFingerprint: preview.fingerprint, backupReference: 'verified-backup' }, true);
        expect(result.changed).toBe(true);
        expect(JSON.stringify({ journals, movements })).toBe(original);
        expect(tx.stockMovement.create).toHaveBeenCalledTimes(2);
        expect(tx.stockMovement.create).toHaveBeenCalledWith({ data: expect.objectContaining({ type: 'OUT', reversalOfId: 'lump-move', cost: null, quantity: d(2) }) });
        expect(tx.stockMovement.create).toHaveBeenCalledWith({ data: expect.objectContaining({ type: 'IN', cost: 0, quantity: d(2), productionExecutionId: 'exec' }) });
        expect(tx.stockMovement.update).toHaveBeenCalledWith({ where: { id: 'leaf-move' }, data: { cost: 0, companyOwned: true, productionExecutionId: 'exec' } });
        for (const [args] of tx.inventory.update.mock.calls) expect(Object.keys(args.data)).toEqual(['averageCost']);
        expect(tx.journalEntry.create.mock.calls[0][0].data.lines.create).toEqual(journals[2].lines.map(l => expect.objectContaining({ accountId: l.accountId, debit: l.credit, credit: l.debit })));
        expect(tx.auditLog.create.mock.calls[0][0].data.changes.originalMovements).toHaveLength(2);
    });
    it.each(['wrong-db', 'unauthorized', 'multiple-executions', 'wrong-order', 'maklon', 'missing-source', 'unabsorbed', 'journal-duplicate', 'voided-journal', 'reversed', 'closed-period', 'insufficient-gl', 'downstream', 'bad-stock'])('fails closed before writes: %s', async kind => {
        const { db, tx, order, journals, inventories } = fixture();
        if (kind === 'wrong-db') tx.$queryRaw.mockResolvedValue([{ name: 'other' }]);
        if (kind === 'unauthorized') tx.user.findUnique.mockResolvedValue(null);
        if (kind === 'multiple-executions') tx.productionExecution.count.mockResolvedValue(2);
        if (kind === 'wrong-order') order.orderNumber = 'OTHER';
        if (kind === 'maklon') order.isMaklon = true;
        if (kind === 'missing-source') tx.stockMovement.findMany.mockResolvedValue([]);
        if (kind === 'unabsorbed') journals[1].lines[0].debit = d(100);
        if (kind === 'journal-duplicate') journals.push(journals[2]);
        if (kind === 'voided-journal') journals[2].status = 'VOIDED';
        if (kind === 'reversed') tx.journalEntry.count.mockResolvedValue(1);
        if (kind === 'closed-period') tx.fiscalPeriod.findFirst.mockResolvedValue(null);
        if (kind === 'insufficient-gl') tx.journalLine.aggregate.mockResolvedValue({ _sum: { debit: d(1), credit: d(0) } });
        if (kind === 'downstream') tx.stockMovement.findMany.mockImplementation(async ({ where }) => where.productionOrderId ? fixture().movements : [{ type: 'OUT' }] as never);
        if (kind === 'bad-stock') inventories[0].quantity = d(1);
        await expect(reconcileProductionScrap(db, input)).rejects.toThrow();
        expect(tx.stockMovement.create).not.toHaveBeenCalled();
    });
    it('accepts only verified quantity-only later receipts when reconstructing historical average', async () => {
        const { db, tx, movements, inventories } = fixture();
        tx.stockMovement.findMany.mockImplementation(async ({ where }) => where.productionOrderId ? movements : [{
            ...movements[2], id: 'later', productionOrderId: 'later-wo', quantity: d(3), createdAt: new Date(at.getTime() + 1000),
        }]);
        tx.scrapRecord.findMany.mockImplementation(async ({ where }: { where: { productionOrderId: string } }) => where.productionOrderId === 'wo'
            ? ['leaf', 'lump'].map(id => ({ id, productionOrderId: 'wo', productVariantId: id, quantity: d(2), locationId: 'scrap-store', productionExecutionId: 'exec' }))
            : [{ recordedAt: new Date(at.getTime() + 1000), productionExecution: { status: 'COMPLETED' } }] as never);
        inventories.forEach(i => { i.quantity = d(15); });
        const result = await reconcileProductionScrap(db, input);
        expect('inventory' in result && result.inventory[0].newAverage).toBe('43.3333');
    });
    it('rejects a prior correction to the same inventory instead of treating changed WAC as historical', async () => {
        const { db, tx } = fixture();
        tx.auditLog.findMany.mockResolvedValue([{ changes: { inventoryStates: [{ inventory: { id: 'inventory-leaf' } }] } }]);
        await expect(reconcileProductionScrap(db, input)).rejects.toThrow('telah dikoreksi');
    });
    it.each(['valid', 'stock-drift', 'unseen-source', 'wrong-audit', 'later-write', 'bad-vector', 'bad-arithmetic'])('requires an exact verified valuation audit anchor: %s', async kind => {
        const { db, tx, movements, inventories, journals } = fixture();
        const priorSources = movements.slice(2).map(m => ({ ...m, id: `prior-${m.id}`, productionOrderId: 'prior-wo' }));
        const priorJ = { ...journals[2], id: 'prior-journal', referenceId: priorSources[0].id };
        const inverseJ = { ...priorJ, id: 'inverse-journal', referenceId: 'inverse-move', lines: priorJ.lines.map(l => ({ ...l, debit: l.credit, credit: l.debit })) };
        const pair = [{ ...priorSources[0], id: 'inverse-move', type: 'OUT', fromLocationId: 'scrap-store', toLocationId: null, reversalOfId: priorSources[0].id },
            { ...priorSources[0], id: 'replacement', type: 'IN', cost: d(0), companyOwned: true, productionExecutionId: 'prior-execution' }];
        const state = inventories.map(i => ({ inventory: { ...i }, movementId: priorSources.find(m => m.productVariantId === i.productVariantId)!.id,
            later: movements.filter(m => m.productVariantId === i.productVariantId), removedInflation: '100', newAverage: '41.6667' }));
        const audit = JSON.parse(JSON.stringify({ id: 'prior-audit', action: 'RECONCILE_PRODUCTION_SCRAP', entityType: 'ProductionExecution', entityId: 'prior-execution',
            changes: { database: input.database, orderNumber: 'PRIOR', fingerprint: 'f'.repeat(64), netPhysicalQuantityChange: 0,
                inventoryStates: state, originalMovements: priorSources, originalJournal: priorJ,
                reversalId: 'inverse-move', replacementId: 'replacement', reversalJournalId: 'inverse-journal' } }));
        audit.createdAt = new Date(at.getTime() + 1000);
        inventories.forEach(i => { i.averageCost = d(41.6667); });
        tx.auditLog.findMany.mockResolvedValue([audit]);
        tx.stockMovement.findMany.mockImplementation(async ({ where }) => where.productionOrderId ? movements : where.id?.in ? pair as never : []);
        tx.journalEntry.findMany.mockImplementation(async ({ where }: { where: { referenceId: { in: string[] } } }) => where.referenceId.in.includes('inverse-move') ? [priorJ, inverseJ] : journals);
        if (kind === 'stock-drift') inventories[0].averageCost = d(42);
        if (kind === 'unseen-source') audit.changes.inventoryStates[0].later = [];
        if (kind === 'later-write') tx.stockMovement.count.mockImplementation(async ({ where }: { where: { createdAt?: unknown } }) => where.createdAt ? 1 : 0);
        if (kind === 'bad-vector') inverseJ.lines[0].accountId = 'wrong';
        if (kind === 'bad-arithmetic') audit.changes.inventoryStates[0].removedInflation = '10';
        const run = reconcileProductionScrap(db, { ...input, valuationAuditId: kind === 'wrong-audit' ? 'wrong' : 'prior-audit' });
        if (kind === 'valid') {
            const result = await run;
            expect('inventory' in result && result.inventory[0].removedInflation).toBe('100');
            expect('inventory' in result && result.inventory[0].newAverage).toBe('33.3334');
        } else await expect(run).rejects.toThrow();
        expect(tx.stockMovement.create).not.toHaveBeenCalled();
    });
    it('refuses apply without evidence and rejects fingerprint drift', async () => {
        const { db, tx, inventories } = fixture();
        await expect(reconcileProductionScrap(db, input, true)).rejects.toThrow('fingerprint');
        const preview = await reconcileProductionScrap(db, input);
        inventories[0].quantity = d(13);
        await expect(reconcileProductionScrap(db, { ...input, expectedFingerprint: preview.fingerprint, backupReference: 'verified' }, true)).rejects.toThrow('Data berubah');
        expect(tx.stockMovement.create).not.toHaveBeenCalled();
    });
    it('returns prior audit idempotently but rejects a mismatched order', async () => {
        const { db, tx } = fixture();
        tx.auditLog.findUnique.mockResolvedValue({ id: 'audit', changes: { database: input.database, orderNumber: input.orderNumber, fingerprint: 'a'.repeat(64) } });
        expect((await reconcileProductionScrap(db, { ...input, expectedFingerprint: 'a'.repeat(64), backupReference: 'verified' }, true)).alreadyApplied).toBe(true);
        await expect(reconcileProductionScrap(db, { ...input, orderNumber: 'OTHER' })).rejects.toThrow('Identitas');
        expect(tx.stockMovement.create).not.toHaveBeenCalled();
    });
    it('requires CLI execute confirmation, target and reviewed evidence', () => {
        expect(() => parseScrapReconciliationArgs(['--execute'])).toThrow('--yes');
        expect(() => parseScrapReconciliationArgs([])).toThrow('database');
    });
});
