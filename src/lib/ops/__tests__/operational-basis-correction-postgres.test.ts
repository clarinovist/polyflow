import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import { Prisma } from '@prisma/client';
import { returnTestClient, verifyReturnTestDatabase } from '@/services/finance/__tests__/return-credit-postgres-fixture';
import { getWibMonthBounds, toBusinessDateString } from '@/lib/utils/timezone';
import { skuInventoryBasis } from '@/services/inventory/internal-usage-accounting';
import { correctOperationalBasis } from '../operational-basis-correction';

// Synthetic only: the correction must close exactly the subledger/journal gap,
// stay SKU-linked, and leave every other posting untouched.
const connection = process.env.RETURN_CREDIT_TEST_DATABASE_URL;
const db = connection ? returnTestClient(connection) : null;
const database = connection
    ? decodeURIComponent(new URL(connection).pathname.slice(1))
    : '';
const actor = 'corr-finance';
const today = toBusinessDateString(new Date());
const request = {
    database,
    skuCode: 'ATK-CORR',
    movementId: 'corr-adjustment',
    amount: '200.00',
    postingDate: today,
    actorId: actor,
    reason: 'Synthetic Finance-approved basis correction',
};

const balance = async (accountId: string) => {
    const sums = await db!.journalLine.aggregate({
        where: { accountId, journalEntry: { status: 'POSTED' } },
        _sum: { debit: true, credit: true },
    });
    return new Prisma.Decimal(sums._sum.debit ?? 0)
        .minus(sums._sum.credit ?? 0)
        .toNumber();
};

async function seed() {
    await verifyReturnTestDatabase(db!);
    await db!.$executeRaw`TRUNCATE "Product", "Location", "User", "Account", "JournalEntry", "FiscalPeriod", "SystemSequence", "AuditLog", "Inventory", "StockMovement", "ProductVariant" CASCADE`;
    await db!.user.create({
        data: {
            id: actor,
            name: 'Synthetic finance',
            email: 'corr@example.invalid',
            password: 'synthetic-only',
            role: 'FINANCE',
        },
    });
    await db!.account.createMany({
        data: [
            { id: 'corr-inv', code: '1-130', name: 'Synthetic inventory', type: 'ASSET', category: 'CURRENT_ASSET' },
            { id: 'corr-exp', code: '8-203', name: 'Synthetic loss', type: 'EXPENSE', category: 'OTHER_EXPENSE' },
            { id: 'corr-eq', code: '32000', name: 'Synthetic equity', type: 'EQUITY', category: 'CAPITAL' },
        ],
    });
    await db!.location.create({
        data: { id: 'corr-loc', name: 'Synthetic ATK', slug: 'corr-atk' },
    });
    await db!.product.create({
        data: { id: 'corr-product', name: 'Synthetic ATK item', productType: 'OPERATIONAL' },
    });
    await db!.productVariant.create({
        data: {
            id: 'corr-sku',
            productId: 'corr-product',
            name: 'Synthetic ATK variant',
            skuCode: 'ATK-CORR',
            primaryUnit: 'PCS',
        },
    });
    await db!.inventory.create({
        data: { locationId: 'corr-loc', productVariantId: 'corr-sku', quantity: 8, averageCost: 100 },
    });
    await db!.stockMovement.createMany({
        data: [
            { id: 'corr-opening', type: 'IN', productVariantId: 'corr-sku', toLocationId: 'corr-loc', quantity: 5, cost: 140, reference: 'Opening Balance - Sinkronisasi Inventory' },
            { id: 'corr-purchase', type: 'PURCHASE', productVariantId: 'corr-sku', toLocationId: 'corr-loc', quantity: 5, cost: 100, reference: 'GR-SYNTHETIC' },
            { id: 'corr-adjustment', type: 'ADJUSTMENT', productVariantId: 'corr-sku', fromLocationId: 'corr-loc', toLocationId: null, quantity: 10, cost: null, reference: 'OPN-SYNTHETIC' },
        ],
    });
    const journal = (entryNumber: string, referenceType: 'MANUAL_ENTRY' | 'GOODS_RECEIPT' | 'STOCK_ADJUSTMENT', referenceId: string, lines: Array<{ accountId: string; debit: number; credit: number }>) =>
        db!.journalEntry.create({
            data: {
                entryNumber,
                entryDate: new Date(),
                description: `Synthetic ${entryNumber}`,
                status: 'POSTED',
                isAutoGenerated: true,
                referenceType,
                referenceId,
                lines: { create: lines },
            },
        });
    await journal('CORR-OB', 'MANUAL_ENTRY', 'corr-opening', [
        { accountId: 'corr-inv', debit: 700, credit: 0 },
        { accountId: 'corr-eq', debit: 0, credit: 700 },
    ]);
    await journal('CORR-GR', 'GOODS_RECEIPT', 'corr-purchase', [
        { accountId: 'corr-inv', debit: 500, credit: 0 },
        { accountId: 'corr-eq', debit: 0, credit: 500 },
    ]);
    await journal('CORR-ADJ', 'STOCK_ADJUSTMENT', 'corr-adjustment', [
        { accountId: 'corr-exp', debit: 600, credit: 0 },
        { accountId: 'corr-inv', debit: 0, credit: 600 },
    ]);
    const [year, month] = today.split('-').map(Number);
    const bounds = getWibMonthBounds(year, month);
    await db!.fiscalPeriod.create({
        data: { name: 'Synthetic current', year, month, startDate: bounds.start, endDate: bounds.end, status: 'OPEN' },
    });
}

describe.skipIf(!db)('operational basis correction PostgreSQL contract', () => {
    beforeEach(seed);
    afterAll(async () => {
        await db?.$disconnect();
    });

    it('closes the SKU basis gap with one linked journal and keeps other balances intact', async () => {
        const preview = await correctOperationalBasis(db!, request);
        expect(preview).toMatchObject({
            changed: false,
            alreadyApplied: false,
            stockValue: '800.0000',
            basis: '600.00',
            gap: '200.0000',
            amount: '200.00',
            reference: 'ATK-BASIS-CORR:ATK-CORR:OPN-SYNTHETIC',
            debitAccount: { code: '1-130' },
            creditAccount: { code: '8-203' },
        });
        expect(await db!.journalEntry.count()).toBe(3);

        const applied = await correctOperationalBasis(
            db!,
            {
                ...request,
                expectedFingerprint: preview.fingerprint,
                backupReference: 'synthetic-backup',
            },
            true,
        );
        expect(applied).toMatchObject({ changed: true, alreadyApplied: false });

        const journal = await db!.journalEntry.findFirstOrThrow({
            where: { reference: 'ATK-BASIS-CORR:ATK-CORR:OPN-SYNTHETIC' },
            include: { lines: true },
        });
        expect(journal).toMatchObject({
            referenceType: 'STOCK_ADJUSTMENT',
            referenceId: 'corr-adjustment',
            isAutoGenerated: true,
            status: 'POSTED',
        });
        expect(
            journal.lines.map((line) => [
                line.accountId,
                Number(line.debit),
                Number(line.credit),
            ]),
        ).toEqual(
            expect.arrayContaining([
                ['corr-inv', 200, 0],
                ['corr-exp', 0, 200],
            ]),
        );
        expect(await balance('corr-inv')).toBe(800);
        expect(await balance('corr-exp')).toBe(400);
        expect(await balance('corr-eq')).toBe(-1200);
        expect(
            Object.fromEntries(
                [
                    ...(await db!.$transaction((tx) =>
                        skuInventoryBasis(tx, 'corr-sku'),
                    )),
                ].map(([key, value]) => [key, value.toNumber()]),
            ),
        ).toEqual({ 'corr-inv': 800 });
        expect(
            await db!.auditLog.count({
                where: { action: 'CORRECT_OPERATIONAL_BASIS' },
            }),
        ).toBe(1);
    });

    it('is idempotent after apply and refuses a stale fingerprint or a wrong amount', async () => {
        const preview = await correctOperationalBasis(db!, request);
        await correctOperationalBasis(
            db!,
            {
                ...request,
                expectedFingerprint: preview.fingerprint,
                backupReference: 'synthetic-backup',
            },
            true,
        );
        const again = await correctOperationalBasis(db!, request);
        expect(again.alreadyApplied).toBe(true);
        const second = await correctOperationalBasis(
            db!,
            {
                ...request,
                expectedFingerprint: again.fingerprint,
                backupReference: 'synthetic-backup',
            },
            true,
        );
        expect(second).toMatchObject({
            changed: false,
            alreadyApplied: true,
        });
        expect(await db!.journalEntry.count()).toBe(4);
    });

    it('rejects a stale fingerprint when the movement reference changes', async () => {
        const preview = await correctOperationalBasis(db!, request);
        await db!.stockMovement.update({
            where: { id: 'corr-adjustment' },
            data: { reference: 'OPN-CHANGED' },
        });
        await expect(
            correctOperationalBasis(
                db!,
                {
                    ...request,
                    expectedFingerprint: preview.fingerprint,
                    backupReference: 'synthetic-backup',
                },
                true,
            ),
        ).rejects.toThrow('Data berubah');
        expect(await db!.journalEntry.count()).toBe(3);
    });

    it('rejects a non-gap amount and a closed period', async () => {
        await expect(
            correctOperationalBasis(db!, { ...request, amount: '199.00' }),
        ).rejects.toThrow('Nominal harus sama');
        await db!.fiscalPeriod.updateMany({ data: { status: 'CLOSED' } });
        await expect(correctOperationalBasis(db!, request)).rejects.toThrow(
            'OPEN',
        );
    });
});
