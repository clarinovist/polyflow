import { describe, expect, it, vi } from 'vitest';
import { Prisma, type PrismaClient } from '@prisma/client';
import {
    correctOperationalBasis,
    OPERATIONAL_BASIS_CORRECTION_ACTION,
    type OperationalBasisCorrectionRequest,
} from '../operational-basis-correction';
import { parseOperationalBasisCorrectionArgs } from '../../../../scripts/correct-operational-basis';

const d = (value: Prisma.Decimal.Value) => new Prisma.Decimal(value);
const request: OperationalBasisCorrectionRequest = {
    database: 'synthetic_test',
    skuCode: 'AT222001',
    movementId: 'm-adj',
    amount: '200.00',
    postingDate: '2026-11-23',
    actorId: 'u-finance',
    reason: 'Finance-approved basis correction',
};

const account = (id: string, code: string, type: string, category: string) => ({
    id,
    code,
    name: code,
    type,
    category,
    currency: 'IDR',
    isActive: true,
    isCashAccount: false,
});

function fixture() {
    const inventory = account('inv', '1-130', 'ASSET', 'CURRENT_ASSET');
    const expense = account('exp', '8-203', 'EXPENSE', 'OTHER_EXPENSE');
    const source = {
        id: 'j-src',
        entryNumber: 'JE-SRC',
        reference: 'OPN-SYNTHETIC',
        referenceType: 'STOCK_ADJUSTMENT',
        referenceId: 'm-adj',
        status: 'POSTED',
        isAutoGenerated: true,
        createdAt: new Date('2026-10-02T00:00:00Z'),
        lines: [
            {
                accountId: 'inv',
                debit: d(0),
                credit: d(1000),
                account: inventory,
            },
            {
                accountId: 'exp',
                debit: d(1000),
                credit: d(0),
                account: expense,
            },
        ],
    };
    const state = {
        identity: 'synthetic_test',
        role: 'FINANCE',
        active: true,
        productType: 'OPERATIONAL',
        warehouses: [
            {
                id: 'inv-row',
                productVariantId: 'v-atk',
                quantity: d(8),
                averageCost: d(100),
                location: {
                    locationType: 'INTERNAL',
                    packagingOwnerCustomerId: null,
                },
            },
        ],
        movement: {
            id: 'm-adj',
            productVariantId: 'v-atk',
            type: 'ADJUSTMENT',
            fromLocationId: 'loc',
            toLocationId: null,
            quantity: d(10),
            reference: 'OPN-SYNTHETIC',
        },
        journals: [source] as unknown[],
        basisRows: [{ accountId: 'inv', value: d(600) }],
        period: { id: 'p-nov', status: 'OPEN' } as unknown,
        counterSums: {
            _sum: { debit: d(1000), credit: d(0) },
        },
        recheck: null as unknown,
    };
    let journal = 0;
    const tx = {
        $executeRaw: vi.fn(async (_q: TemplateStringsArray) => 0),
        $queryRaw: vi.fn(async (q: TemplateStringsArray) => {
            const sql = q.join('?');
            if (sql.includes('current_database'))
                return [{ name: state.identity }];
            if (sql.includes('FOR UPDATE')) return [];
            if (sql.includes('GROUP BY l."accountId"'))
                return state.basisRows;
            return [];
        }),
        user: {
            findUnique: vi.fn(async () => ({
                role: state.role,
                isActive: state.active,
            })),
        },
        productVariant: {
            findUnique: vi.fn(async () => ({
                id: 'v-atk',
                skuCode: 'AT222001',
                archivedAt: null,
                product: { productType: state.productType },
            })),
        },
        inventory: { findMany: vi.fn(async () => state.warehouses) },
        stockMovement: {
            findUnique: vi.fn(async () => state.movement),
        },
        journalEntry: {
            findMany: vi.fn(async () => state.journals),
            findUnique: vi.fn(async () => ({
                status: 'POSTED',
                isAutoGenerated: true,
            })),
            findFirst: vi.fn(async () => state.recheck),
            create: vi.fn(async (_args: unknown) => ({ id: `j${++journal}` })),
        },
        fiscalPeriod: {
            findFirst: vi.fn(async () => state.period),
        },
        journalLine: {
            aggregate: vi.fn(async () => state.counterSums),
        },
        auditLog: {
            create: vi.fn(async (_args: unknown) => ({ id: 'audit' })),
        },
    };
    const db = {
        $transaction: vi.fn(async (fn: (t: unknown) => unknown) => fn(tx)),
    } as unknown as PrismaClient;
    return { db, tx, state, source };
}

type Created = {
    data: {
        reference: string;
        referenceType: string;
        referenceId: string;
        isAutoGenerated: boolean;
        status: string;
        lines: {
            create: Array<{
                accountId: string;
                debit: Prisma.Decimal;
                credit: Prisma.Decimal;
            }>;
        };
    };
};

describe('operational basis correction', () => {
    it('previews read-only and derives the source adjustment accounts', async () => {
        const { db, tx } = fixture();
        const result = await correctOperationalBasis(db, request);
        expect(result).toMatchObject({
            changed: false,
            alreadyApplied: false,
            stockValue: '800.0000',
            basis: '600.00',
            gap: '200.0000',
            amount: '200.00',
            reference: 'ATK-BASIS-CORR:AT222001:OPN-SYNTHETIC',
        });
        expect(result.debitAccount).toMatchObject({ code: '1-130' });
        expect(result.creditAccount).toMatchObject({ code: '8-203' });
        expect(tx.$executeRaw.mock.calls[0][0].join('')).toContain(
            'READ ONLY',
        );
        expect(tx.journalEntry.create).not.toHaveBeenCalled();
    });

    it('posts one SKU-linked delta journal in the source accounts and records the audit', async () => {
        const { db, tx } = fixture();
        const preview = await correctOperationalBasis(db, request);
        const applied = await correctOperationalBasis(
            db,
            {
                ...request,
                expectedFingerprint: preview.fingerprint,
                backupReference: 'verified-backup',
            },
            true,
        );
        expect(applied).toMatchObject({
            changed: true,
            alreadyApplied: false,
            journalId: 'j1',
            auditId: 'audit',
        });
        const created = tx.journalEntry.create.mock.calls[0][0] as Created;
        expect(created.data).toMatchObject({
            reference: 'ATK-BASIS-CORR:AT222001:OPN-SYNTHETIC',
            referenceType: 'STOCK_ADJUSTMENT',
            referenceId: 'm-adj',
            isAutoGenerated: true,
            status: 'POSTED',
        });
        expect(
            created.data.lines.create.map((line) => [
                line.accountId,
                line.debit.toFixed(2),
                line.credit.toFixed(2),
            ]),
        ).toEqual([
            ['inv', '200.00', '0.00'],
            ['exp', '0.00', '200.00'],
        ]);
        expect(tx.auditLog.create.mock.calls[0][0]).toMatchObject({
            data: {
                action: OPERATIONAL_BASIS_CORRECTION_ACTION,
                entityType: 'StockMovement',
                entityId: 'm-adj',
                dedupeKey: `${OPERATIONAL_BASIS_CORRECTION_ACTION}:${preview.reference}`,
            },
        });
        expect(
            tx.$queryRaw.mock.calls.some((call) =>
                call[0].join('?').includes('FOR UPDATE'),
            ),
        ).toBe(true);
    });

    it('fails closed on identity, actor, SKU, movement, source journal, gap, period and balance', async () => {
        const cases: Array<[string, (state: ReturnType<typeof fixture>['state']) => void, Partial<OperationalBasisCorrectionRequest>, string]> = [
            ['database', (s) => { s.identity = 'other'; }, {}, 'Database'],
            ['actor role', (s) => { s.role = 'WAREHOUSE'; }, {}, 'Aktor'],
            ['actor inactive', (s) => { s.active = false; }, {}, 'Aktor'],
            ['product type', (s) => { s.productType = 'RAW_MATERIAL'; }, {}, 'SKU'],
            ['stocked locations', (s) => { s.warehouses[0].quantity = d(0); }, {}, 'lokasi bersaldo'],
            ['movement type', (s) => { s.movement.type = 'OUT'; }, {}, 'Movement'],
            ['source status', (s) => { (s.journals[0] as { status: string }).status = 'DRAFT'; }, {}, 'Jurnal sumber'],
            ['source lines', (s) => { (s.journals[0] as { lines: unknown[] }).lines.pop(); }, {}, '2 baris'],
            ['counter type', (s) => { (s.journals[0] as { lines: Array<{ account: { type: string } }> }).lines[1].account.type = 'LIABILITY'; }, {}, 'beban atau ekuitas'],
            ['amount', (_s) => {}, { amount: '199.00' }, 'Nominal harus sama'],
            ['period', (s) => { s.period = null; }, {}, 'OPEN'],
            ['closed period', (s) => { s.period = { id: 'p', status: 'CLOSED' }; }, {}, 'OPEN'],
            ['counter balance', (s) => { s.counterSums._sum.debit = d(100); }, {}, 'Saldo akun lawan'],
        ];
        for (const [label, mutate, override, message] of cases) {
            const { db, state } = fixture();
            mutate(state);
            await expect(
                correctOperationalBasis(db, { ...request, ...override }),
            ).rejects.toThrow(message);
            expect(label).toBeTruthy();
        }
    });

    it('rejects missing approval evidence and data drift', async () => {
        const { db, state } = fixture();
        const preview = await correctOperationalBasis(db, request);
        await expect(
            correctOperationalBasis(
                db,
                { ...request, expectedFingerprint: preview.fingerprint },
                true,
            ),
        ).rejects.toThrow('backup');
        await expect(
            correctOperationalBasis(db, { ...request, reason: 'short' }),
        ).rejects.toThrow('Alasan');
        // The source journal id is part of the fingerprint but not of the gap checks.
        state.journals = [
            { ...(state.journals[0] as object), id: 'j-other' },
        ];
        await expect(
            correctOperationalBasis(
                db,
                {
                    ...request,
                    expectedFingerprint: preview.fingerprint,
                    backupReference: 'backup',
                },
                true,
            ),
        ).rejects.toThrow('Data berubah');
    });

    it('is idempotent when the correction journal already exists', async () => {
        const { db, tx, state } = fixture();
        state.journals = [
            state.journals[0],
            {
                id: 'j-existing',
                entryNumber: 'JE-EXISTING',
                reference: 'ATK-BASIS-CORR:AT222001:OPN-SYNTHETIC',
                referenceType: 'STOCK_ADJUSTMENT',
                referenceId: 'm-adj',
                status: 'POSTED',
                isAutoGenerated: true,
                createdAt: new Date(),
                lines: [],
            },
        ];
        const preview = await correctOperationalBasis(db, request);
        expect(preview).toMatchObject({
            changed: false,
            alreadyApplied: true,
            existingJournalId: 'j-existing',
        });
        const again = await correctOperationalBasis(
            db,
            {
                ...request,
                expectedFingerprint: preview.fingerprint,
                backupReference: 'backup',
            },
            true,
        );
        expect(again).toMatchObject({
            changed: false,
            alreadyApplied: true,
            existingJournalId: 'j-existing',
        });
        expect(tx.journalEntry.create).not.toHaveBeenCalled();
    });
});

describe('operational basis correction CLI arguments', () => {
    const base = [
        '--tenant=synthetic',
        '--database=synthetic_test',
        '--sku=AT222001',
        '--movement-id=m-adj',
        '--amount=200.00',
        '--posting-date=2026-11-23',
        '--actor-id=u-finance',
        '--reason=Finance-approved basis correction',
    ];
    it('parses preview and confirmed execute modes', () => {
        expect(parseOperationalBasisCorrectionArgs(base)).toMatchObject({
            tenant: 'synthetic',
            execute: false,
            request: {
                database: 'synthetic_test',
                skuCode: 'AT222001',
                amount: '200.00',
            },
        });
        expect(
            parseOperationalBasisCorrectionArgs([
                ...base,
                '--execute',
                '--yes',
                `--fingerprint=${'a'.repeat(64)}`,
                '--backup=bk',
            ]),
        ).toMatchObject({
            execute: true,
            request: { backupReference: 'bk' },
        });
    });
    it('rejects ambiguous or unconfirmed arguments', () => {
        expect(() =>
            parseOperationalBasisCorrectionArgs([...base, '--execute']),
        ).toThrow('--yes');
        expect(() =>
            parseOperationalBasisCorrectionArgs([...base, '--tenant=other']),
        ).toThrow('Exactly one');
        expect(() =>
            parseOperationalBasisCorrectionArgs([...base, '--foo=bar']),
        ).toThrow('Unknown');
        expect(() =>
            parseOperationalBasisCorrectionArgs([
                ...base,
                `--fingerprint=${'a'.repeat(64)}`,
            ]),
        ).toThrow('only with --execute');
    });
});
