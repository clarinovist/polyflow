import { describe, expect, it, vi } from 'vitest';
import { Prisma, type PrismaClient } from '@prisma/client';
import {
    ABSORBED_SCRAP_ACTION, normalizeAbsorbedScrap, scanAbsorbedScrap, type AbsorbedScrapRequest,
} from '../absorbed-scrap-normalization';
import { parseAbsorbedScrapArgs } from '../../../../scripts/normalize-absorbed-scrap';

const at = new Date('2026-10-01T01:00:00Z');
const later = (ms: number) => new Date(at.getTime() + ms);
const d = (value: Prisma.Decimal.Value) => new Prisma.Decimal(value);
const request: AbsorbedScrapRequest = { database: 'synthetic_test', orderId: 'wo', orderNumber: 'WO-SYNTHETIC', actorId: 'system', reason: 'Verified full-absorption legacy scrap' };
type Movement = Record<string, unknown> & { id: string };
const text = (query: TemplateStringsArray | Prisma.Sql) => ('sql' in query ? query.sql : query.join('?'));

function fixture() {
    const movement = (id: string, type: 'IN' | 'OUT', productVariantId: string, quantity: number, cost: number | null, ms: number): Movement => ({
        id, type, productVariantId, quantity: d(quantity), cost: cost == null ? null : d(cost), productionOrderId: 'wo', createdAt: later(ms),
        toLocationId: type === 'IN' ? (productVariantId === 'fg' ? 'fg-store' : 'scrap-store') : null, fromLocationId: type === 'OUT' ? 'raw-store' : null,
        reversalOfId: null, goodsReceiptId: null, salesOrderId: null, companyOwned: null, productionExecutionId: null,
        reference: ['leaf', 'lump'].includes(productVariantId) ? 'Production Scrap: WO-SYNTHETIC' : id,
    });
    // Two material components (one from another WIP pool), one output, two NULL-cost scraps.
    const movements: Movement[] = [movement('issue-a', 'OUT', 'raw', 10, 10, 100), movement('issue-b', 'OUT', 'aux', 4, 10, 120),
        movement('output', 'IN', 'fg', 10, 14, 300), movement('lump-move', 'IN', 'lump', 2, null, 400), movement('leaf-move', 'IN', 'leaf', 2, null, 450)];
    const line = (accountId: string, debit: number, credit: number) => ({ accountId, debit: d(debit), credit: d(credit), currency: 'IDR', exchangeRate: d(1), account: { type: 'ASSET' } });
    const journal = (id: string, lines: ReturnType<typeof line>[]) => ({ id: `j-${id}`, status: 'POSTED', isAutoGenerated: true, referenceId: id, referenceType: 'MANUAL_ENTRY', lines });
    const journals = [journal('issue-a', [line('wip', 100, 0), line('raw-account', 0, 100)]), journal('issue-b', [line('wip-2', 40, 0), line('aux-account', 0, 40)]),
        journal('output', [line('fg-account', 140, 0), line('wip', 0, 100), line('wip-2', 0, 40)])];
    const executions = [
        { id: 'idle', productionOrderId: 'wo', status: 'COMPLETED', endTime: null, createdAt: at, quantityProduced: d(0), scrapQuantity: d(0), scrapProngkolQty: d(0), scrapDaunQty: d(0) },
        { id: 'exec', productionOrderId: 'wo', status: 'COMPLETED', endTime: later(500), createdAt: later(90), quantityProduced: d(10), scrapQuantity: d(4), scrapProngkolQty: d(2), scrapDaunQty: d(2) },
    ];
    const records = ['leaf', 'lump'].map(id => ({ id: `record-${id}`, productionOrderId: 'wo', productionExecutionId: 'exec', productVariantId: id, quantity: d(2), locationId: 'scrap-store' }));
    const inventories = [{ id: 'inv-leaf', productVariantId: 'leaf', locationId: 'scrap-store', quantity: d(40), averageCost: null }, { id: 'inv-lump', productVariantId: 'lump', locationId: 'scrap-store', quantity: d(9), averageCost: d(0) }];
    const order = { id: 'wo', orderNumber: 'WO-SYNTHETIC', status: 'IN_PROGRESS', isMaklon: false, actualPackagingEnabled: false, estimatedConversionCost: d(0), actualQuantity: d(10), bom: { productVariantId: 'fg' } };
    const state = { order, executions, movements, journals, records, inventories, audit: null as unknown, identity: 'synthetic_test', reversals: 0, journalReversals: 0, updated: 1, scrapType: 'SCRAP' };
    const tx = {
        $executeRaw: vi.fn(async (_query: TemplateStringsArray) => 0),
        $queryRaw: vi.fn(async (query: TemplateStringsArray | Prisma.Sql) => {
            const sql = text(query);
            if (sql.includes('current_database')) return [{ name: state.identity }];
            if (sql.includes('DISTINCT')) return [{ id: 'wo', orderNumber: 'WO-SYNTHETIC' }, { id: 'other', orderNumber: 'WO-OTHER' }];
            return [];
        }),
        user: { findUnique: vi.fn().mockResolvedValue({ role: 'FINANCE' }) },
        auditLog: { findUnique: vi.fn(async () => state.audit), create: vi.fn().mockResolvedValue({ id: 'audit' }) },
        productionOrder: { findUnique: vi.fn(async ({ where }) => (where.id === 'wo' ? state.order : null)) },
        productionExecution: { findMany: vi.fn(async () => state.executions) },
        stockMovement: { findMany: vi.fn(async () => state.movements), count: vi.fn(async () => state.reversals), updateMany: vi.fn(async (_args: unknown) => ({ count: state.updated })) },
        journalEntry: { findMany: vi.fn(async () => state.journals), count: vi.fn(async () => state.journalReversals) },
        scrapRecord: { findMany: vi.fn(async () => state.records) },
        productVariant: { findUnique: vi.fn(async () => ({ product: { productType: state.scrapType } })) },
        inventory: { findUnique: vi.fn(async ({ where }) => state.inventories.find(i => i.productVariantId === where.locationId_productVariantId.productVariantId) ?? null) },
    };
    const db = { $transaction: vi.fn(async (fn: (t: unknown) => unknown) => fn(tx)) } as unknown as PrismaClient;
    return { db, tx, state };
}
const preview = (db: PrismaClient) => normalizeAbsorbedScrap(db, request);
const apply = (db: PrismaClient, fingerprint: string) => normalizeAbsorbedScrap(db, { ...request, expectedFingerprint: fingerprint, backupReference: 'verified-backup' }, true);

describe('absorbed legacy scrap normalization', () => {
    it('previews in a read-only transaction, proving full absorption across WIP accounts', async () => {
        const { db, tx } = fixture();
        const result = await preview(db);
        expect(result).toMatchObject({ changed: false, alreadyApplied: false, orderNumber: 'WO-SYNTHETIC', executionId: 'exec', absorbedValue: '140',
            scraps: [{ movementId: 'lump-move', quantity: '2', averageCost: '0' }, { movementId: 'leaf-move', quantity: '2', averageCost: null }] });
        expect(result.fingerprint).toMatch(/^[a-f0-9]{64}$/);
        expect(tx.$executeRaw.mock.calls[0][0].join('')).toContain('READ ONLY');
        expect(tx.stockMovement.updateMany).not.toHaveBeenCalled(); expect(tx.auditLog.create).not.toHaveBeenCalled();
    });
    it('sets only explicit zero cost and execution ownership, with an atomic audit of the originals', async () => {
        const { db, tx } = fixture();
        const { fingerprint } = await preview(db);
        const result = await apply(db, fingerprint);
        expect(result).toMatchObject({ changed: true, auditId: 'audit' });
        expect(tx.stockMovement.updateMany.mock.calls.map(c => c[0])).toEqual(['lump-move', 'leaf-move'].map(id => ({
            where: { id, cost: null, productionExecutionId: null }, data: { cost: 0, companyOwned: true, productionExecutionId: 'exec' } })));
        const audit = tx.auditLog.create.mock.calls[0][0].data;
        expect(audit).toMatchObject({ action: ABSORBED_SCRAP_ACTION, entityType: 'ProductionOrder', entityId: 'wo', dedupeKey: `${ABSORBED_SCRAP_ACTION}:wo` });
        expect(audit.changes).toMatchObject({ fingerprint, backupReference: 'verified-backup', executionId: 'exec', netPhysicalQuantityChange: 0, journalsCreated: 0 });
        expect(audit.changes.originalMovements.map((m: Movement) => [m.id, m.cost, m.productionExecutionId])).toEqual([['lump-move', null, null], ['leaf-move', null, null]]);
        expect(tx.$queryRaw.mock.calls.filter(c => text(c[0]).includes('FOR UPDATE'))).toHaveLength(2);
    });
    it('is idempotent and refuses a different identity on replay', async () => {
        const { db, tx, state } = fixture();
        const { fingerprint } = await preview(db);
        state.audit = { id: 'audit', changes: { orderNumber: 'WO-SYNTHETIC', database: 'synthetic_test', fingerprint } };
        expect(await apply(db, fingerprint)).toEqual({ changed: false, alreadyApplied: true, auditId: 'audit', fingerprint });
        await expect(apply(db, 'f'.repeat(64))).rejects.toThrow('berbeda'); expect(tx.stockMovement.updateMany).not.toHaveBeenCalled();
    });
    it('fails closed on drift, wrong target, missing approval evidence and concurrent writers', async () => {
        const { db, state } = fixture();
        const { fingerprint } = await preview(db);
        state.inventories[0] = { ...state.inventories[0], quantity: d(41) };
        await expect(apply(db, fingerprint)).rejects.toThrow('Data berubah');
        await expect(normalizeAbsorbedScrap(db, { ...request, expectedFingerprint: fingerprint }, true)).rejects.toThrow('backup');
        await expect(normalizeAbsorbedScrap(db, { ...request, reason: 'short' })).rejects.toThrow('wajib');
        const fresh = fixture(); const ok = await preview(fresh.db); fresh.state.updated = 0;
        await expect(apply(fresh.db, ok.fingerprint)).rejects.toThrow('bersamaan');
        fresh.state.identity = 'other_db'; await expect(preview(fresh.db)).rejects.toThrow('Database');
        fresh.state.identity = 'synthetic_test'; fresh.tx.user.findUnique.mockResolvedValue({ role: 'WAREHOUSE' });
        await expect(normalizeAbsorbedScrap(fresh.db, { ...request, actorId: 'warehouse' })).rejects.toThrow('Aktor');
        await expect(normalizeAbsorbedScrap(fresh.db, { ...request, orderId: 'missing' })).rejects.toMatchObject({ code: 'SOURCE_MISMATCH' });
        await expect(normalizeAbsorbedScrap(fresh.db, { ...request, orderNumber: 'WO-OTHER' })).rejects.toMatchObject({ code: 'SOURCE_MISMATCH' });
    });
    it.each([
        ['AFFAL_ONLY_DEFERRED', (s: ReturnType<typeof fixture>['state']) => { s.executions[0] = { ...s.executions[0], scrapDaunQty: d(0.5) }; }],
        ['PARTIAL_ABSORPTION', (s: ReturnType<typeof fixture>['state']) => {
            s.movements[2] = { ...s.movements[2], cost: d(13) };
            s.journals[2] = { ...s.journals[2], lines: s.journals[2].lines.map(l => l.accountId === 'wip-2' ? { ...l, credit: d(30) } : l.accountId === 'fg-account' ? { ...l, debit: d(130) } : l) };
        }],
        ['JOURNALED_SCRAP', (s: ReturnType<typeof fixture>['state']) => { s.journals.push({ ...s.journals[0], id: 'j-leaf', referenceId: 'leaf-move' }); }],
        ['VALUED_SCRAP_STOCK', (s: ReturnType<typeof fixture>['state']) => { s.inventories[0] = { ...s.inventories[0], averageCost: d(55) as never }; }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.order = { ...s.order, actualPackagingEnabled: true }; }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.executions.push({ ...s.executions[1], id: 'voided', status: 'VOIDED' }); }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.executions.push({ ...s.executions[1], id: 'second' }); }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.movements[1] = { ...s.movements[1], reversalOfId: 'x' }; }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.reversals = 1; }],
        ['UNSUPPORTED_HISTORY', (s: ReturnType<typeof fixture>['state']) => { s.journalReversals = 1; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.records.pop(); }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.records[0] = { ...s.records[0], productionExecutionId: 'idle' }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.movements[4] = { ...s.movements[4], createdAt: later(90000) }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.movements[4] = { ...s.movements[4], reference: 'Manual scrap' }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.scrapType = 'RAW_MATERIAL'; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.executions[1] = { ...s.executions[1], scrapDaunQty: d(3) }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.journals[0] = { ...s.journals[0], lines: [s.journals[0].lines[0], { ...s.journals[0].lines[1], currency: 'USD' }] }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.movements[0] = { ...s.movements[0], cost: d(11) }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.journals.splice(1, 1); }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.order = { ...s.order, actualQuantity: d(9) }; }],
        ['SOURCE_MISMATCH', (s: ReturnType<typeof fixture>['state']) => { s.inventories.pop(); }],
    ])('skips %s with a reason instead of normalizing', async (code, mutate) => {
        const { db, state, tx } = fixture(); mutate(state);
        await expect(preview(db)).rejects.toMatchObject({ code });
        expect(tx.stockMovement.updateMany).not.toHaveBeenCalled();
    });
    function withScrapOnlyBatch(state: ReturnType<typeof fixture>['state'], { affalAt = 60000, issueAt = 60100 } = {}) {
        // A later scrap-only entry: 0.5 kg material went entirely to 1 kg of leaf scrap.
        state.executions.push({ id: 'affal', productionOrderId: 'wo', status: 'COMPLETED', endTime: later(affalAt + 500), createdAt: later(affalAt),
            quantityProduced: d(0), scrapQuantity: d(0), scrapProngkolQty: d(0), scrapDaunQty: d(1) });
        state.movements.push({ ...state.movements[0], id: 'issue-r', quantity: d(0.5), createdAt: later(issueAt) },
            { ...state.movements[4], id: 'leaf-affal', quantity: d(1), createdAt: later(affalAt + 200) });
        state.journals.push({ ...state.journals[0], id: 'j-issue-r', referenceId: 'issue-r', lines: state.journals[0].lines.map(l => ({ ...l, debit: l.debit.gt(0) ? d(5) : d(0), credit: l.credit.gt(0) ? d(5) : d(0) })) });
        state.records.push({ id: 'record-affal', productionOrderId: 'wo', productionExecutionId: 'affal', productVariantId: 'leaf', quantity: d(1), locationId: 'scrap-store' });
    }
    const retain = (db: PrismaClient, extra: Partial<AbsorbedScrapRequest> = {}) => normalizeAbsorbedScrap(db, { ...request, retainScrapOnlyResidual: true, ...extra }, Boolean(extra.expectedFingerprint));
    it('keeps a proven scrap-only residual in WIP only when Finance chose that policy', async () => {
        const { db, state, tx } = fixture(); withScrapOnlyBatch(state);
        await expect(preview(db)).rejects.toMatchObject({ code: 'AFFAL_ONLY_DEFERRED' });
        const result = await retain(db);
        expect(result).toMatchObject({ mode: 'RETAIN_SCRAP_ONLY_RESIDUAL', scrapOnlyExecutionId: 'affal', absorbedValue: '140', residualValue: '5' });
        expect('scraps' in result && result.scraps.find(m => m.movementId === 'leaf-affal')?.executionId).toBe('affal');
        await retain(db, { expectedFingerprint: result.fingerprint, backupReference: 'verified-backup' });
        const updates = tx.stockMovement.updateMany.mock.calls.map(c => (c[0] as { where: { id: string }; data: { productionExecutionId: string } }));
        expect(updates.map(u => [u.where.id, u.data.productionExecutionId])).toEqual([['lump-move', 'exec'], ['leaf-move', 'exec'], ['leaf-affal', 'affal']]);
        expect(tx.auditLog.create.mock.calls[0][0].data.changes).toMatchObject({ mode: 'RETAIN_SCRAP_ONLY_RESIDUAL', residualValue: '5', journalsCreated: 0 });
    });
    it.each([
        ['ambiguous material timing', (s: ReturnType<typeof fixture>['state']) => withScrapOnlyBatch(s, { affalAt: 20000, issueAt: 10000 }), 'SOURCE_MISMATCH'],
        ['scrap-only batch without material', (s: ReturnType<typeof fixture>['state']) => { withScrapOnlyBatch(s); s.movements = s.movements.filter(m => m.id !== 'issue-r'); s.journals = s.journals.filter(j => j.id !== 'j-issue-r'); }, 'SOURCE_MISMATCH'],
        ['two scrap-only batches', (s: ReturnType<typeof fixture>['state']) => { withScrapOnlyBatch(s); s.executions.push({ ...s.executions[2], id: 'affal-2' }); }, 'UNSUPPORTED_HISTORY'],
        ['scrap linked to the wrong batch', (s: ReturnType<typeof fixture>['state']) => { withScrapOnlyBatch(s); s.records[2] = { ...s.records[2], productionExecutionId: 'exec' }; }, 'SOURCE_MISMATCH'],
    ])('fails closed on %s in residual mode', async (_name, mutate, code) => {
        const { db, state, tx } = fixture(); mutate(state);
        await expect(retain(db)).rejects.toMatchObject({ code });
        expect(tx.stockMovement.updateMany).not.toHaveBeenCalled();
    });
    it('scans active orders into eligible and skipped without hardcoded order numbers', async () => {
        const { db, tx } = fixture();
        const result = await scanAbsorbedScrap(db, { database: 'synthetic_test' });
        expect(result).toEqual([
            expect.objectContaining({ orderId: 'wo', orderNumber: 'WO-SYNTHETIC', eligible: true, fingerprint: (await preview(db)).fingerprint }),
            { orderId: 'other', orderNumber: 'WO-OTHER', eligible: false, code: 'SOURCE_MISMATCH', reason: expect.any(String) },
        ]);
        expect(tx.stockMovement.updateMany).not.toHaveBeenCalled();
        tx.productionExecution.findMany.mockRejectedValueOnce(new Error('connection lost'));
        await expect(scanAbsorbedScrap(db, { database: 'synthetic_test' })).rejects.toThrow('connection lost');
    });
});

describe('absorbed scrap CLI arguments', () => {
    const base = ['--tenant=synthetic', '--database=synthetic_test'];
    it('parses scan, preview and confirmed execute modes', () => {
        expect(parseAbsorbedScrapArgs([...base, '--scan'])).toEqual({ tenant: 'synthetic', mode: 'scan', database: 'synthetic_test' });
        const order = [...base, '--order-id=wo', '--order-number=WO-1', '--actor-id=system', '--reason=Verified legacy scrap'];
        expect(parseAbsorbedScrapArgs(order)).toMatchObject({ mode: 'order', execute: false, request: { orderId: 'wo', orderNumber: 'WO-1' } });
        expect(parseAbsorbedScrapArgs([...order, '--execute', '--yes', `--fingerprint=${'a'.repeat(64)}`, '--backup=bk'])).toMatchObject({ execute: true, request: { backupReference: 'bk' } });
        expect(parseAbsorbedScrapArgs([...order, '--retain-scrap-only-residual'])).toMatchObject({ request: { retainScrapOnlyResidual: true } });
        expect(parseAbsorbedScrapArgs([...base, '--scan', '--retain-scrap-only-residual'])).toEqual({ tenant: 'synthetic', mode: 'scan', database: 'synthetic_test', retainScrapOnlyResidual: true });
    });
    it('rejects ambiguous or unconfirmed arguments', () => {
        expect(() => parseAbsorbedScrapArgs([...base, '--scan', '--order-id=wo'])).toThrow('--scan');
        expect(() => parseAbsorbedScrapArgs([...base, '--order-id=wo', '--order-id=x'])).toThrow('Exactly one');
        expect(() => parseAbsorbedScrapArgs([...base, '--order-id=wo', '--order-number=W', '--actor-id=s', '--reason=r', '--execute'])).toThrow('--yes');
        expect(() => parseAbsorbedScrapArgs([...base, '--scan', '--execute', '--yes'])).toThrow('--scan');
    });
});
