import { createHash, randomUUID } from 'node:crypto';
import { Prisma, type PrismaClient } from '@prisma/client';

export interface ScrapReconciliationRequest {
    database: string;
    orderId: string;
    orderNumber: string;
    executionId: string;
    actorId: string;
    reason: string;
    expectedFingerprint?: string;
    backupReference?: string;
    valuationAuditId?: string;
}
const action = 'RECONCILE_PRODUCTION_SCRAP';
function fail(message: string): never { throw new Error(message); }
const zero = () => new Prisma.Decimal(0);
function hash(value: unknown): string {
    // JSONB reorders object keys; fingerprint values, not serialization order.
    const canonical = (v: unknown): unknown => Array.isArray(v) ? v.map(canonical)
        : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b)).map(([k, x]) => [k, canonical(x)])) : v;
    return createHash('sha256').update(JSON.stringify(canonical(JSON.parse(JSON.stringify(value))))).digest('hex');
}
type Journal = Prisma.JournalEntryGetPayload<{ include: { lines: { include: { account: true } } } }>;

function validateJournal(journal: Journal, movementId: string) {
    if (journal.status !== 'POSTED' || !journal.isAutoGenerated || journal.referenceType !== 'MANUAL_ENTRY' ||
        journal.referenceId !== movementId || journal.lines.length !== 2) fail('Jurnal sumber tidak tunggal/valid.');
    for (const line of journal.lines) {
        if (line.account.type !== 'ASSET' || line.currency !== 'IDR' || !line.exchangeRate.eq(1) ||
            !line.debit.isFinite() || !line.credit.isFinite() || line.debit.lt(0) || line.credit.lt(0) ||
            line.debit.gt(0) === line.credit.gt(0)) fail('Vektor jurnal sumber tidak valid.');
    }
    const debit = journal.lines.reduce((sum, line) => sum.plus(line.debit), zero());
    if (!debit.gt(0) || !debit.eq(journal.lines.reduce((sum, line) => sum.plus(line.credit), zero()))) fail('Jurnal tidak seimbang.');
    return debit;
}

function object(value: Prisma.JsonValue | undefined): Prisma.JsonObject {
    if (!value || typeof value !== 'object' || Array.isArray(value)) fail('Bukti audit valuasi tidak lengkap.');
    return value as Prisma.JsonObject;
}
function decimal(value: Prisma.JsonValue | undefined): Prisma.Decimal {
    if (typeof value !== 'string' || !new Prisma.Decimal(value).isFinite()) fail('Nilai audit valuasi tidak valid.');
    return new Prisma.Decimal(value);
}

/** Verify a prior correction's post-state and the original source it observed.
 * Only this explicit anchor can prove a pre-correction WAC; current WAC cannot.
 */
async function anchoredValuation(tx: Prisma.TransactionClient, input: ScrapReconciliationRequest,
    movement: Prisma.StockMovementGetPayload<object>, inventory: Prisma.InventoryGetPayload<object>,
    audits: Prisma.AuditLogGetPayload<object>[]) {
    const related = audits.filter(a => {
        const states = object(a.changes).inventoryStates;
        if (!Array.isArray(states)) fail('Bukti audit valuasi tidak lengkap.');
        return states.some(s => object(object(s).inventory).id === inventory.id);
    });
    if (!related.length) {
        if (input.valuationAuditId) fail('Anchor valuasi bukan untuk persediaan ini.');
        return { historicalAverage: inventory.averageCost!, correctionMovementIds: [] as string[], anchor: null };
    }
    if (!input.valuationAuditId || related.length !== 1 || related[0].id !== input.valuationAuditId) fail('Nilai persediaan telah dikoreksi; anchor audit tunggal wajib direview.');
    const audit = related[0], saved = object(audit.changes);
    if (audit.entityType !== 'ProductionExecution' || audit.action !== action || saved.database !== input.database ||
        saved.orderNumber === input.orderNumber || saved.netPhysicalQuantityChange !== 0 ||
        typeof saved.fingerprint !== 'string' || !/^[a-f0-9]{64}$/.test(saved.fingerprint) || audit.createdAt <= movement.createdAt) fail('Identitas anchor valuasi tidak cocok.');
    const states = saved.inventoryStates as Prisma.JsonArray;
    const state = object(states.find(s => object(object(s).inventory).id === inventory.id));
    const before = object(state.inventory);
    if (before.productVariantId !== movement.productVariantId || before.locationId !== movement.toLocationId ||
        !decimal(before.quantity).eq(inventory.quantity) || !decimal(state.newAverage).eq(inventory.averageCost!)) fail('Persediaan berubah sejak anchor valuasi.');
    if (!Array.isArray(state.later) || !state.later.some(s => object(s).id === movement.id && hash(s) === hash(movement))) fail('Sumber tidak tercakup snapshot anchor valuasi.');
    const historicalAverage = state.historicalAverage === undefined ? decimal(before.averageCost) : decimal(state.historicalAverage);
    if (historicalAverage.lt(0) || !Array.isArray(saved.originalMovements)) fail('Nilai historis anchor tidak valid.');
    const priorSource = saved.originalMovements.find(s => object(s).id === state.movementId);
    if (!priorSource || !decimal(object(priorSource).quantity).mul(historicalAverage).eq(decimal(state.removedInflation)) ||
        !decimal(before.quantity).mul(decimal(before.averageCost)).minus(decimal(state.removedInflation))
            .div(decimal(before.quantity)).toDecimalPlaces(4).eq(decimal(state.newAverage))) fail('Perhitungan anchor valuasi tidak sesuai.');
    if (await tx.stockMovement.count({ where: { productVariantId: movement.productVariantId,
        OR: [{ toLocationId: movement.toLocationId }, { fromLocationId: movement.toLocationId }],
        createdAt: { gt: audit.createdAt } } })) fail('Ada mutasi setelah anchor valuasi.');
    if (!Array.isArray(saved.originalMovements) || typeof saved.reversalId !== 'string' || typeof saved.replacementId !== 'string') fail('Sumber anchor valuasi tidak lengkap.');
    const originalJournal = object(saved.originalJournal);
    const originalId = originalJournal.referenceId;
    const old = saved.originalMovements.find(s => object(s).id === originalId);
    if (!old) fail('Sumber jurnal anchor hilang.');
    const original = object(old);
    const pair = await tx.stockMovement.findMany({ where: { id: { in: [saved.reversalId, saved.replacementId] } } });
    const reversal = pair.find(m => m.id === saved.reversalId), replacement = pair.find(m => m.id === saved.replacementId);
    if (!reversal || !replacement || reversal.type !== 'OUT' || replacement.type !== 'IN' ||
        reversal.reversalOfId !== originalId || replacement.reversalOfId || !replacement.cost?.isZero() ||
        reversal.productVariantId !== original.productVariantId || replacement.productVariantId !== original.productVariantId ||
        !reversal.quantity.eq(decimal(original.quantity)) || !replacement.quantity.eq(reversal.quantity) ||
        reversal.fromLocationId !== original.toLocationId || replacement.toLocationId !== original.toLocationId ||
        reversal.productionOrderId !== original.productionOrderId || replacement.productionOrderId !== original.productionOrderId ||
        replacement.productionExecutionId !== audit.entityId || replacement.companyOwned !== true) fail('Pasangan koreksi anchor tidak valid.');
    const sourceJournals = await tx.journalEntry.findMany({ where: { referenceId: { in: [String(originalId), reversal.id] } },
        include: { lines: { include: { account: true } } } });
    const source = sourceJournals.filter(j => j.referenceId === originalId), inverse = sourceJournals.filter(j => j.referenceId === reversal.id);
    if (source.length !== 1 || inverse.length !== 1 || source[0].id !== originalJournal.id || inverse[0].id !== saved.reversalJournalId) fail('Jurnal anchor tidak lengkap.');
    validateJournal(source[0], String(originalId)); validateJournal(inverse[0], reversal.id);
    const vector = (j: Journal, invert: boolean) => j.lines.map(l => [l.accountId, l.currency, l.exchangeRate.toString(),
        (invert ? l.credit : l.debit).toString(), (invert ? l.debit : l.credit).toString()].join('|')).sort().join(';');
    if (vector(source[0], true) !== vector(inverse[0], false)) fail('Jurnal pembalik anchor tidak sesuai sumber.');
    return { historicalAverage, correctionMovementIds: pair.filter(m => m.productVariantId === movement.productVariantId).map(m => m.id),
        anchor: { id: audit.id, changes: saved, createdAt: audit.createdAt } };
}

/** Explicit operator-only repair of a proven first-output legacy scrap defect.
 * Never called by output posting. No quantities, master costs or old journals are
 * edited. Dry-run is transaction-read-only; apply requires its exact fingerprint.
 */
export async function reconcileProductionScrap(db: PrismaClient, input: ScrapReconciliationRequest, execute = false) {
    if (!input.database || !input.orderId || !input.orderNumber || !input.executionId || !input.actorId || input.reason.trim().length < 12) {
        fail('Identitas/bukti koreksi wajib lengkap.');
    }
    if (execute && (!/^[a-f0-9]{64}$/.test(input.expectedFingerprint ?? '') || !input.backupReference?.trim())) {
        fail('Eksekusi wajib fingerprint dry-run dan referensi backup terverifikasi.');
    }
    return db.$transaction(async tx => {
        if (!execute) await tx.$executeRaw`SET TRANSACTION READ ONLY`;
        const [identity] = await tx.$queryRaw<Array<{ name: string }>>`SELECT current_database() AS name`;
        if (identity.name !== input.database) fail('Database bukan target yang disetujui.');
        const actor = await tx.user.findUnique({ where: { id: input.actorId }, select: { role: true } });
        if (!actor || (input.actorId !== 'system' && !['ADMIN', 'FINANCE'].includes(actor.role))) fail('Aktor koreksi tidak diizinkan.');
        if (execute) await tx.$queryRaw`SELECT id FROM "ProductionOrder" WHERE id = ${input.orderId} FOR UPDATE`;
        const dedupeKey = `${action}:${input.orderId}:${input.executionId}`;
        const previous = await tx.auditLog.findUnique({ where: { dedupeKey } });
        if (previous) {
            const saved = previous.changes as Prisma.JsonObject | null;
            if (!saved || saved.orderNumber !== input.orderNumber || saved.database !== input.database ||
                (execute && saved.fingerprint !== input.expectedFingerprint)) fail('Identitas koreksi terdahulu berbeda.');
            return { changed: false, alreadyApplied: true, auditId: previous.id, fingerprint: String(saved.fingerprint) };
        }
        const order = await tx.productionOrder.findUniqueOrThrow({ where: { id: input.orderId }, include: { bom: true } });
        if (order.orderNumber !== input.orderNumber || order.isMaklon || order.actualPackagingEnabled ||
            order.status !== 'IN_PROGRESS' || (order.estimatedConversionCost && !order.estimatedConversionCost.isZero())) fail('Jenis/status WO di luar koreksi terbatas.');
        const execution = await tx.productionExecution.findUniqueOrThrow({ where: { id: input.executionId } });
        const positiveExecutions = await tx.productionExecution.count({ where: { productionOrderId: order.id, status: { not: 'VOIDED' }, quantityProduced: { gt: 0 } } });
        if (execution.productionOrderId !== order.id || execution.status !== 'COMPLETED' || !execution.endTime ||
            !execution.quantityProduced.gt(0) || !order.actualQuantity?.eq(execution.quantityProduced) || positiveExecutions !== 1) fail('Bukan hasil pertama tunggal yang terverifikasi.');
        const movements = await tx.stockMovement.findMany({ where: { productionOrderId: order.id }, orderBy: [{ createdAt: 'asc' }, { id: 'asc' }] });
        if (movements.length !== 4 || movements.some(m => m.reversalOfId || m.goodsReceiptId || m.salesOrderId || m.companyOwned === false ||
            m.productionExecutionId || !m.quantity.gt(0) || !['IN', 'OUT'].includes(m.type))) fail('Riwayat movement WO tidak sesuai pola koreksi.');
        const issues = movements.filter(m => m.type === 'OUT');
        const outputs = movements.filter(m => m.type === 'IN' && m.productVariantId === order.bom.productVariantId);
        const scraps = movements.filter(m => m.type === 'IN' && m.productVariantId !== order.bom.productVariantId);
        if (issues.length !== 1 || outputs.length !== 1 || scraps.length !== 2 || !outputs[0].quantity.eq(execution.quantityProduced) ||
            issues[0].cost == null || outputs[0].cost == null) fail('Sumber bahan/hasil tidak lengkap.');
        for (const m of [issues[0], outputs[0]]) {
            const variant = await tx.productVariant.findUniqueOrThrow({ where: { id: m.productVariantId } });
            if (variant.primaryUnit !== 'KG') fail('Satuan bahan/hasil bukan KG.');
        }
        const reportedScrap = [execution.scrapProngkolQty, execution.scrapDaunQty].map(q => q.toString()).sort();
        if (!execution.scrapQuantity.isZero() || reportedScrap.join('|') !== scraps.map(m => m.quantity.toString()).sort().join('|')) {
            fail('Rincian affal eksekusi tidak sesuai sumber.');
        }
        const scrapRecords = await tx.scrapRecord.findMany({ where: { productionOrderId: order.id }, orderBy: { id: 'asc' } });
        if (scrapRecords.length !== 2 || new Set(scraps.map(m => m.productVariantId)).size !== 2 ||
            !issues[0].quantity.eq(outputs[0].quantity.plus(scraps.reduce((sum, m) => sum.plus(m.quantity), zero())))) fail('Rekonsiliasi kuantitas sumber gagal.');
        for (const m of scraps) {
            const variant = await tx.productVariant.findUniqueOrThrow({ where: { id: m.productVariantId }, include: { product: true } });
            const records = scrapRecords.filter(s => s.productVariantId === m.productVariantId && s.quantity.eq(m.quantity) &&
                s.locationId === m.toLocationId && s.productionExecutionId === execution.id);
            if (variant.product.productType !== 'SCRAP' || variant.primaryUnit !== 'KG' || m.cost !== null || !m.toLocationId || m.fromLocationId ||
                m.reference !== `Production Scrap: ${order.orderNumber}` || records.length !== 1 ||
                Math.abs(m.createdAt.getTime() - execution.createdAt.getTime()) > 30000) fail('Atribusi scrap historis tidak terbukti.');
        }
        if (execute) await tx.$queryRaw(Prisma.sql`SELECT id FROM "JournalEntry" WHERE "referenceId" IN (${Prisma.join(movements.map(m => m.id))}) ORDER BY id FOR UPDATE`);
        const journals = await tx.journalEntry.findMany({ where: { referenceId: { in: movements.map(m => m.id) } },
            include: { lines: { include: { account: true }, orderBy: { id: 'asc' } } }, orderBy: { id: 'asc' } });
        const forMove = (id: string) => journals.filter(j => j.referenceId === id);
        const issueJ = forMove(issues[0].id), outputJ = forMove(outputs[0].id);
        if (issueJ.length !== 1 || outputJ.length !== 1 || journals.length !== 3) fail('Jumlah jurnal sumber tidak sesuai.');
        const issueValue = validateJournal(issueJ[0], issues[0].id), outputValue = validateJournal(outputJ[0], outputs[0].id);
        if (!issueValue.eq(outputValue) || !issueValue.eq(issues[0].quantity.mul(issues[0].cost!).toDecimalPlaces(2)) ||
            issueJ[0].lines.find(l => l.debit.gt(0))!.accountId !== outputJ[0].lines.find(l => l.credit.gt(0))!.accountId) fail('Biaya bahan belum seluruhnya terserap hasil.');
        const journaled = scraps.filter(m => forMove(m.id).length === 1);
        const missing = scraps.filter(m => forMove(m.id).length === 0);
        if (journaled.length !== 1 || missing.length !== 1) fail('Pola jurnal affal tidak sesuai.');
        const original = journaled[0], originalJournal = forMove(original.id)[0];
        const reversedAmount = validateJournal(originalJournal, original.id);
        if (await tx.journalEntry.count({ where: { referenceId: { in: journals.map(j => j.id) } } }) ||
            await tx.stockMovement.count({ where: { reversalOfId: { in: movements.map(m => m.id) } } })) fail('Sumber telah dibalik.');
        const inventoryStates = [];
        for (const m of [...scraps].sort((a, b) => a.productVariantId.localeCompare(b.productVariantId))) {
            if (execute) await tx.$queryRaw`SELECT id FROM "Inventory" WHERE "locationId"=${m.toLocationId} AND "productVariantId"=${m.productVariantId} FOR UPDATE`;
            const inventory = await tx.inventory.findUniqueOrThrow({ where: { locationId_productVariantId: { locationId: m.toLocationId!, productVariantId: m.productVariantId } } });
            if (!inventory.averageCost?.isFinite() || inventory.averageCost.lt(0) || inventory.quantity.lt(m.quantity)) fail('Snapshot persediaan tidak valid.');
            const valuationCorrections = await tx.auditLog.findMany({ where: { action, createdAt: { gte: m.createdAt } }, take: 101 });
            if (valuationCorrections.length > 100) fail('Riwayat koreksi melebihi batas review.');
            const valuation = await anchoredValuation(tx, input, m, inventory, valuationCorrections);
            const later = await tx.stockMovement.findMany({ where: { productVariantId: m.productVariantId,
                OR: [{ toLocationId: m.toLocationId }, { fromLocationId: m.toLocationId }], createdAt: { gte: m.createdAt }, id: { notIn: [m.id, ...valuation.correctionMovementIds] } },
                orderBy: [{ createdAt: 'asc' }, { id: 'asc' }], take: 101 });
            if (later.length > 100) fail('Riwayat lanjutan melebihi batas review.');
            for (const next of later) {
                if (next.type !== 'IN' || next.fromLocationId || next.toLocationId !== m.toLocationId || next.cost !== null ||
                    next.reversalOfId || !next.productionOrderId || next.productionExecutionId || next.goodsReceiptId || next.salesOrderId ||
                    !next.quantity.gt(0) || !next.reference?.startsWith('Production Scrap: ')) fail('Ada transaksi lanjutan bukan penerimaan affal legacy; review terpisah diperlukan.');
                const sourceRecord = await tx.scrapRecord.findMany({ where: { productionOrderId: next.productionOrderId,
                    productVariantId: next.productVariantId, locationId: next.toLocationId, quantity: next.quantity }, include: { productionExecution: true } });
                if (!sourceRecord.some(s => s.productionExecution?.status === 'COMPLETED' &&
                    Math.abs(s.recordedAt.getTime() - next.createdAt.getTime()) < 30000)) fail('Bukti penerimaan affal lanjutan tidak lengkap.');
            }
            const historicalQty = inventory.quantity.minus(later.reduce((sum, next) => sum.plus(next.quantity), zero()));
            if (historicalQty.lt(m.quantity)) fail('Kuantitas historis tidak dapat direkonstruksi.');
            const removedInflation = m.quantity.mul(valuation.historicalAverage);
            const remainingValue = inventory.quantity.mul(inventory.averageCost).minus(removedInflation);
            if (remainingValue.lt(0)) fail('Nilai persediaan tidak cukup untuk koreksi sumber.');
            const newAverage = inventory.quantity.isZero() ? zero() : remainingValue.div(inventory.quantity).toDecimalPlaces(4);
            inventoryStates.push({ movementId: m.id, inventory, later, historicalQty, removedInflation, newAverage,
                historicalAverage: valuation.historicalAverage, valuationAnchor: valuation.anchor });
        }
        const now = new Date();
        const period = await tx.fiscalPeriod.findFirst({ where: { startDate: { lte: now }, endDate: { gte: new Date(now.toISOString().slice(0, 10)) }, status: 'OPEN' }, orderBy: { startDate: 'desc' } });
        if (!period) fail('Periode koreksi tidak OPEN.');
        const stockLine = originalJournal.lines.find(l => l.debit.gt(0))!;
        const sums = await tx.journalLine.aggregate({ where: { accountId: stockLine.accountId, journalEntry: { status: 'POSTED' } }, _sum: { debit: true, credit: true } });
        if (new Prisma.Decimal(sums._sum.debit ?? 0).minus(sums._sum.credit ?? 0).lt(reversedAmount)) fail('Saldo sumber tidak cukup untuk inverse jurnal.');
        const fingerprint = hash({ database: identity.name, order, execution, movements, scrapRecords, journals, inventoryStates, period });
        const preview = { changed: false, alreadyApplied: false, fingerprint, orderNumber: order.orderNumber,
            quantityProduced: order.actualQuantity!.toString(), reverseAmount: reversedAmount.toString(),
            inventory: inventoryStates.map(s => ({ movementId: s.movementId, quantity: s.inventory.quantity.toString(),
                oldAverage: s.inventory.averageCost!.toString(), newAverage: s.newAverage.toString(), removedInflation: s.removedInflation.toString() })) };
        if (!execute) return preview;
        if (fingerprint !== input.expectedFingerprint) fail('Data berubah setelah dry-run; tidak ada koreksi diterapkan.');
        const reversal = await tx.stockMovement.create({ data: { type: 'OUT', productVariantId: original.productVariantId,
            fromLocationId: original.toLocationId, quantity: original.quantity, cost: original.cost,
            productionOrderId: order.id, reversalOfId: original.id, createdById: input.actorId,
            reference: `VOID: ${original.reference} [cost reconciliation]` } });
        const replacement = await tx.stockMovement.create({ data: { type: 'IN', productVariantId: original.productVariantId,
            toLocationId: original.toLocationId, quantity: original.quantity, cost: 0, companyOwned: true,
            productionOrderId: order.id, productionExecutionId: execution.id, createdById: input.actorId,
            reference: `Production Scrap Reconciled: ${order.orderNumber}` } });
        const reverseJournal = await tx.journalEntry.create({ data: {
            entryNumber: `JE-SCRAP-REC-${randomUUID()}`, entryDate: now, status: 'POSTED', isAutoGenerated: true,
            referenceType: 'MANUAL_ENTRY', referenceId: reversal.id, reference: reversal.reference,
            description: `Exact inverse of ${originalJournal.entryNumber}: duplicate scrap cost`,
            createdById: input.actorId, approvedById: input.actorId, approvedAt: now,
            lines: { create: originalJournal.lines.map(l => ({ accountId: l.accountId, debit: l.credit, credit: l.debit,
                currency: l.currency, exchangeRate: l.exchangeRate, description: `Reconcile ${originalJournal.entryNumber}` })) },
        } });
        await tx.stockMovement.update({ where: { id: missing[0].id }, data: { cost: 0, companyOwned: true, productionExecutionId: execution.id } });
        for (const s of inventoryStates) await tx.inventory.update({ where: { id: s.inventory.id }, data: { averageCost: s.newAverage } });
        const audit = await tx.auditLog.create({ data: { userId: input.actorId, action, entityType: 'ProductionExecution',
            entityId: execution.id, dedupeKey, details: input.reason,
            changes: JSON.parse(JSON.stringify({ database: input.database, orderNumber: input.orderNumber, fingerprint,
                backupReference: input.backupReference, originalMovements: scraps, originalJournal,
                inventoryStates, reversalId: reversal.id, replacementId: replacement.id, reversalJournalId: reverseJournal.id,
                quantityProduced: order.actualQuantity, netPhysicalQuantityChange: 0 })) as Prisma.InputJsonObject,
        } });
        return { ...preview, changed: true, auditId: audit.id, reversalJournalId: reverseJournal.id };
    }, { isolationLevel: Prisma.TransactionIsolationLevel.Serializable, timeout: 30000 });
}
